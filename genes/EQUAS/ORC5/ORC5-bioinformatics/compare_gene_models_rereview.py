"""Compare all donkey ORC5 UniProt entries against human, mouse and horse ORC5.

Fetches sequences live from UniProt REST, aligns each to human O43913 globally,
and reports identity, coverage and the C-terminal 20 residues, to decide
whether the benchmark accession A0A9L0JAR4 carries the canonical ORC5 C-terminus.
Writes RESULTS-rereview.md and results-rereview.json next to this script.
"""
import json
from pathlib import Path

import requests
from Bio import Align
from Bio.Align import substitution_matrices

HERE = Path(__file__).parent
REFS = {"O43913": "human", "Q9WUV0": "mouse", "A0A3Q2KSP7": "horse"}
TARGET = "A0A9L0JAR4"


def fetch(acc: str) -> dict:
    r = requests.get(f"https://rest.uniprot.org/uniprotkb/{acc}.json", timeout=60)
    r.raise_for_status()
    d = r.json()
    proteome = [x["id"] for x in d.get("uniProtKBCrossReferences", []) if x["database"] == "Proteomes"]
    ens = [x for x in d.get("uniProtKBCrossReferences", []) if x["database"] == "Ensembl"]
    genes = sorted({p["value"] for x in ens for p in x.get("properties", []) if p["key"] == "GeneId"})
    return {"acc": acc, "seq": d["sequence"]["value"], "proteome": proteome,
            "ensembl": [x["id"] for x in ens], "ensembl_gene": genes}


def donkey_accessions() -> list[str]:
    r = requests.get(
        "https://rest.uniprot.org/uniprotkb/search",
        params={"query": "gene:ORC5 AND organism_id:9793", "fields": "accession", "format": "tsv"},
        timeout=60,
    )
    r.raise_for_status()
    return sorted(line for line in r.text.splitlines()[1:] if line)


def aligner() -> Align.PairwiseAligner:
    a = Align.PairwiseAligner()
    a.mode = "global"
    a.substitution_matrix = substitution_matrices.load("BLOSUM62")
    a.open_gap_score = -10
    a.extend_gap_score = -0.5
    a.end_gap_score = 0
    return a


def compare(al, ref: str, q: str) -> dict:
    aln = al.align(ref, q)[0]
    ident = paired = 0
    for (rs, re_), (qs, qe) in zip(*aln.aligned):
        for i, j in zip(range(rs, re_), range(qs, qe)):
            paired += 1
            ident += ref[i] == q[j]
    return {
        "paired": paired,
        "identity_pct": round(100 * ident / paired, 2) if paired else 0.0,
        "ref_coverage_pct": round(100 * paired / len(ref), 2),
    }


def main() -> None:
    al = aligner()
    human = fetch("O43913")
    rows = []
    accs = list(REFS) + [a for a in donkey_accessions() if a not in REFS]
    for acc in accs:
        e = human if acc == "O43913" else fetch(acc)
        c = compare(al, human["seq"], e["seq"])
        rows.append({
            "acc": acc,
            "label": REFS.get(acc, "donkey"),
            "length": len(e["seq"]),
            "proteome": e["proteome"],
            "ensembl": e["ensembl"],
            "ensembl_gene": e["ensembl_gene"],
            "c_terminal_20": e["seq"][-20:],
            "has_human_c_terminal_motif_YLYDFL": "YLYDFL" in e["seq"][-30:],
            **c,
        })
    (HERE / "results-rereview.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = [
        "# ORC5 donkey gene models vs human/mouse/horse ORC5 (re-review)",
        "",
        "Generated by `uv run --script compare_gene_models_rereview.py` (UniProt REST, live).",
        "Global alignment to human O43913, BLOSUM62, gap open -10, extend -0.5, free end gaps.",
        "",
        "| accession | source | length | identity to human (%) | human coverage (%) | C-terminal 20 aa | human-type C-terminus (YLYDFL) | proteome | Ensembl gene |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['acc']} | {r['label']} | {r['length']} | {r['identity_pct']} | {r['ref_coverage_pct']} | "
            f"{r['c_terminal_20']} | {r['has_human_c_terminal_motif_YLYDFL']} | {','.join(r['proteome'])} | {','.join(r['ensembl_gene'])} |"
        )
    t = next(r for r in rows if r["acc"] == TARGET)
    lines += [
        "",
        f"Benchmark accession {TARGET}: length {t['length']}, identity {t['identity_pct']}% to human over "
        f"{t['paired']} paired residues; C-terminus {t['c_terminal_20']}; human-type C-terminus present: "
        f"{t['has_human_c_terminal_motif_YLYDFL']}.",
    ]
    tseq = fetch(TARGET)["seq"]
    hseq = human["seq"]
    lines += [
        "",
        f"Human ORC5 Walker A (residues 37-44) {hseq[36:44]} vs {TARGET} {tseq[36:44]}; "
        f"human DNA-proximal beta-hairpin H398 vs {TARGET} residue 398 {tseq[397]}.",
        f"Residues 1-420: {sum(a == b for a, b in zip(hseq[:420], tseq[:420]))}/420 identical to human; "
        f"human 421-435 {hseq[420:]} vs {TARGET} 421-440 {tseq[420:]}.",
    ]
    (HERE / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
