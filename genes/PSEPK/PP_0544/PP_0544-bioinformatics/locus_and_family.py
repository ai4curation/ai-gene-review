"""Fetch family-model descriptions and genomic neighbourhood for PP_0544 (Q88QF0).

Reproducible, stdlib only. Writes RESULTS.md next to this script from live
InterPro and UniProt REST responses; nothing is hard-coded except the queries.

Usage: python3 -I locus_and_family.py
"""
import json
import re
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent


def get(url, as_json=True):
    with urllib.request.urlopen(url, timeout=60) as r:
        data = r.read().decode()
    return json.loads(data) if as_json else data


def strip_html(s):
    return re.sub(r"<[^>]+>", "", s).strip()


def entry(db, acc):
    m = get(f"https://www.ebi.ac.uk/interpro/api/entry/{db}/{acc}/")["metadata"]
    desc = " ".join(strip_html(d["text"]) for d in (m.get("description") or []))
    return m["name"]["name"], m["type"], desc


def neighbours(kt_from=540, kt_to=548):
    genes = "+OR+".join(f"gene:PP_{i:04d}" for i in range(kt_from, kt_to + 1))
    url = (
        "https://rest.uniprot.org/uniprotkb/search?query=proteome:UP000000556+AND+("
        + genes
        + ")&fields=accession,gene_oln,protein_name,xref_interpro,xref_panther&format=tsv"
    )
    rows = [r.split("\t") for r in get(url, as_json=False).strip().splitlines()]
    header, body = rows[0], rows[1:]
    body.sort(key=lambda r: r[1])
    return header, body


def sf7_members():
    """PTHR42770:SF7 Swiss-Prot members plus P. aeruginosa Eat (PA4023): which carry IPR004757?"""
    q = ("(reviewed:true+AND+accession:P9WQM3)+OR+accession:P63350+OR+accession:O87394"
         "+OR+accession:P75597+OR+accession:P9WQM2+OR+accession:Q8QL47"
         "+OR+(gene:PA4023+AND+organism_id:208964)+OR+accession:Q88QF0")
    url = ("https://rest.uniprot.org/uniprotkb/search?query=" + q +
           "&fields=accession,gene_oln,protein_name,xref_interpro,xref_panther,xref_ncbifam&format=tsv")
    rows = [r.split("\t") for r in get(url, as_json=False).strip().splitlines()]
    return rows[0], sorted(rows[1:])


def main():
    out = ["# PP_0544 family-model and locus analysis", ""]
    out.append("Generated by `locus_and_family.py` from InterPro and UniProt REST APIs.")
    out.append("")
    out.append("## Family models matching Q88QF0")
    out.append("")
    for db, acc in [("ncbifam", "TIGR00908"), ("interpro", "IPR004757"), ("panther", "PTHR42770")]:
        name, typ, desc = entry(db, acc)
        out.append(f"- {db} {acc}: {name} (type {typ})")
        if desc:
            out.append(f"  - description: {desc}")
    out.append("")
    out.append("## Genomic neighbourhood (KT2440 PP_0540-PP_0548, UniProt)")
    out.append("")
    header, body = neighbours()
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    for r in body:
        out.append("| " + " | ".join(c.replace("|", "/") for c in r) + " |")
    out.append("")
    out.append("## PTHR42770:SF7 members: IPR004757 / TIGR00908 coverage")
    out.append("")
    header, body = sf7_members()
    out.append("| " + " | ".join(header) + " | IPR004757 |")
    out.append("|" + "---|" * (len(header) + 1))
    for r in body:
        has = "yes" if "IPR004757" in "".join(r) else "no"
        out.append("| " + " | ".join(c.replace("|", "/") for c in r) + f" | {has} |")
    out.append("")
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
