#!/usr/bin/env python
"""Test whether PP_5147 (Q88CN3) is the KT2440 ortholog of the P. aeruginosa HolPase PA0335.

Run from the repository root:

    python genes/PSEPK/PP_5147/PP_5147-bioinformatics/holpase_orthology.py --cache-dir <dir>

Steps (inputs downloaded at run time; only identifiers are fixed):
1. NCBIfam HMM NF052360 (HolPasePseu, an equivalog built on PMID:31862725) is searched with
   pyhmmer hmmsearch against the complete UniProt proteomes of P. putida KT2440 (UP000000556)
   and P. aeruginosa PAO1 (UP000002438); scores are compared with the model's trusted cutoff.
2. Reciprocal best hits: phmmer of PA0335 (Q9I6F6) against KT2440 and of PP_5147 (Q88CN3)
   against PAO1.
3. Local BLOSUM62 alignment of PA0335 and PP_5147, reporting identity and the residues aligned
   to the PA0335 HAD catalytic positions annotated in Swiss-Prot (Asp7 nucleophile, Asp9 proton
   donor, Asp179 Mg2+ ligand), read from the cached UniProt record.
Requires biopython and pyhmmer. Writes RESULTS.md and results/*.tsv next to this script.
"""
import argparse
import re
import urllib.request
from pathlib import Path

import pyhmmer
from Bio.Align import PairwiseAligner, substitution_matrices

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
HMM_URL = "https://ftp.ncbi.nlm.nih.gov/hmm/current/hmm_PGAP.HMM/{}.HMM"
PROTEOME_URL = "https://rest.uniprot.org/uniprotkb/stream?query=proteome:{}&format=fasta"
PROTEOMES = {"KT2440": "UP000000556", "PAO1": "UP000002438"}
HMM = "NF052360.1"
PA0335, PP5147 = "Q9I6F6", "Q88CN3"
PA0335_UNIPROT = REPO / "genes/PSEAE/PA0335/PA0335-uniprot.txt"


def fetch(url, path):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url) as r:
            path.write_bytes(r.read())
    return path


def name(x):
    return x.decode() if isinstance(x, bytes) else x


def acc_of(n):
    parts = n.split("|")
    return parts[1] if len(parts) > 2 else n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache-dir", type=Path, required=True)
    args = ap.parse_args()
    abc = pyhmmer.easel.Alphabet.amino()
    blocks, text = {}, {}
    for org, up in PROTEOMES.items():
        fa = fetch(PROTEOME_URL.format(up), args.cache_dir / f"{up}.fasta")
        with pyhmmer.easel.SequenceFile(str(fa), digital=True, alphabet=abc) as sf:
            blocks[org] = sf.read_block()
        with pyhmmer.easel.SequenceFile(str(fa), digital=False) as sf:
            for s in sf:
                text[acc_of(name(s.name))] = s.sequence
    with pyhmmer.plan7.HMMFile(str(fetch(HMM_URL.format(HMM), args.cache_dir / f"{HMM}.HMM"))) as hf:
        hmm = hf.read()
    tc = hmm.cutoffs.trusted[0]
    hmm_rows = []
    for org, blk in blocks.items():
        for hits in pyhmmer.hmmsearch([hmm], blk, E=1e-5):
            for h in hits:
                hmm_rows.append((org, acc_of(name(h.name)), h.score, h.score >= tc))

    def best(query_acc, org):
        q = next(s for s in blocks["PAO1" if org == "KT2440" else "KT2440"]
                 if acc_of(name(s.name)) == query_acc)
        q = pyhmmer.easel.DigitalSequence(abc, name=q.name, sequence=q.sequence)
        res = []
        for hits in pyhmmer.phmmer([q], blocks[org], E=1e-5):
            for h in hits:
                res.append((acc_of(name(h.name)), h.score))
        res.sort(key=lambda x: -x[1])
        return res[:3]

    fwd = best(PA0335, "KT2440")
    rev = best(PP5147, "PAO1")
    rbh = bool(fwd and rev and fwd[0][0] == PP5147 and rev[0][0] == PA0335)

    al = PairwiseAligner(mode="local")
    al.substitution_matrix = substitution_matrices.load("BLOSUM62")
    al.open_gap_score, al.extend_gap_score = -10, -0.5
    a, b = text[PA0335], text[PP5147]
    aln = al.align(a, b)[0]
    mp, ident, cols = {}, 0, 0
    for (s1, e1), (s2, e2) in zip(*aln.aligned):
        for i, j in zip(range(s1, e1), range(s2, e2)):
            mp[i + 1] = (b[j], j + 1)
            cols += 1
            ident += a[i] == b[j]
    ft = PA0335_UNIPROT.read_text()
    sites = sorted({int(m) for m in re.findall(r"FT   (?:ACT_SITE|BINDING)\s+(\d+)\n", ft)})

    (HERE / "results").mkdir(exist_ok=True)
    with open(HERE / "results" / "nf052360_hits.tsv", "w") as f:
        f.write("proteome\ttarget\tbitscore\ttrusted_cutoff\tabove_tc\n")
        for o, t, s, ok in hmm_rows:
            f.write(f"{o}\t{t}\t{s:.1f}\t{tc:.1f}\t{'yes' if ok else 'no'}\n")
    L = ["# PP_5147 (Q88CN3) orthology to PA0335 - generated by holpase_orthology.py", "",
         "Generated output; do not edit by hand. Re-run the script to regenerate.", "",
         f"## NF052360 (HolPasePseu) hmmsearch, trusted cutoff {tc:.1f}", "",
         "| proteome | target | bitscore | above TC |", "|---|---|---|---|"]
    for o, t, s, ok in hmm_rows:
        L.append(f"| {o} | {t} | {s:.1f} | {'yes' if ok else 'no'} |")
    L += ["", "## Reciprocal best hits (phmmer bitscores)", "",
          f"- PA0335 ({PA0335}) vs KT2440 proteome, top hits: " + ", ".join(f"{x} ({s:.1f})" for x, s in fwd),
          f"- PP_5147 ({PP5147}) vs PAO1 proteome, top hits: " + ", ".join(f"{x} ({s:.1f})" for x, s in rev),
          f"- Reciprocal best hit PA0335 <-> PP_5147: {'yes' if rbh else 'no'}", "",
          "## Pairwise alignment PA0335 vs PP_5147", "",
          f"- Identity over {cols} aligned columns: {ident / cols:.3f} (PA0335 length {len(a)}, PP_5147 length {len(b)})",
          "- Residues aligned to PA0335 catalytic/Mg2+ positions (from the Swiss-Prot FT lines): "
          + ", ".join(f"PA0335 {a[p - 1]}{p} -> PP_5147 {mp[p][0]}{mp[p][1]}" if p in mp else f"PA0335 {a[p - 1]}{p} -> gap"
                      for p in sites)]
    above = [t for o, t, s, ok in hmm_rows if ok and o == "KT2440"]
    L.append(f"- KT2440 proteins above the NF052360 trusted cutoff: {', '.join(above) or 'none'}")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
