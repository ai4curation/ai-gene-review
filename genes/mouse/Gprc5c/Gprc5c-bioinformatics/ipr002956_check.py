"""Check what InterPro IPR002956 (Bride of sevenless) matches, and where it hits Gprc5c.

Queries the public InterPro REST API (no key needed) and prints a Markdown report.
Usage: python3 ipr002956_check.py > RESULTS.md
"""
import json
import urllib.parse
import urllib.request

API = "https://www.ebi.ac.uk/interpro/api"
UNIPROT = "https://rest.uniprot.org/uniprotkb/search"
# Related InterPro entries whose names are cited alongside IPR002956
NAMED_ENTRIES = ["IPR050726", "IPR051753", "IPR037893"]
# UniProtKB breakdowns of the IPR002956 membership
BREAKDOWN = {
    "all IPR002956": "xref:interpro-IPR002956",
    "vertebrates (taxon 7742)": "xref:interpro-IPR002956 AND taxonomy_id:7742",
    "arthropods (taxon 6656)": "xref:interpro-IPR002956 AND taxonomy_id:6656",
    "insects (taxon 50557)": "xref:interpro-IPR002956 AND taxonomy_id:50557",
    "bacteria (taxon 2)": "xref:interpro-IPR002956 AND taxonomy_id:2",
    "also IPR051753 (GPRC5 family)": "xref:interpro-IPR002956 AND xref:interpro-IPR051753",
    "also IPR051753, vertebrates": "xref:interpro-IPR002956 AND xref:interpro-IPR051753 AND taxonomy_id:7742",
    "also IPR050726": "xref:interpro-IPR002956 AND xref:interpro-IPR050726",
    "also IPR050726, vertebrates": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 AND taxonomy_id:7742",
    "also IPR050726, arthropods": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 AND taxonomy_id:6656",
    "also IPR050726, not arthropods": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 NOT taxonomy_id:6656",
    "also IPR050726, insects": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 AND taxonomy_id:50557",
    "also IPR050726, bacteria": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 AND taxonomy_id:2",
    "also IPR050726 and IPR051753": "xref:interpro-IPR002956 AND xref:interpro-IPR050726 AND xref:interpro-IPR051753",
}
TARGET = "Q8K3J9"  # mouse Gprc5c
# GPRC5 family members and Drosophila BOSS for comparison
COMPARE = {
    "Q8K3J9": "mouse Gprc5c",
    "Q9NQ84": "human GPRC5C",
    "Q923Z0": "mouse Gprc5b",
    "Q9NZH0": "human GPRC5B",
    "Q8BHL4": "mouse Gprc5a",
    "Q8NFJ5": "human GPRC5A",
    "Q9NZD1": "human GPRC5D",
    "P22815": "Drosophila BOSS",
}


def get(url):
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        body = r.read()
    return json.loads(body) if body else {}


def uniprot_count(query):
    url = UNIPROT + "?" + urllib.parse.urlencode({"query": f"({query})", "size": 1})
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.headers.get("x-total-results")


def main():
    entry = get(f"{API}/entry/interpro/IPR002956")["metadata"]
    print("# IPR002956 / InterPro2GO check for mouse Gprc5c (Q8K3J9)\n")
    print("Generated by `ipr002956_check.py` from the InterPro REST API.\n")
    print("## Entry\n")
    print(f"- name: {entry['name']['name']} (type: {entry['type']})")
    print(f"- member signatures: {entry.get('member_databases')}")
    gos = [f"{g['identifier']} {g['name']}" for g in entry.get("go_terms") or []]
    print(f"- InterPro2GO terms: {'; '.join(gos)}\n")

    print("## Reviewed (Swiss-Prot) proteins matching IPR002956\n")
    rev = get(f"{API}/protein/reviewed/entry/interpro/IPR002956/?page_size=100")
    print(f"- count: {rev.get('count')}")
    for r in rev.get("results", []):
        m = r["metadata"]
        print(f"- {m['accession']} {m['name']} ({m['source_organism']['scientificName']}, length {m['length']})")
    allp = get(f"{API}/protein/uniprot/entry/interpro/IPR002956/?page_size=1")
    print(f"\nAll UniProtKB proteins matching IPR002956: {allp.get('count')}"
          " (InterPro API protein/uniprot endpoint; the UniProtKB search counts below"
          " come from a different index and can differ)\n")

    print("## PRINTS PR01223 (BRIDEOF7LESS) match segments on Q8K3J9\n")
    pr = get(f"{API}/entry/prints/PR01223/protein/uniprot/{TARGET.lower()}")
    for p in pr.get("proteins", []):
        for loc in p["entry_protein_locations"]:
            for f in loc["fragments"]:
                print(f"- residues {f['start']}-{f['end']} (score {loc.get('score')})")
    print("\nCompare with UniProt Q8K3J9 predicted topology: extracellular N-terminus 23..49;"
          " TM1 50..70; TM6 241..261 (FT lines in Gprc5c-uniprot.txt).\n")

    print("## InterPro entries per GPRC5 family member / BOSS\n")
    for acc, label in COMPARE.items():
        try:
            d = get(f"{API}/entry/interpro/protein/uniprot/{acc}?page_size=50")
            ids = sorted(r["metadata"]["accession"] for r in d.get("results", []))
            has = "YES" if "IPR002956" in ids else "no"
            print(f"- {acc} {label}: IPR002956 match = {has}; entries = {', '.join(ids)}")
        except Exception as e:  # report, never invent
            print(f"- {acc} {label}: query failed ({e})")

    print("\n## Related InterPro entry names\n")
    for acc in NAMED_ENTRIES:
        try:
            m = get(f"{API}/entry/interpro/{acc}")["metadata"]
            print(f"- {acc}: {m['name']['name']} (type: {m['type']})")
        except Exception as e:  # report, never invent
            print(f"- {acc}: query failed ({e})")

    print("\n## UniProtKB breakdown of IPR002956 matches\n")
    print("| Subset | UniProtKB query | Count |")
    print("|---|---|---|")
    for label, query in BREAKDOWN.items():
        try:
            n = uniprot_count(query)
        except Exception as e:  # report, never invent
            n = f"query failed ({e})"
        print(f"| {label} | `{query}` | {n} |")

    print("\n## IPR002956 AND IPR050726 matches outside Arthropoda\n")
    try:
        url = UNIPROT + "?" + urllib.parse.urlencode({
            "query": "(xref:interpro-IPR002956 AND xref:interpro-IPR050726 NOT taxonomy_id:6656)",
            "fields": "accession,organism_name", "format": "tsv", "size": 50})
        with urllib.request.urlopen(url, timeout=60) as r:
            rows = r.read().decode().strip().splitlines()[1:]
        for row in rows:
            acc, org = row.split("\t", 1)
            print(f"- {acc} ({org})")
    except Exception as e:  # report, never invent
        print(f"- query failed ({e})")


if __name__ == "__main__":
    main()
