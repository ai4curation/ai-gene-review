"""Report where PANTHER places the Pax4, Pax6 and Pax10 leaves of PTHR45636.

Fetches the PANTHER tree for family PTHR45636 from the PANTHER web service
(``treeinfo``), finds the leaves whose gene symbol or subfamily name marks them
as Pax4, Pax6 or Pax10 in selected vertebrates, and prints, for each leaf, the
chain of internal nodes from the Bilateria node PTN008693041 down to the leaf,
with each node's taxonomic range and event type (speciation or duplication).
It also prints the children of the nodes that carry the eye, brain and beta-cell
IBDs, so the duplication nodes that separate Pax4 from Pax6 can be read off.

Usage (needs network access to www.pantherdb.org)::

    python3 panther_tree_paths.py > panther_tree_paths.md

Nothing is hardcoded: every node id, range and event comes from the service.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from collections.abc import Iterator

URL = "https://www.pantherdb.org/services/oai/pantherdb/treeinfo?family=PTHR45636"
SPECIES = {
    "Homo sapiens",
    "Mus musculus",
    "Rattus norvegicus",
    "Danio rerio",
    "Oryzias latipes",
    "lepisosteus oculatus",
    "Gallus gallus",
    "Xenopus tropicalis",
}
ANCHOR = "PTN008693041"
IBD_NODES = ["PTN008693041", "PTN002900580", "PTN009179984", "PTN009180006", "PTN000676674"]


def children(node: dict) -> list[dict]:
    """Return the child nodes of a PANTHER tree node (possibly empty)."""
    kids = node.get("children")
    if not kids:
        return []
    kids = kids.get("annotation_node")
    return [kids] if isinstance(kids, dict) else list(kids)


def walk(node: dict, path: list[dict]) -> Iterator[list[dict]]:
    """Yield the root-to-leaf path for every leaf below ``node``."""
    here = path + [node]
    kids = children(node)
    if not kids:
        yield here
    for kid in kids:
        yield from walk(kid, here)


def label(node: dict) -> str:
    """Format an internal node as id[range/event]."""
    event = (node.get("event_type") or "").replace("SPECIATION", "SPE").replace("DUPLICATION", "DUP")
    return f"{node.get('persistent_id')}[{node.get('taxonomic_range')}/{event}]"


def is_pax46(leaf: dict) -> bool:
    """True for a Pax4, Pax6 or Pax10 leaf (by symbol or subfamily name)."""
    text = f"{leaf.get('gene_symbol') or ''} {leaf.get('sf_name') or ''}".upper()
    return any(tag in text for tag in ("PAX4", "PAX-4", "PAX6", "PAX-6", "PAX10", "PAX 10", "PAX6.2"))


def main() -> None:
    """Fetch the tree and print the report as Markdown."""
    request = urllib.request.Request(URL, headers={"User-Agent": "curl/8 (ai-gene-review)"})
    with urllib.request.urlopen(request, timeout=120) as handle:
        data = json.load(handle)
    root = data["search"]["tree_topology"]["annotation_node"]
    version = data["search"]["product"]["version"]
    print(f"# PANTHER {version} PTHR45636: placement of Pax4, Pax6 and Pax10 leaves\n")
    print(f"Source: `{URL}`; generated by `panther_tree_paths.py`.\n")
    print("## Leaves (path from PTN008693041, Bilateria, down to the leaf's parent)\n")
    print("| species | symbol | subfamily | leaf gene id | path |")
    print("|---|---|---|---|---|")
    by_id: dict[str, dict] = {}
    for path in walk(root, []):
        for node in path:
            by_id[str(node.get("persistent_id"))] = node
        leaf = path[-1]
        if leaf.get("organism") not in SPECIES or not is_pax46(leaf):
            continue
        ids = [str(n.get("persistent_id")) for n in path]
        if ANCHOR not in ids:
            continue
        inner = path[ids.index(ANCHOR) : -1]
        print(
            f"| {leaf.get('organism')} | {leaf.get('gene_symbol')} | {leaf.get('sf_name')} | "
            f"{leaf.get('gene_id')} | {' > '.join(label(n) for n in inner)} |"
        )
    print("\n## Children of the IBD and duplication nodes\n")
    for node_id in IBD_NODES:
        node = by_id.get(node_id)
        if node is None:
            print(f"- {node_id}: not found")
            continue
        kids = ", ".join(label(k) for k in children(node))
        print(f"- {label(node)} has children: {kids}")


if __name__ == "__main__":
    sys.exit(main())
