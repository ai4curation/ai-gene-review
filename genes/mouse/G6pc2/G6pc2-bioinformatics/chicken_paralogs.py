"""Chicken G6PC paralog expression in Bgee, for the G6PC2-clade IRD question.

The G6pc2 review suggests a PAINT loss (IRD) of gluconeogenesis on the G6PC2
clade. PANTHER's G6PC2 orthogroup spans Euteleostomi (birds, reptiles, fish),
while the evidence for an islet-restricted, non-gluconeogenic G6PC2 is
mammalian. Poultry liver studies report a hepatic G6PC2 transcript, so this
script asks Bgee which chicken paralog is the hepatic/renal G6Pase.

Orthologs are Bgee's own (OMA) chicken orthologs of human G6PC1/G6PC2/G6PC3;
expression is Bgee 15.2 present calls (REST API; stages merged by taking each
entity's best score). Writes chicken_paralogs.md next to this script.

Run from the repository root:
    uv run python genes/mouse/G6pc2/G6pc2-bioinformatics/chicken_paralogs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "projects" / "BGEEDB_EXPRESSION" / "scripts"))
import bgee_common as bc  # noqa: E402

HUMAN = {"G6PC1": "ENSG00000131482", "G6PC2": "ENSG00000152254", "G6PC3": "ENSG00000141349"}
CHICKEN = 9031


def main() -> None:
    lines = [
        "# Chicken G6PC paralogs in Bgee",
        "",
        f"Generated by `chicken_paralogs.py`; do not edit. Source: {bc.BGEE_RELEASE} REST API present calls "
        "(best score per anatomical entity over all stages) for the OMA chicken orthologs of human G6PC1, "
        "G6PC2 and G6PC3. The API reports present calls only, so an entity that is not listed has no call, "
        "which is not the same as absence.",
        "",
        "| human gene | chicken ortholog | Bgee id | entities with a present call | liver | kidney | top entities (score) |",
        "|---|---|---|---|---|---|---|",
    ]
    pancreatic: set[str] = set()
    for sym, ens in HUMAN.items():
        for gid, name in bc.orthologs(ens, 9606, CHICKEN):
            best: dict[str, float] = {}
            for c in bc.stage_calls(gid, CHICKEN):
                a = c["condition"]["anatEntity"]["name"]
                best[a] = max(best.get(a, 0.0), float(c["expressionScore"]["expressionScore"]))
            pancreatic |= {f"{name}: {a}" for a in best if "pancrea" in a or "islet" in a}
            top = "; ".join(f"{a} ({s:.0f})" for a, s in sorted(best.items(), key=lambda kv: -kv[1])[:8])
            liver = f"{best['liver']:.0f}" if "liver" in best else "no call"
            kidney = f"{best['kidney']:.0f}" if "kidney" in best else "no call"
            lines.append(f"| {sym} | {name} | {gid} | {len(best)} | {liver} | {kidney} | {top} |")
    lines += ["", "Present calls in pancreas or islet for any chicken paralog: "
              + ("; ".join(sorted(pancreatic)) if pancreatic else "none") + "."]
    (Path(__file__).parent / "chicken_paralogs.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
