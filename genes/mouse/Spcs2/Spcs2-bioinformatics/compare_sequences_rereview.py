"""Independent re-review analysis of A0A140LHW5 versus canonical mouse Spcs2 (Q9CYN2).

Fetches both sequences from UniProt REST and both transcript models from the
Ensembl REST API, then reports:

* the shared N-terminal prefix and the divergent C-terminal tail of A0A140LHW5;
* which canonical UniProt features (topology, transmembrane helices) fall in the
  shared prefix;
* the exon structure of the benchmark transcript versus the canonical transcript,
  identifying skipped exons and whether the skip preserves reading frame.

Run: uv run --script compare_sequences_rereview.py > RESULTS-rereview.md
"""

import requests

UNIPROT = "https://rest.uniprot.org/uniprotkb/{acc}.json"
ENSEMBL = "https://rest.ensembl.org/lookup/id/{id}?content-type=application/json;expand=1"

BENCH_ACC = "A0A140LHW5"
CANON_ACC = "Q9CYN2"
BENCH_TX = "ENSMUST00000208465"
CANON_TX = "ENSMUST00000036274"


def uniprot(acc: str) -> dict:
    r = requests.get(UNIPROT.format(acc=acc), timeout=60)
    r.raise_for_status()
    return r.json()


def ensembl(tx: str) -> dict:
    r = requests.get(ENSEMBL.format(id=tx), timeout=60)
    r.raise_for_status()
    return r.json()


def shared_prefix(a: str, b: str) -> int:
    n = 0
    for x, y in zip(a, b):
        if x != y:
            break
        n += 1
    return n


def main() -> None:
    bench = uniprot(BENCH_ACC)
    canon = uniprot(CANON_ACC)
    bseq = bench["sequence"]["value"]
    cseq = canon["sequence"]["value"]
    k = shared_prefix(bseq, cseq)

    print("# Spcs2 re-review: A0A140LHW5 versus canonical Q9CYN2\n")
    print("Generated by `compare_sequences_rereview.py` (UniProt REST + Ensembl REST, live fetch).\n")
    print("## Sequence comparison\n")
    print(f"- {BENCH_ACC} length: {len(bseq)} aa")
    print(f"- {CANON_ACC} length: {len(cseq)} aa")
    print(f"- Identical N-terminal prefix: residues 1-{k}")
    print(f"- {BENCH_ACC} divergent tail ({k + 1}-{len(bseq)}): `{bseq[k:]}`")
    print(f"- {CANON_ACC} residues from {k + 1}: `{cseq[k:k + 20]}...`")
    print(f"- Tail occurs as a substring of {CANON_ACC}: {bseq[k:] in cseq}\n")

    print("## Canonical Q9CYN2 features relative to the shared prefix\n")
    print("| Feature | Description | Start | End | Inside shared prefix |")
    print("|---|---|---|---|---|")
    for f in canon.get("features", []):
        if f["type"] in ("Transmembrane", "Topological domain", "Modified residue", "Chain"):
            s = f["location"]["start"]["value"]
            e = f["location"]["end"]["value"]
            inside = "yes" if e <= k else ("partial" if s <= k else "no")
            print(f"| {f['type']} | {f.get('description', '')} | {s} | {e} | {inside} |")
    print()

    btx = ensembl(BENCH_TX)
    ctx = ensembl(CANON_TX)
    bex = {e["id"]: (e["start"], e["end"]) for e in btx["Exon"]}
    print("## Transcript models (Ensembl)\n")
    for label, tx in (("benchmark", btx), ("canonical", ctx)):
        tl = tx.get("Translation") or {}
        print(
            f"- {label} {tx['id']} ({tx.get('display_name')}), biotype {tx['biotype']}, "
            f"is_canonical={tx.get('is_canonical')}, {len(tx['Exon'])} exons, "
            f"translation {tl.get('id')} length {tl.get('length')}, strand {tx['strand']}"
        )
    print("\n| Canonical exon | Start | End | Length (nt) | Present in benchmark | Length mod 3 |")
    print("|---|---|---|---|---|---|")
    for e in ctx["Exon"]:
        ln = e["end"] - e["start"] + 1
        present = e["id"] in bex or any(
            bs <= e["end"] and be >= e["start"] for bs, be in bex.values()
        )
        print(f"| {e['id']} | {e['start']} | {e['end']} | {ln} | {present} | {ln % 3} |")
    print()
    print("A skipped internal coding exon whose length is not a multiple of 3 shifts the")
    print("reading frame of all downstream codons; the divergent tail then reflects")
    print("out-of-frame translation of the next exon until a stop codon is met.")


if __name__ == "__main__":
    main()
