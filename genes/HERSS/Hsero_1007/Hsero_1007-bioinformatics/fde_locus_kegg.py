#!/usr/bin/env python3
"""Query KEGG for the Herbaspirillum seropedicae SmR1 fde locus (Hsero_1004-Hsero_1012).

Retrieves, live from the KEGG REST API:
  * KO assignments of each locus tag,
  * the definition, comment, and orthology of reactions R13074-R13079,
  * the number of KEGG organisms carrying each Fde KO (taxonomic breadth).

Writes RESULTS.md next to this script. Nothing is hardcoded except the query ids.
Usage: python fde_locus_kegg.py
"""
from __future__ import annotations

import collections
import pathlib
import urllib.request

KEGG = "https://rest.kegg.jp"
LOCI = [f"Hsero_{n}" for n in range(1004, 1013)]
REACTIONS = [f"R1307{n}" for n in range(4, 10)]
# Submitter EC/name claims on fde-locus proteins, checked against the dedicated
# KEGG orthology groups for the same activity elsewhere in the SmR1 genome.
SUBMITTER_CLAIMS = {
    "Hsero_1005": ("glyoxalase II / hydroxyacylglutathione hydrolase", "K01069"),
    "Hsero_1006": ("hydroxyethylthiazole kinase", "K00878"),
    "Hsero_1012": ("UDP-glucose 4-epimerase", "K01784"),
}
KOS = ["K26179", "K26180", "K26181", "K26182", "K26183", "K26184", "K26185"]


def get(path: str) -> str:
    """Return the text body of a KEGG REST call."""
    with urllib.request.urlopen(f"{KEGG}/{path}", timeout=60) as r:
        return r.read().decode()


def main() -> None:
    """Run the queries and write RESULTS.md."""
    out: list[str] = ["# Herbaspirillum seropedicae SmR1 fde locus: KEGG assignments", ""]
    out += ["Generated by `fde_locus_kegg.py` from the live KEGG REST API.", ""]
    out += ["## KO assignments", ""]
    links = get("link/ko/" + "+".join(f"hse:{x}" for x in LOCI))
    names = dict(
        line.split("\t", 1) for line in get("list/" + "+".join(KOS)).strip().splitlines()
    )
    assigned = {}
    for line in links.strip().splitlines():
        gene, ko = line.split("\t")
        assigned[gene.split(":")[1]] = ko.split(":")[1]
    for locus in LOCI:
        ko = assigned.get(locus)
        label = names.get(ko, "") if ko else ""
        out.append(f"- KEGG mapping: `hse:{locus} -> ko:{ko}` ({label})" if ko else f"- `hse:{locus}`: no KO assigned")
    out += ["", "## Reactions", ""]
    for rid in REACTIONS:
        rec = get(f"get/{rid}")
        fields = collections.defaultdict(list)
        key = None
        for line in rec.splitlines():
            if line[:12].strip():
                key = line[:12].strip()
            if key:
                fields[key].append(line[12:].strip())
        out.append(f"- {rid}: {' '.join(fields['DEFINITION'])}; KEGG comment: {' '.join(fields['COMMENT'])}; orthology: {'; '.join(fields['ORTHOLOGY'])}")
    out += ["", "## Taxonomic breadth of each Fde KO", ""]
    for ko in KOS:
        genes = get(f"link/genes/{ko}").strip().splitlines()
        orgs = {g.split("\t")[1].split(":")[0] for g in genes if "\t" in g}
        out.append(f"- {ko} ({names.get(ko, '')}): {len(genes)} genes in {len(orgs)} KEGG organisms")
    out += ["", "## Dedicated SmR1 genes for submitter-named activities", ""]
    for locus, (activity, ko) in SUBMITTER_CLAIMS.items():
        hits = sorted(
            line.split("\t")[1].split(":")[1]
            for line in get(f"link/hse/{ko}").strip().splitlines()
            if "\t" in line
        )
        listed = ", ".join(hits) if hits else "none"
        out.append(
            f"- {locus} submitter name/EC '{activity}': SmR1 genes in the dedicated KO {ko}: {listed}"
            f"; {locus} in {ko}: {locus in hits}"
        )
    pathlib.Path(__file__).with_name("RESULTS.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
