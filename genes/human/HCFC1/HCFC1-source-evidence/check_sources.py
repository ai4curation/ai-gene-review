"""Recheck source-linked HCFC1 interaction records without retaining API payloads.

Run from the repository root with its existing Python runtime. IntAct records
index the cited experiments; they are not independent replications or proof of
a direct binary interface. A missing result leaves a check unresolved.
"""
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path
import argparse
import hashlib
import json
from urllib.parse import quote

import requests

TARGET = 'P51610'
CHECKS = {
    '18585351': {'EBI-1790937', 'EBI-1790971'},
    '19615732': {'EBI-2509989'},
    '23870121': {'EBI-8787802'},
    '27705803': {'EBI-8833802', 'EBI-8836498', 'EBI-8830949'},
    '33961781': {'EBI-54660611', 'EBI-54660483', 'EBI-54660643',
                 'EBI-54660685', 'EBI-54628566'},
}

def lookup(item):
    pmid, expected = item
    url = ('https://www.ebi.ac.uk/Tools/webservices/psicquic/intact/'
           'webservices/current/search/query/' +
           quote(f'id:{TARGET} AND pubid:{pmid}', safe='') + '?format=tab27')
    response = requests.get(url, timeout=90)
    result = {'pmid': pmid, 'url': url, 'http_status': response.status_code,
              'response_bytes': len(response.content),
              'response_sha256': hashlib.sha256(response.content).hexdigest(),
              'records': [], 'missing_expected': sorted(expected)}
    if not response.ok:
        result['status'] = 'unresolved'
        return result
    seen = set()
    for line in response.text.splitlines():
        if not line or line.startswith('#'):
            continue
        fields = line.split('\t')
        if len(fields) < 15:
            continue
        identities = fields[0].split('|') + fields[1].split('|')
        ids = [x.split(':', 1)[1] for x in identities if x.startswith('uniprotkb:')]
        record_ids = {x.split(':', 1)[-1] for x in fields[13].split('|')}
        matching = expected & record_ids
        if TARGET not in ids or not matching or f'pubmed:{pmid}' not in fields[8].split('|'):
            continue
        for rid in sorted(matching):
            if rid in seen:
                continue
            seen.add(rid)
            record = {'id': rid, 'interactors': ids, 'publication': fields[8],
                      'method': fields[6], 'taxa': fields[9:11],
                      'interaction_type': fields[11], 'source': fields[12],
                      'source_ids': fields[13]}
            if len(fields) >= 38:
                record.update(host_organism=fields[28], features=fields[36:38],
                              negative=fields[35])
            record['quote'] = (f'IntAct {rid}: {" + ".join(ids)}; PMID:{pmid}; '
                               f'method={fields[6]}; taxa={" / ".join(fields[9:11])}.')
            result['records'].append(record)
    result['missing_expected'] = sorted(expected - seen)
    result['status'] = 'verified' if not result['missing_expected'] else 'unresolved'
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--output-dir', type=Path, default=Path(__file__).resolve().parent,
        help='Directory for checks.json and RESULTS.md; existing results are never overwritten.',
    )
    out = parser.parse_args().output_dir
    destination = out / 'checks.json'
    report = out / 'RESULTS.md'
    if destination.exists() or report.exists():
        raise SystemExit('Retained evidence exists; choose a new versioned directory with --output-dir.')
    out.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=3) as pool:
        checks = list(pool.map(lookup, CHECKS.items()))
    data = {'checked_utc': datetime.now(timezone.utc).isoformat(),
            'target': TARGET, 'script_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'limitations': 'IntAct indexes the cited experiments; association is not independent replication or proof of a direct interface.',
            'checks': checks}
    with destination.open('x') as handle:
        handle.write(json.dumps(data, indent=2) + '\n')
    lines = ['# HCFC1 source-linked interaction checks', '', data['limitations'], '',
             'Generated by `check_sources.py`; response hashes and selected source fields are in `checks.json`. No full API payloads are retained.', '']
    for check in checks:
        lines.extend([f'## PMID:{check["pmid"]}', '',
                      f'Status: {check["status"]}. [IntAct query]({check["url"]})', ''])
        lines.extend('- ' + record['quote'] for record in check['records'])
        if check['missing_expected']:
            lines.append('Unresolved expected records: ' + ', '.join(check['missing_expected']))
        lines.append('')
    with report.open('x') as handle:
        handle.write('\n'.join(lines))
    print(json.dumps({'checks': len(checks), 'verified': sum(x['status'] == 'verified' for x in checks),
                      'records': sum(len(x['records']) for x in checks), 'output': str(destination)}))

if __name__ == '__main__':
    main()
