"""Scan Tim50-family sequences for the FCP/SCP phosphatase catalytic motif D-x-D-x-(T/V).

Haloacid-dehalogenase phosphatases of the FCP/SCP class use a D-x-D-x-(T/V) motif;
the first Asp is the nucleophile. Trypanosoma brucei Tim50 keeps the motif and loses
phosphatase activity when it is mutated, so it is the positive control here. The other
accessions are the Tim50 orthologues in PANTHER PTHR12210:SF3 below the IRD node
PTN002639282 (from projects/IRD_EVIDENCE/ird_clade_members.tsv.gz).

Sequences are fetched live from UniProt. Writes RESULTS.md next to this script.

Usage:
    uv run python genes/human/TIMM50/TIMM50-bioinformatics/motif_scan.py
"""

from __future__ import annotations

import re
import urllib.request
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
MOTIF = re.compile(r"(?=(D.D.[TV]))")
PROTEINS = [
    ("Q57ZA0", "Trypanosoma brucei", "Tim50 (positive control, outside the IRD clade)"),
    ("Q3ZCQ8", "Homo sapiens", "TIMM50"),
    ("Q9D880", "Mus musculus", "Timm50"),
    ("Q02776", "Saccharomyces cerevisiae", "TIM50"),
    ("O13636", "Schizosaccharomyces pombe", "tim50"),
    ("Q9W4V8", "Drosophila melanogaster", "ttm50"),
    ("Q9W0S3", "Drosophila melanogaster", "ttm2"),
    ("Q9V9P3", "Drosophila melanogaster", "ttm3"),
    ("Q22647", "Caenorhabditis elegans", "scpl-4"),
    ("Q8VYE2", "Arabidopsis thaliana", "TIM50"),
]


def fetch(acc: str) -> str:
    """Return the UniProt canonical sequence for an accession."""
    with urllib.request.urlopen(f"https://rest.uniprot.org/uniprotkb/{acc}.fasta", timeout=60) as r:
        return "".join(r.read().decode().splitlines()[1:])


def main() -> None:
    rows = []
    for acc, organism, label in PROTEINS:
        seq = fetch(acc)
        hits = [f"{m.group(1)}@{m.start() + 1}" for m in MOTIF.finditer(seq)]
        rows.append(f"| {acc} | {organism} | {label} | {len(seq)} | {', '.join(hits) or 'none'} |")
    out = [
        "# D-x-D-x-(T/V) motif scan of Tim50 proteins",
        "",
        f"Generated by `motif_scan.py` on {date.today().isoformat()} from live UniProt sequences.",
        "",
        "| UniProt | Organism | Protein | Length | D-x-D-x-(T/V) matches (motif@start) |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "A match is necessary but not sufficient for catalysis; its absence means the canonical",
        "FCP/SCP nucleophile motif is missing.",
    ]
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
