#!/usr/bin/env python3
"""Render RESULTS.md from results.json.

Every figure in the report is read out of results.json, so a stale report is
impossible: `uv run python nucleotide_site.py && uv run python write_results.py`
followed by `git diff` reproduces the committed file exactly.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    src = HERE / "results.json"
    if not src.exists():
        raise SystemExit(
            "ERROR: results.json missing. Run `uv run python nucleotide_site.py` first."
        )
    r = json.loads(src.read_text())
    p = r["parameters"]
    g = r["g_actin_pocket"]
    f = r["f_actin_interface_site"]
    panel = r["panel"]
    q = panel["ARP5_HUMAN"]
    L: list[str] = []
    A = L.append

    A("# ACTR5 (ARP5) actin-fold audit: nucleotide site and filament interface")
    A("")
    A("Generated by `write_results.py` from `results.json`; `results.json` is")
    A("produced by `nucleotide_site.py`. Do not hand-edit — a fresh run will")
    A("overwrite it.")
    A("")
    A("```")
    A("uv run python nucleotide_site.py")
    A("uv run python write_results.py")
    A("```")
    A("")
    A("## Question")
    A("")
    A("UniProt places ACTR5 in \"the actin family, ARP5 subfamily\" and CDD")
    A("annotates it `cd10211 ASKHA_NBD_Arp5`, i.e. an actin/Hsp70/sugar-kinase")
    A("nucleotide-binding domain. A fold assignment is not an activity, so two")
    A("things are tested here, in both directions:")
    A("")
    A("1. **Is there a nucleotide site, and is it the actin one?** (a positive claim)")
    A("2. **Could ACTR5 polymerise, or hydrolyse the bound nucleotide?** (claims")
    A("   that would license actin-filament or ATPase terms)")
    A("")
    A("## 1. A nucleotide is resolved in the ARP5 chain of the human INO80 complex")
    A("")
    A(f"| PDB | resolution (A) | ARP5 chain | nucleotide in the ARP5 chain | contacts (<= {p['ligand_contact_cutoff_angstrom']} A) | ATP-mimic group in the ARP5 chain |")
    A("|---|---|---|---|---|---|")
    for e in r["arp5_structures"]:
        nts = e["arp5_nucleotides"]
        if nts:
            desc = ", ".join(n["comp"] for n in nts)
            n_c = ", ".join(str(n["n_contacts"]) for n in nts)
            mim = ", ".join(", ".join(n["atp_mimic_in_same_chain"]) or "none" for n in nts)
        else:
            desc, n_c, mim = "none", "-", "-"
        A(f"| {e['pdb_id']} | {e['resolution_angstrom']} | {','.join(e['arp5_chains'])} | "
          f"{desc} | {n_c} | {mim} |")
    A("")
    A("Resolutions are the PDBe-reported values, fetched rather than transcribed.")
    A("")
    A("ARP5 chain assignment comes from the PDBe SIFTS UniProt mapping, not from")
    A("chain letters: a missing Q9H9F9 mapping aborts the run rather than")
    A("reporting an empty result (a silent zero reads as a finding).")
    A("")
    hit = r["arp5_structures_with_nucleotide"]
    A(f"**ADP is modelled in the ARP5 chain in {len(hit)} of "
      f"{len(r['arp5_structures'])} entries ({', '.join(hit)}); ATP never is.**")
    A("The three entries without it are 6HTS (whose ARP5 was an I-TASSER homology")
    A("model trimmed of all side chains) and two of the 2026 nucleosome states.")
    A("")
    A("**The bound species is plain ADP, not an ATP analogue.** Every one of these")
    A("samples was soaked with ADP-BeF3, which would ordinarily leave the")
    A("identity of the ligand ambiguous. It does not here: in all three entries")
    A("the ARP5 chain contains no BeF3, AlF, VO4 or PO4 group alongside its ADP.")
    mimic_rows = [
        (e["pdb_id"], n["atp_mimic_in_same_chain"], n["atp_mimic_elsewhere_in_entry"])
        for e in r["arp5_structures"] for n in e["arp5_nucleotides"]
    ]
    for pdb_id, same, elsewhere in mimic_rows:
        where = ", ".join(f"{c} in chain {ch}" for c, ch in elsewhere) or "none in the entry"
        A(f"  * {pdb_id}: mimic groups in the ARP5 chain: "
          f"{', '.join(same) if same else 'none'}; elsewhere in the entry: {where}.")
    A("")
    A("In 7ZI4 the only BeF3 in the whole entry sits in chain G, the Ino80 motor")
    A("domain, which is where the ATP mimic belongs. So the ADP-BeF3 soak")
    A("qualifies what the *motor* was trapped with, not what ARP5 was: ARP5's")
    A("cleft holds ADP. What the structures still cannot do is rank ADP against")
    A("ATP, because no ATP was offered to ARP5 in solution.")
    A("")
    seven = next(n for e in r["arp5_structures"] if e["pdb_id"] == "7ZI4"
                 for n in e["arp5_nucleotides"])
    A("Contacts in the highest-resolution entry (7ZI4, 3.2 A):")
    A("")
    A("`" + " ".join("%s%d" % (c["aa"], c["unp_pos"]) for c in seven["contacts"]) + "`")
    A("")
    A("## 2. It is the canonical actin nucleotide site (reciprocal test)")
    A("")
    A(f"Reference: {g['pdb_id']} chain {g['chain']} "
      f"({g['structure_entry_name']}, {g['structure_accession']}, "
      f"{g['identity_to_human_ACTB']['percent_identity']}% identical to human "
      f"{p['numbering_frame'].split()[2]}), {g['ligand']}-contacting residues:")
    A("")
    A("`" + " ".join(g["residues"]) + "`")
    A("")
    A("Finding a ligand is not enough — it has to be the *same* site. So the")
    A("test is reciprocal: align ACTR5 to beta-actin, then ask what fraction of")
    A("ARP5's **observed** contacts fall on ACTR5 positions that align to")
    A("beta-actin's own nucleotide contacts.")
    A("")
    A("| PDB | observed ARP5 contacts | on the aligned actin pocket | fraction | off-pocket |")
    A("|---|---|---|---|---|")
    for row in r["reciprocal_site_check"]:
        A("| {} | {} | {} | {} | {} |".format(
            row["pdb_id"], row["n_observed_contacts"],
            row["n_on_aligned_actin_pocket"], row["fraction_on_aligned_actin_pocket"],
            ", ".join(str(x) for x in row["outside_actin_pocket"]) or "-"))
    u = r["actr5_observed_contact_union"]
    A("")
    A(f"Union over the three entries: {u['n']} ACTR5 positions contact the "
      f"nucleotide, {u['n_on_aligned_actin_pocket']} of them on the aligned "
      "actin pocket. The retained contacts are the two actin phosphate-binding")
    A("loops (ACTB G13-S14-G15-M16-K18 -> ACTR5 G38-S39-F40-Q41-R43; ACTB G156")
    A("-> ACTR5 G189) and the adenosine shelf (ACTB G302/M305/Y306 -> ACTR5")
    A("G496/M499/Y500). This is the actin nucleotide cleft, not an adventitious")
    A("surface site.")
    A("")
    A("## 3. The ATP-hydrolysis trigger is not retained")
    A("")
    A("Literature-defined actin catalytic positions (ACTB numbering), kept")
    A("deliberately identical to the ACTL7A review's audit so the two are")
    A("comparable: " + ", ".join(f"{v}{k}" for k, v in
                                 sorted(p["catalytic_residues"].items(), key=lambda x: int(x[0]))) + ".")
    A("The script asserts each position carries the expected residue in ACTB")
    A("before mapping anything.")
    A("")
    A(f"**ACTR5 = `{q['catalytic_residues']}`, i.e. "
      f"{q['n_catalytic_conserved']}/{len(p['catalytic_residues'])} conserved:** the")
    A("Mg-coordinating Asp11 and His161 are kept, but Gln137 (which orients the")
    A("attacking water), Asp154 and Val159 are not. So the pocket binds a")
    A("nucleotide while the hydrolysis machinery is degenerate — the same shape")
    A("of result the ACTL7A review reported for its gene.")
    A("")
    cc = r["crosscheck_ACTL7A_audit"]
    A(f"Cross-check: the independently committed `{cc['file']}` reports "
      f"`{cc['their_ARP5_HUMAN_catalytic_residues']}` for ARP5_HUMAN; this run "
      f"computes `{cc['our_ARP5_HUMAN_catalytic_residues']}` "
      f"(agree = {cc['agree']}). A mismatch is a hard error, not a warning.")
    A("")
    A("## 4. The filament protomer interface is not retained either")
    A("")
    A(f"Reference: {f['pdb_id']} ({f['structure_entry_name']}, "
      f"{f['structure_accession']}, {f['identity_to_human_ACTB']['percent_identity']}% "
      f"identical to human beta-actin), chains {','.join(f['chains'])}. Interface = "
      f"residues within {p['interface_contact_cutoff_angstrom']} A of a different "
      f"protomer in >= {int(p['protomer_fraction']*100)}% of protomers that have any "
      f"inter-protomer contact: {f['n_positions']} positions in ACTB numbering.")
    A("")
    A("| protein | group | catalytic | nucleotide pocket %id | protomer interface %id | overall %id vs ACTB |")
    A("|---|---|---|---|---|---|")
    for label, v in panel.items():
        A("| {} | {} | {} ({}/{}) | {} | {} | {} |".format(
            label, v["group"], v["catalytic_residues"], v["n_catalytic_conserved"],
            len(p["catalytic_residues"]), v["g_pocket"]["percent_identical"],
            v["f_interface"]["percent_identical"],
            v["alignment_to_ACTB"]["percent_identity"]))
    A("")
    arp1 = panel["ARP1_ACTR1A_HUMAN"]
    A(f"**ARP1/ACTR1A is the positive control**: it is the one ARP that really does")
    A(f"form a filament, and it keeps {arp1['f_interface']['percent_identical']}% of the")
    A(f"interface, against {q['f_interface']['percent_identical']}% for ACTR5 — a")
    A(f"{round(arp1['f_interface']['percent_identical'] / max(q['f_interface']['percent_identical'], 0.1), 1)}-fold")
    A("gap, so the measurement discriminates. ACTR5 sits with the")
    A("non-polymerising nuclear ARPs.")
    A("")
    A("Robustness: repeating the whole transfer under BLOSUM45 with a")
    A(f"(-14,-2) gap model gives ACTR5 pocket "
      f"{q['second_model']['g_pocket_percent_identical']}% / interface "
      f"{q['second_model']['f_interface_percent_identical']}% and the same")
    A(f"catalytic string `{q['second_model']['catalytic_residues']}`, so the")
    A("conclusions do not depend on the alignment model.")
    A("")
    A("## 5. The ARP5 orthologs that donate ACTR5's IBAs are in the same regime")
    A("")
    A("The four WITH/FROM donor orthologs (fly, budding yeast, fission yeast,")
    A("Arabidopsis ARP5) all show a partly conserved nucleotide pocket")
    A("(" + ", ".join(
        f"{k.split('_')[-1]} {v['g_pocket']['percent_identical']}%"
        for k, v in panel.items() if v["group"] == "arp5_ortholog_iba_donor") + ")")
    A("and a degenerate filament interface")
    A("(" + ", ".join(
        f"{k.split('_')[-1]} {v['f_interface']['percent_identical']}%"
        for k, v in panel.items() if v["group"] == "arp5_ortholog_iba_donor") + ").")
    A("So both results are family-wide properties of ARP5, not human")
    A("peculiarities: any nucleotide-binding gap in the GO record is a")
    A("family-level gap, and the absence of filament terms across the family is")
    A("correct rather than an oversight.")
    A("")
    A("## Conclusions")
    A("")
    A("* **Supports** a nucleotide-binding molecular function for ACTR5, with ADP")
    A("  the observed ligand: resolved in three independent human INO80")
    f_hits = ", ".join(hit)
    A(f"  depositions ({f_hits}), in the canonical actin cleft by the reciprocal")
    A("  test. ACTR5's GO record currently contains no nucleotide-binding")
    A("  annotation of any kind.")
    A("* **Does not support** any ATP-hydrolysis / ATPase activity for ACTR5")
    A(f"  itself ({q['n_catalytic_conserved']}/{len(p['catalytic_residues'])} catalytic")
    A("  positions). GOA asserts none, which is correct.")
    A("* **Does not support** actin-filament, actin-binding or protein-")
    A(f"  polymerisation terms ({q['f_interface']['percent_identical']}% interface")
    A(f"  identity against {arp1['f_interface']['percent_identical']}% for the")
    A("  filament-forming positive control). GOA asserts none, which is also")
    A("  correct — so no cytoplasmic-actin annotation has leaked into this gene.")
    A("")
    A("## Provenance")
    A("")
    A(f"* gemmi {r['provenance']['gemmi']}; coordinates from the PDBe entry-files")
    A("  API, sequences from the UniProt REST API (each lookup asserts that the")
    A("  returned `primaryAccession` is the one requested).")
    A("* Downloaded mmCIF files are cached under `structures/` and are not")
    A("  committed.")

    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote", HERE / "RESULTS.md")


if __name__ == "__main__":
    main()
