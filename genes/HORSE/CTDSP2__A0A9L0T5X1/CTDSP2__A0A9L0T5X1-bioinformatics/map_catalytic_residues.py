"""Map human CTDSP2 (O14595) curated catalytic features onto horse A0A9L0T5X1.

Fetches both sequences from UniProt REST, aligns them globally (BLOSUM62,
affine gaps), and reports, for each human feature position, the aligned horse
residue. Also reports overall identity over the human FCP1 domain (97-255)
and the horse N-terminal extension that has no human counterpart.

Run: uv run python map_catalytic_residues.py > RESULTS.md
"""

import urllib.request

from Bio import Align
from Bio.Align import substitution_matrices

HUMAN = "O14595"
HORSE = "A0A9L0T5X1"
# Human O14595 feature positions as annotated in UniProt (FT lines).
HUMAN_FEATURES = {
    107: "ACT_SITE 4-aspartylphosphate intermediate; Mg2+ binding",
    109: "ACT_SITE proton donor; Mg2+ binding",
    163: "SITE transition state stabilizer",
    201: "SITE transition state stabilizer",
    218: "BINDING Mg2+",
}
FCP1_DOMAIN = (97, 255)
# SCP-clade comparators (PANTHER PTHR12210 subfamily per PANTHER 19.0:
# CTDSP2 = SF187, CTDSP1 = SF139, CTDSPL = SF43).
COMPARATORS = {
    "human CTDSP2 O14595 (SF187)": "O14595",
    "cow CTDSP2 Q2KJ43": "Q2KJ43",
    "mouse Ctdsp2 Q8BX07": "Q8BX07",
    "human CTDSP1 Q9GZU7 (SF139)": "Q9GZU7",
    "mouse Ctdsp1 P58466": "P58466",
    "human CTDSPL O15194 (SF43)": "O15194",
}


def fetch(acc: str) -> str:
    url = f"https://rest.uniprot.org/uniprotkb/{acc}.fasta"
    with urllib.request.urlopen(url) as fh:
        lines = fh.read().decode().splitlines()
    return "".join(line for line in lines if not line.startswith(">"))


def main() -> None:
    hs = fetch(HUMAN)
    ec = fetch(HORSE)
    aligner = Align.PairwiseAligner()
    aligner.substitution_matrix = substitution_matrices.load("BLOSUM62")
    aligner.open_gap_score = -10
    aligner.extend_gap_score = -0.5
    aln = aligner.align(hs, ec)[0]
    # map human 1-based position -> horse 1-based position (or None)
    h2e: dict[int, int | None] = {i + 1: None for i in range(len(hs))}
    for (hs_s, hs_e), (ec_s, ec_e) in zip(*aln.aligned):
        for k in range(hs_e - hs_s):
            h2e[hs_s + k + 1] = ec_s + k + 1

    print(f"# Catalytic-residue mapping: human {HUMAN} -> horse {HORSE}\n")
    print("Generated by `map_catalytic_residues.py`; values are computed from")
    print("UniProt REST sequences, not hand-entered.\n")
    print(f"- Human length: {len(hs)}; horse length: {len(ec)}")
    first_aligned_horse = min(p for p in h2e.values() if p is not None)
    print(f"- Horse N-terminal residues before the first aligned position: "
          f"{first_aligned_horse - 1} (horse starts with '{ec[:10]}', "
          f"human starts with '{hs[:10]}')")
    lo, hi = FCP1_DOMAIN
    pairs = [(hs[i - 1], ec[h2e[i] - 1]) for i in range(lo, hi + 1) if h2e[i]]
    ident = sum(a == b for a, b in pairs)
    print(f"- Human FCP1 domain {lo}-{hi}: {len(pairs)} of {hi - lo + 1} "
          f"positions aligned, {ident} identical "
          f"({ident / (hi - lo + 1):.3f} of domain length)")
    hm = hs.find("DLDET") + 1
    em = ec.find("DLDET") + 1
    print(f"- DLDET motif: human position {hm}, horse position {em}\n")
    print("| Human position | Human residue | Feature | Horse position | Horse residue | Conserved |")
    print("|---|---|---|---|---|---|")
    for pos, note in HUMAN_FEATURES.items():
        e = h2e[pos]
        er = ec[e - 1] if e else "-"
        print(f"| {pos} | {hs[pos - 1]} | {note} | {e} | {er} | {hs[pos - 1] == er} |")
    # identity of the horse catalytic region (from 10 aa before DLDET to the
    # C-terminus) to each comparator, over horse catalytic-region length
    region = ec[em - 11:]
    print(f"\n## Horse catalytic region ({len(region)} aa from position {em - 10}) vs SCP-clade comparators\n")
    print("| Comparator | Identical | Identity over horse region |")
    print("|---|---|---|")
    rows = []
    for name, acc in COMPARATORS.items():
        other = fetch(acc)
        a = aligner.align(region, other)[0]
        idn = 0
        for (rs, re_), (cs, ce) in zip(*a.aligned):
            idn += sum(x == y for x, y in zip(region[rs:re_], other[cs:ce]))
        rows.append((idn / len(region), name, idn))
    for frac, name, idn in sorted(rows, reverse=True):
        print(f"| {name} | {idn} | {frac:.3f} |")
    print("\n## Alignment\n\n```")
    print(aln)
    print("```")


if __name__ == "__main__":
    main()
