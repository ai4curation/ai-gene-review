"""Re-review: compare horse PEA15 gene models with human/mouse PEA15.

Inputs (all local): horse A0A9L0RWM8 (PEA15-uniprot.txt), horse F7AD02 and
mouse Q62048 (FASTA downloaded from UniProt REST into this folder), human
Q15121 (genes/human/PEA15/PEA15-uniprot.txt). Writes RESULTS-rereview.md and
results-rereview.json. Reports where the conserved mammalian start Met and
selected human features land in each horse model; it does not test function.
"""
from pathlib import Path
import json
from Bio import Align, SeqIO, SwissProt

here = Path(__file__).resolve().parent
with (here.parent / "PEA15-uniprot.txt").open() as f:
    bench = SwissProt.read(f)
with (here.parents[2] / "human" / "PEA15" / "PEA15-uniprot.txt").open() as f:
    human = SwissProt.read(f)
f7ad02 = str(next(SeqIO.parse(here / "F7AD02-rereview.fasta", "fasta")).seq)
mouse = str(next(SeqIO.parse(here / "Q62048-rereview.fasta", "fasta")).seq)

aligner = Align.PairwiseAligner()
aligner.mode = "global"
aligner.match_score = 2
aligner.mismatch_score = -1
aligner.open_gap_score = -10
aligner.extend_gap_score = -0.5
aligner.target_end_gap_score = 0
aligner.query_end_gap_score = 0

# Human features (1-based positions on Q15121) from UniProt FT lines / literature.
features = {
    "DED (UniProt FT 3-81)": (3, 81),
    "NES (residues 7-17)": (7, 17),
    "Asp74 (D74, ERK-binding network)": (74, 74),
    "Ser104 (PKC site)": (104, 104),
    "Ser116 (CaMKII/Akt site)": (116, 116),
    "C-terminal ERK D-site segment 121-129": (121, 129),
}


def compare(ref, ref_name, model, model_name):
    aln = aligner.align(ref, model)[0]
    x, y = str(aln[0]), str(aln[1])
    pos_map, rp, mp = {}, 0, 0
    for u, v in zip(x, y):
        if u != "-":
            rp += 1
        if v != "-":
            mp += 1
        if u != "-" and v != "-":
            pos_map[rp] = (mp, u == v)
    paired = len(pos_map)
    ident = sum(1 for _, same in pos_map.values() if same)
    start_in_model = pos_map.get(1, (None,))[0]
    feats = {}
    for name, (s, e) in features.items():
        mapped = [pos_map[i] for i in range(s, e + 1) if i in pos_map]
        feats[name] = {
            "model_positions": f"{mapped[0][0]}-{mapped[-1][0]}" if mapped else None,
            "identical": sum(1 for _, same in mapped if same),
            "length": e - s + 1,
        }
    return {
        "reference": ref_name,
        "model": model_name,
        "reference_length": len(ref),
        "model_length": len(model),
        "paired": paired,
        "identical": ident,
        "reference_met1_maps_to_model_position": start_in_model,
        "model_n_terminal_extension": model[: start_in_model - 1] if start_in_model else None,
        "features": feats,
    }


results = [
    compare(human.sequence, "human Q15121", bench.sequence, "horse A0A9L0RWM8"),
    compare(human.sequence, "human Q15121", f7ad02, "horse F7AD02"),
    compare(human.sequence, "human Q15121", mouse, "mouse Q62048"),
]
(here / "results-rereview.json").write_text(json.dumps(results, indent=2) + "\n")
lines = [
    "# PEA15 re-review: horse gene models vs human/mouse PEA15",
    "",
    "Generated by `uv run python genes/HORSE/PEA15/PEA15-bioinformatics/compare_sequences_rereview.py`",
    "(Biopython global alignment, free end gaps). Values are computed, not hardcoded.",
    "",
    "| Reference | Model | Ref len | Model len | Identical/paired | Ref Met1 -> model pos | Model N-terminal extension |",
    "|---|---|---|---|---|---|---|",
]
for r in results:
    ext = r["model_n_terminal_extension"] or ""
    lines.append(
        f"| {r['reference']} | {r['model']} | {r['reference_length']} | {r['model_length']} | "
        f"{r['identical']}/{r['paired']} | {r['reference_met1_maps_to_model_position']} | "
        f"{ext} ({len(ext)} aa) |"
    )
lines += ["", "## Human feature correspondence", ""]
for r in results:
    lines += [f"### {r['model']}", "", "| Human feature | Model positions | Identical/length |", "|---|---|---|"]
    for name, v in r["features"].items():
        lines.append(f"| {name} | {v['model_positions']} | {v['identical']}/{v['length']} |")
    lines.append("")
lines += [
    "Interpretation limits: this shows sequence correspondence only. Whether the horse",
    "upstream extensions are translated in vivo (rather than predicted from an upstream",
    "in-frame ATG / alternative 5' exon) is not tested here.",
]
(here / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
