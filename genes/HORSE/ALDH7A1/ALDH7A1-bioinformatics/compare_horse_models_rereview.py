"""Compare all horse ALDH7A1 gene-model products with human P49419 (re-review).

Fetches (live) every horse UniProt entry in PANTHER PTHR43521, the Ensembl
transcript structure of horse gene ENSECAG00000010547, and human P49419, then:

* aligns each horse product globally to human P49419-1;
* reports internal gaps relative to human and whether the human catalytic
  Glu296 / Cys330 and the 65-82 segment (beta strands 65-70, 75-81) are present;
* lists coding-exon lengths (nt) per Ensembl transcript so that an in-frame
  exon skip can be recognised.

Writes RESULTS-rereview.md and results-rereview.json next to this script.
Run from the repository root:
    uv run python genes/HORSE/ALDH7A1/ALDH7A1-bioinformatics/compare_horse_models_rereview.py
"""

import json
from pathlib import Path
from urllib.request import Request, urlopen

from Bio import Align

HERE = Path(__file__).resolve().parent
HUMAN = "P49419"
TARGET = "A0A9L0RRL6"
HORSE_GENE = "ENSECAG00000010547"
SEGMENT = (65, 82)
CATALYTIC = {296: "E", 330: "C"}


def get(url: str, accept: str = "text/plain") -> str:
    with urlopen(Request(url, headers={"Accept": accept})) as r:
        return r.read().decode()


def fasta_seq(acc: str) -> str:
    text = get(f"https://rest.uniprot.org/uniprotkb/{acc}.fasta")
    return "".join(text.splitlines()[1:])


def horse_family_entries() -> list[dict]:
    url = (
        "https://rest.uniprot.org/uniprotkb/search?query=xref:panther-PTHR43521"
        "+AND+organism_id:9796&fields=accession,length,xref_ensembl,fragment&format=tsv"
    )
    rows = get(url).strip().splitlines()[1:]
    out = []
    for row in rows:
        acc, length, ens, frag = (row.split("\t") + ["", "", ""])[:4]
        out.append({"accession": acc, "length": int(length), "ensembl_transcript": ens.strip(";").split(".")[0], "fragment": frag})
    return out


def ensembl_transcripts() -> dict:
    d = json.loads(get(f"https://rest.ensembl.org/lookup/id/{HORSE_GENE}?expand=1", "application/json"))
    out = {}
    for t in d["Transcript"]:
        tl = t.get("Translation")
        if not tl:
            continue
        lo, hi = tl["start"], tl["end"]
        exons = sorted(t["Exon"], key=lambda e: e["start"], reverse=t["strand"] == -1)
        cds = [min(e["end"], hi) - max(e["start"], lo) + 1 for e in exons if e["end"] >= lo and e["start"] <= hi]
        out[t["id"]] = {"is_canonical": bool(t.get("is_canonical")), "n_exons": len(exons), "coding_exon_nt": cds, "protein_length": tl["length"]}
    return out


def align(human: str, horse: str) -> dict:
    a = Align.PairwiseAligner()
    a.mode = "global"
    a.match_score, a.mismatch_score = 2, -1
    a.open_gap_score, a.extend_gap_score = -10, -0.5
    a.end_gap_score = 0
    aln = a.align(human, horse)[0]
    x, y = str(aln[0]), str(aln[1])
    hmap: dict[int, str] = {}
    hp = 0
    gaps: list[list[int]] = []
    for u, v in zip(x, y):
        if u != "-":
            hp += 1
            if v != "-":
                hmap[hp] = v
            elif gaps and gaps[-1][1] == hp - 1:
                gaps[-1][1] = hp
            else:
                gaps.append([hp, hp])
    pairs = [(u, v) for u, v in zip(x, y) if u != "-" and v != "-"]
    ident = sum(u == v for u, v in pairs)
    first, last = min(hmap), max(hmap)
    internal = [g for g in gaps if g[0] > first and g[1] < last]
    return {
        "identity_paired": round(ident / len(pairs), 4),
        "human_span_covered": [first, last],
        "internal_human_gaps": internal,
        "segment_65_82_present": all(i in hmap for i in range(SEGMENT[0], SEGMENT[1] + 1)),
        "catalytic": {str(k): hmap.get(k, "-") for k in CATALYTIC},
        "horse_insertions": sum(1 for u, v in zip(x, y) if u == "-" and v != "-"),
    }


def main() -> None:
    human = fasta_seq(HUMAN)
    entries = horse_family_entries()
    transcripts = ensembl_transcripts()
    for e in entries:
        e.update(align(human, fasta_seq(e["accession"])))
        e["ensembl"] = transcripts.get(e["ensembl_transcript"])
    result = {"human": HUMAN, "human_length": len(human), "target": TARGET, "horse_gene": HORSE_GENE, "entries": entries}
    (HERE / "results-rereview.json").write_text(json.dumps(result, indent=2) + "\n")
    lines = [
        "# ALDH7A1 horse gene models vs human P49419 (re-review)",
        "",
        f"Generated by `compare_horse_models_rereview.py` from live UniProt (PANTHER PTHR43521, taxon 9796) and Ensembl ({HORSE_GENE}) queries. Human reference P49419-1, {len(human)} aa.",
        "",
        "| Accession | Length | Ensembl transcript | Ensembl canonical | Exons | Identity (paired) | Human span | Internal human gaps | Human 65-82 present | Glu296 | Cys330 |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        ens = e["ensembl"] or {}
        lines.append(
            f"| {e['accession']} | {e['length']} | {e['ensembl_transcript'] or '-'} | {ens.get('is_canonical', '-')} | {ens.get('n_exons', '-')} | "
            f"{e['identity_paired']:.1%} | {e['human_span_covered'][0]}-{e['human_span_covered'][1]} | "
            f"{'; '.join(f'{a}-{b}' for a, b in e['internal_human_gaps']) or 'none'} | {e['segment_65_82_present']} | "
            f"{e['catalytic']['296']} | {e['catalytic']['330']} |"
        )
    lines += ["", "## Coding-exon lengths (nt) per Ensembl transcript", ""]
    for tid, t in transcripts.items():
        lines.append(f"- {tid} (canonical={t['is_canonical']}, {t['protein_length']} aa): {t['coding_exon_nt']}")
    paint = HERE.parents[3] / "interpro" / "panther" / "PTHR43521" / "PTHR43521-paint.tsv"
    lines += ["", f"## PAINT IBD assertions in PTHR43521 (from {paint.relative_to(HERE.parents[3])})", ""]
    for row in paint.read_text().splitlines()[1:]:
        f = row.split("\t")
        lines.append(f"- node {f[1]} asserts {f[2]} ({f[3]}, negated={f[5]}); seeds {f[6]}; taxon constraint '{f[7]}'")
    (HERE / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
