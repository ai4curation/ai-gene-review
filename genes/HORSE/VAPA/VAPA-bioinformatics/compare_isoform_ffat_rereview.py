"""Re-review analysis for horse VAPA A0A3Q2H1L9.

1. Align the horse sequence to human VAPA isoform 2 (Q9P0L0-2, built from the
   canonical sequence plus the VSP_038648 VAR_SEQ in the cached human record)
   and to the human canonical isoform 1, to determine which human isoform the
   horse gene model corresponds to.
2. Map the human MSP-domain FFAT-pocket residues named in PMID:33124732
   (K50, K52, T53, T54, K94, F95, M96, K125) onto the horse sequence.

Run from the repository root:
    uv run python genes/HORSE/VAPA/VAPA-bioinformatics/compare_isoform_ffat_rereview.py
"""

import json
import re
from pathlib import Path

from Bio import Align, SwissProt

here = Path(__file__).resolve().parent
horse_file = here.parent / "VAPA-uniprot.txt"
human_file = here.parents[2] / "human" / "VAPA" / "VAPA-uniprot.txt"

with horse_file.open() as f:
    horse = SwissProt.read(f)
with human_file.open() as f:
    human = SwissProt.read(f)

iso1 = human.sequence
varseq = next(
    feat
    for feat in human.features
    if feat.type == "VAR_SEQ" and "isoform 2" in feat.qualifiers.get("note", "")
)
note = varseq.qualifiers["note"].replace(" ", "")
m = re.match(r"([A-Z]+)->([A-Z]+)", note)
assert m, note
start = int(varseq.location.start)
end = int(varseq.location.end)
assert iso1[start:end] == m.group(1)
iso2 = iso1[:start] + m.group(2) + iso1[end:]

aligner = Align.PairwiseAligner()
aligner.mode = "global"
aligner.match_score = 2
aligner.mismatch_score = -1
aligner.open_gap_score = -10
aligner.extend_gap_score = -0.5


def summarise(ref: str, query: str) -> tuple[dict, dict[int, tuple[int, str]]]:
    aln = aligner.align(ref, query)[0]
    x, y = str(aln[0]), str(aln[1])
    pairs = [(u, v) for u, v in zip(x, y) if u != "-" and v != "-"]
    ident = sum(u == v for u, v in pairs)
    gaps_ref = x.count("-")
    gaps_query = y.count("-")
    mapping: dict[int, tuple[int, str]] = {}
    rp = qp = 0
    for u, v in zip(x, y):
        if u != "-":
            rp += 1
        if v != "-":
            qp += 1
        if u != "-" and v != "-":
            mapping[rp] = (qp, v)
    return (
        {
            "ref_length": len(ref),
            "query_length": len(query),
            "paired": len(pairs),
            "identical": ident,
            "identity": round(ident / len(pairs), 4),
            "gap_columns_in_ref": gaps_ref,
            "gap_columns_in_query": gaps_query,
        },
        mapping,
    )


res_iso1, map1 = summarise(iso1, horse.sequence)
res_iso2, _ = summarise(iso2, horse.sequence)

pocket = [50, 52, 53, 54, 94, 95, 96, 125]
pocket_rows = []
for pos in pocket:
    hpos, haa = map1.get(pos, (None, "-"))
    pocket_rows.append(
        {
            "human_position": pos,
            "human_residue": iso1[pos - 1],
            "horse_position": hpos,
            "horse_residue": haa,
            "identical": iso1[pos - 1] == haa,
        }
    )

result = {
    "horse_accession": horse.accessions[0],
    "human_accession": human.accessions[0],
    "human_isoform2_insert": m.group(2),
    "human_isoform2_insert_after_position": start,
    "vs_human_isoform1": res_iso1,
    "vs_human_isoform2": res_iso2,
    "ffat_pocket": pocket_rows,
}
(here / "results-rereview.json").write_text(json.dumps(result, indent=2) + "\n")

lines = [
    "# VAPA horse A0A3Q2H1L9: isoform correspondence and FFAT pocket (re-review)",
    "",
    "Generated by `compare_isoform_ffat_rereview.py` from the cached UniProt records; "
    "full numbers in `results-rereview.json`.",
    "",
    "## Isoform correspondence",
    "",
    "| Human reference | Ref length | Horse length | Paired | Identical | Identity | Gap columns (ref / horse) |",
    "|---|---|---|---|---|---|---|",
]
for label, r in (("Q9P0L0-1 (canonical)", res_iso1), ("Q9P0L0-2 (VSP_038648)", res_iso2)):
    lines.append(
        f"| {label} | {r['ref_length']} | {r['query_length']} | {r['paired']} | "
        f"{r['identical']} | {r['identity']:.1%} | {r['gap_columns_in_ref']} / {r['gap_columns_in_query']} |"
    )
lines += [
    "",
    "## FFAT-binding pocket residues (human numbering from PMID:33124732)",
    "",
    "| Human pos | Human aa | Horse pos | Horse aa | Identical |",
    "|---|---|---|---|---|",
]
for row in pocket_rows:
    lines.append(
        f"| {row['human_position']} | {row['human_residue']} | {row['horse_position']} | "
        f"{row['horse_residue']} | {row['identical']} |"
    )
lines += [
    "",
    "Residue conservation is necessary but not sufficient evidence of FFAT binding; "
    "it does not by itself demonstrate the activity in horse.",
    "",
]
(here / "RESULTS-rereview.md").write_text("\n".join(lines))
print(json.dumps(result, indent=2))
