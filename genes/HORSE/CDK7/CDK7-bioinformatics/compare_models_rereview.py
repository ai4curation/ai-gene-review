"""Re-review: compare all horse CDK7 UniProt models with human CDK7 (P50613).

Run from the repository root:
    uv run python genes/HORSE/CDK7/CDK7-bioinformatics/compare_models_rereview.py

Input: horse_CDK7_models-rereview.fasta (UniProt REST download of P50613,
A0A9L0R074 and every UniProt entry with gene:CDK7 in taxon 9796).
For each horse model it reports length, global-alignment identity to human
CDK7, which human positions are covered, whether key human residues are
conserved (ATP-site K41, catalytic D137, DFG D155, activation-loop S164 and
T170), and the length of any segment not aligned to human (extra tails or
inserts). Writes results-rereview.json and RESULTS-rereview.md.
"""

import json
from pathlib import Path

from Bio import Align, SeqIO

here = Path(__file__).resolve().parent
records = {r.id.split("|")[1]: str(r.seq) for r in SeqIO.parse(here / "horse_CDK7_models-rereview.fasta", "fasta")}
human = records.pop("P50613")
benchmark = "A0A9L0R074"

key_sites = {41: "K41 ATP-binding lysine", 137: "D137 catalytic", 155: "D155 DFG", 164: "S164 activation loop",
             170: "T170 activation loop (CAK/CDK7 T-loop phosphosite)"}
aligner = Align.PairwiseAligner(mode="global", match_score=2, mismatch_score=-1, open_gap_score=-10,
                                extend_gap_score=-0.5)

results = []
for acc, seq in records.items():
    aln = aligner.align(human, seq)[0]
    hmap = {}
    for (s, e), (t, u) in zip(*aln.aligned):
        for i, j in zip(range(s, e), range(t, u)):
            hmap[i] = j
    ident = sum(human[i] == seq[j] for i, j in hmap.items())
    covered_h = sorted(hmap)
    aligned_q = set(hmap.values())
    unaligned_q = [j for j in range(len(seq)) if j not in aligned_q]
    sites = {}
    for pos, name in key_sites.items():
        j = hmap.get(pos - 1)
        sites[name] = None if j is None else f"{seq[j]}{j + 1}"
    last_h = covered_h[-1] + 1 if covered_h else None
    first_h = covered_h[0] + 1 if covered_h else None
    results.append({
        "accession": acc,
        "length": len(seq),
        "identical_to_benchmark_prefix_1_337": seq[:337] == records[benchmark][:337],
        "paired_residues": len(hmap),
        "identity_percent_over_paired": round(100 * ident / len(hmap), 2) if hmap else None,
        "human_range_covered": [first_h, last_h],
        "human_residues_not_covered": len(human) - len(hmap),
        "horse_residues_unaligned_to_human": len(unaligned_q),
        "key_sites": sites,
    })

(here / "results-rereview.json").write_text(json.dumps(results, indent=2) + "\n")
lines = [
    "# CDK7 re-review: horse UniProt CDK7 models vs human P50613",
    "",
    f"Human CDK7 (P50613) is {len(human)} residues. Global alignment (Biopython PairwiseAligner, match 2,"
    " mismatch -1, gap open -10, extend -0.5) of each horse model to human. Generated by"
    " compare_models_rereview.py; raw values in results-rereview.json.",
    "",
    "| accession | length | identity % (paired) | human range covered | human residues missing |"
    " horse residues unaligned | K41 | D137 | D155 | S164 | T170 |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]
for r in results:
    s = list(r["key_sites"].values())
    lines.append(
        f"| {r['accession']} | {r['length']} | {r['identity_percent_over_paired']} | "
        f"{r['human_range_covered'][0]}-{r['human_range_covered'][1]} | {r['human_residues_not_covered']} | "
        f"{r['horse_residues_unaligned_to_human']} | "
        + " | ".join(str(x) for x in s) + " |")
lines.append("")
ref = records["K9K3U4"]
b = records[benchmark]
n = next(i for i in range(min(len(ref), len(b))) if ref[i] != b[i])
lines += [
    "## Benchmark C-terminus vs the transcript-supported horse model K9K3U4",
    "",
    f"{benchmark} and K9K3U4 are identical for residues 1-{n}. After that K9K3U4 ends"
    f" `{ref[n:]}` ({len(ref) - n} residues), whereas {benchmark} continues with"
    f" `{b[n:]}` ({len(b) - n} residues).",
    "",
]
(here / "RESULTS-rereview.md").write_text("\n".join(lines))
print("\n".join(lines))
