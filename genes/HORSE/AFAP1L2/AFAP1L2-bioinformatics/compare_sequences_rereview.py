"""Re-review: compare horse AFAP1L2 gene models with human and mouse AFAP1L2.

Inputs (all local): benchmark horse A0A9L0RQI4 (../AFAP1L2-uniprot.txt), human
Q8N4X5 (genes/human/AFAP1L2/AFAP1L2-uniprot.txt), mouse Q5DTU0 and all ten horse
AFAP1L2 TrEMBL models (FASTA downloaded from UniProt REST into this folder).
Writes RESULTS-rereview.md and results-rereview.json.

For each sequence it reports identity to human over paired residues, where the
human start Met lands, the length of N-terminal / internal insertions relative to
human, and conservation of selected human features. It does not test function.
"""

from pathlib import Path
import json
from Bio import Align, SeqIO, SwissProt

here = Path(__file__).resolve().parent
with (here.parent / "AFAP1L2-uniprot.txt").open() as f:
    bench = SwissProt.read(f)
with (here.parents[2] / "human" / "AFAP1L2" / "AFAP1L2-uniprot.txt").open() as f:
    human = SwissProt.read(f)
mouse = str(next(SeqIO.parse(here / "Q5DTU0-rereview.fasta", "fasta")).seq)
horse_models = {
    rec.id.split("|")[1]: str(rec.seq)
    for rec in SeqIO.parse(here / "horse-AFAP1L2-models-rereview.fasta", "fasta")
}

aligner = Align.PairwiseAligner()
aligner.mode = "global"
aligner.substitution_matrix = Align.substitution_matrices.load("BLOSUM62")
aligner.open_gap_score = -10
aligner.extend_gap_score = -0.5
aligner.target_end_gap_score = 0
aligner.query_end_gap_score = 0

# Human Q8N4X5 positions (1-based). PH domains from UniProt FT lines; Tyr54 is the
# RET/PTC phosphorylation site that binds p85 SH2 domains (PMID:19060924);
# N-terminal 167 aa and C-terminal 63 aa are required for lamellipodial
# translocation (PMID:21084565); coiled coil from UniProt FT COILED.
features = {
    "N-terminal SH2/SH3-binding region (1-167)": (1, 167),
    "Tyr54 (p85 SH2-binding phosphosite)": (54, 54),
    "PH 1 (175-271)": (175, 271),
    "PH 2 (353-447)": (353, 447),
    "Coiled coil (652-749)": (652, 749),
    "C-terminal 63 aa (756-818)": (756, 818),
}


def compare(model: str) -> dict:
    aln = aligner.align(human.sequence, model)[0]
    x, y = str(aln[0]), str(aln[1])
    pos_map: dict[int, tuple[int, bool]] = {}
    insertions: list[tuple[int, int]] = []  # (after human pos, length)
    hp = mp = 0
    run = 0
    for u, v in zip(x, y):
        if u == "-":
            run += 1
        else:
            if run:
                insertions.append((hp, run))
                run = 0
            hp += 1
        if v != "-":
            mp += 1
        if u != "-" and v != "-":
            pos_map[hp] = (mp, u == v)
    if run:
        insertions.append((hp, run))
    deletions = sum(1 for i in range(1, len(human.sequence) + 1) if i not in pos_map)
    ident = sum(1 for _, same in pos_map.values() if same)
    feats = {}
    for name, (s, e) in features.items():
        mapped = [pos_map[i] for i in range(s, e + 1) if i in pos_map]
        feats[name] = {
            "model_positions": f"{mapped[0][0]}-{mapped[-1][0]}" if mapped else None,
            "paired": len(mapped),
            "identical": sum(1 for _, same in mapped if same),
            "length": e - s + 1,
        }
    return {
        "length": len(model),
        "paired_with_human": len(pos_map),
        "identity_among_paired": round(ident / len(pos_map), 4),
        "human_residues_missing": deletions,
        "insertions_vs_human": [
            {"after_human_pos": a, "length": n} for a, n in insertions if n >= 3
        ],
        "features": feats,
        "first_20": model[:20],
    }


results = {
    "human_reference": {"accession": "Q8N4X5", "length": len(human.sequence)},
    "benchmark_A0A9L0RQI4": compare(bench.sequence),
    "mouse_Q5DTU0": compare(mouse),
    "horse_models": {acc: compare(seq) for acc, seq in sorted(horse_models.items())},
}
(here / "results-rereview.json").write_text(json.dumps(results, indent=2) + "\n")

lines = [
    "# AFAP1L2 re-review: horse gene models vs human Q8N4X5",
    "",
    "Generated by `compare_sequences_rereview.py` (Biopython global alignment, BLOSUM62,"
    " gap open -10, extend -0.5, free end gaps). Inputs: horse A0A9L0RQI4 UniProt text,"
    " human Q8N4X5 UniProt text, mouse Q5DTU0 and ten horse AFAP1L2 TrEMBL FASTA records"
    " downloaded from UniProt REST.",
    "",
    "## Summary per sequence",
    "",
    "| Sequence | Length | Paired with human | Identity | Human residues missing | Insertions >=3 aa (after human pos:len) | First 20 aa |",
    "|---|---|---|---|---|---|---|",
]


def row(name: str, r: dict) -> str:
    ins = ", ".join(f"{i['after_human_pos']}:{i['length']}" for i in r["insertions_vs_human"]) or "none"
    return (
        f"| {name} | {r['length']} | {r['paired_with_human']} | {r['identity_among_paired']:.3f} | "
        f"{r['human_residues_missing']} | {ins} | {r['first_20']} |"
    )


lines.append(row("A0A9L0RQI4 (benchmark)", results["benchmark_A0A9L0RQI4"]))
lines.append(row("mouse Q5DTU0", results["mouse_Q5DTU0"]))
for acc, r in results["horse_models"].items():
    if acc != "A0A9L0RQI4":
        lines.append(row(f"horse {acc}", r))
lines += [
    "",
    "## Human feature conservation in benchmark A0A9L0RQI4",
    "",
    "| Human feature | Horse positions | Paired / length | Identical |",
    "|---|---|---|---|",
]
for name, f in results["benchmark_A0A9L0RQI4"]["features"].items():
    lines.append(f"| {name} | {f['model_positions']} | {f['paired']}/{f['length']} | {f['identical']}/{f['length']} |")
lines.append("")
(here / "RESULTS-rereview.md").write_text("\n".join(lines))
print("\n".join(lines))
