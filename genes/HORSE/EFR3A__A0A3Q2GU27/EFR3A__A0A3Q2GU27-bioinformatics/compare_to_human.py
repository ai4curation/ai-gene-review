"""Align horse EFR3A A0A3Q2GU27 to human EFR3A Q14156 and report conservation of
experimentally defined functional elements.

Run from the repository root:
    uv run python genes/HORSE/EFR3A__A0A3Q2GU27/EFR3A__A0A3Q2GU27-bioinformatics/compare_to_human.py

Inputs are the cached UniProt flat files in this repository (no network).
Functional elements (human/mouse numbering, both 821 aa):
  - Cys6-Cys9 palmitoylation cluster (PMID:23229899, human EFR3A C6S/C7S/C8S/C9S)
  - basic patch K50, R53, R61, R68, R70 (PMID:24360784, mouse EFR3A mutant)
  - C-terminal TTC7B/FAM126A-binding region 724-787 (PMID:39705356)
Writes results.json and RESULTS.md next to this script. Nothing is hardcoded.
"""

import json
from pathlib import Path

from Bio import Align, SeqIO

here = Path(__file__).resolve().parent
root = next(p for p in here.parents if (p / "pyproject.toml").exists())

horse = SeqIO.read(root / "genes/HORSE/EFR3A__A0A3Q2GU27/EFR3A__A0A3Q2GU27-uniprot.txt", "swiss")
human = SeqIO.read(root / "genes/human/EFR3A/EFR3A-uniprot.txt", "swiss")
hs, eq = str(human.seq), str(horse.seq)

aligner = Align.PairwiseAligner(
    mode="global", match_score=2, mismatch_score=-1, open_gap_score=-10, extend_gap_score=-0.5
)
aln = aligner.align(hs, eq)[0]
hmap: dict[int, int] = {}
for (s, e), (t, u) in zip(*aln.aligned):
    for i, j in zip(range(s, e), range(t, u)):
        hmap[i + 1] = j + 1  # 1-based human -> horse


def region_identity(start: int, end: int) -> dict:
    pos = range(start, end + 1)
    paired = [p for p in pos if p in hmap]
    same = [p for p in paired if hs[p - 1] == eq[hmap[p] - 1]]
    diffs = [f"{hs[p-1]}{p}{eq[hmap[p]-1]}" for p in paired if hs[p - 1] != eq[hmap[p] - 1]]
    return {
        "human_range": f"{start}-{end}",
        "length": len(pos),
        "paired": len(paired),
        "identical": len(same),
        "percent_identity": round(100 * len(same) / len(pos), 2),
        "substitutions": diffs,
    }


def sites(positions: list[int]) -> list[str]:
    return [
        f"{hs[p-1]}{p}->{eq[hmap[p]-1]}{hmap[p]}" if p in hmap else f"{hs[p-1]}{p}->gap"
        for p in positions
    ]


res = {
    "horse": {"accession": horse.id, "length": len(eq)},
    "human": {"accession": human.id, "length": len(hs)},
    "whole_protein": region_identity(1, len(hs)),
    "palmitoylation_cluster_C6_C9": sites([6, 7, 8, 9]),
    "basic_patch": sites([50, 53, 61, 68, 70]),
    "c_terminal_ttc7_binding_724_787": region_identity(724, 787),
    "horse_dr_panther": [x for x in horse.dbxrefs if x.startswith("PANTHER")],
}
(here / "results.json").write_text(json.dumps(res, indent=2) + "\n")

w = res["whole_protein"]
c = res["c_terminal_ttc7_binding_724_787"]
md = f"""# EFR3A horse (A0A3Q2GU27) vs human (Q14156)

Generated by `compare_to_human.py` from cached UniProt records (Biopython PairwiseAligner,
global, match 2, mismatch -1, gap open -10, extend -0.5).

- Horse length {res['horse']['length']} aa; human length {res['human']['length']} aa.
- Whole-protein identity: {w['identical']}/{w['length']} = {w['percent_identity']}% ({w['paired']} human residues paired).
- Substitutions (human->horse): {', '.join(w['substitutions']) or 'none'}
- Palmitoylation cluster Cys6-Cys9 (PMID:23229899): {', '.join(res['palmitoylation_cluster_C6_C9'])}
- Basic patch (PMID:24360784 mouse numbering, same as human): {', '.join(res['basic_patch'])}
- C-terminal TTC7B/FAM126A-binding region 724-787 (PMID:39705356): {c['identical']}/{c['length']} identical ({c['percent_identity']}%); substitutions: {', '.join(c['substitutions']) or 'none'}
- PANTHER cross-references in horse record: {', '.join(res['horse_dr_panther'])}
"""
(here / "RESULTS.md").write_text(md)
print(md)
