"""Re-review: compare the seven horse CC2D2A gene models with human and mouse CC2D2A.

Inputs (all local): human Q9P2K1 (genes/human/CC2D2A/CC2D2A-uniprot.txt), mouse
Q8CFW7 (Q8CFW7-rereview.fasta) and all seven horse CC2D2A TrEMBL models
(horse-CC2D2A-models-rereview.fasta, downloaded from UniProt REST with
query gene:CC2D2A AND organism_id:9796). The benchmark model is A0A5F5PJ44.
Writes RESULTS-rereview.md and results-rereview.json.

For each sequence: length, identity to human over paired residues, which human
residue the model's first residue pairs with, human residue intervals with no
aligned model residue (gaps of >= 5), and coverage of selected human features
taken from the human UniProt FT lines. It does not test function.
"""

from pathlib import Path
import json
from Bio import Align, SeqIO, SwissProt

here = Path(__file__).resolve().parent
with (here.parents[2] / "human" / "CC2D2A" / "CC2D2A-uniprot.txt").open() as f:
    human = SwissProt.read(f)
seqs = {"mouse Q8CFW7": str(next(SeqIO.parse(here / "Q8CFW7-rereview.fasta", "fasta")).seq)}
for rec in SeqIO.parse(here / "horse-CC2D2A-models-rereview.fasta", "fasta"):
    seqs["horse " + rec.id.split("|")[1]] = str(rec.seq)

aligner = Align.PairwiseAligner()
aligner.mode = "global"
aligner.substitution_matrix = Align.substitution_matrices.load("BLOSUM62")
aligner.open_gap_score = -10
aligner.extend_gap_score = -0.5
aligner.target_end_gap_score = 0
aligner.query_end_gap_score = 0

# Human Q9P2K1 intervals from its UniProt FT lines.
features = {
    "N-terminal disordered region (1-241)": (1, 241),
    "isoform-2 N-terminal VAR_SEQ, missing (1-49)": (1, 49),
    "coiled coil (439-493)": (439, 493),
    "coiled coil (532-582)": (532, 582),
    "C2 domain (1025-1203)": (1025, 1203),
    "isoform-2 internal VAR_SEQ, missing (1199-1257)": (1199, 1257),
    "C-terminal region (1258-1620)": (1258, 1620),
}


def compare(model: str) -> dict:
    aln = aligner.align(human.sequence, model)[0]
    x, y = str(aln[0]), str(aln[1])
    pos_map: dict[int, tuple[int, bool]] = {}
    hp = mp = 0
    for u, v in zip(x, y):
        if u != "-":
            hp += 1
        if v != "-":
            mp += 1
        if u != "-" and v != "-":
            pos_map[hp] = (mp, u == v)
    gaps = []
    start = None
    for i in range(1, len(human.sequence) + 2):
        missing = i <= len(human.sequence) and i not in pos_map
        if missing and start is None:
            start = i
        if not missing and start is not None:
            if i - start >= 5:
                gaps.append(f"{start}-{i - 1}")
            start = None
    ident = sum(1 for _, same in pos_map.values() if same)
    first_human = min(h for h, (m, _) in pos_map.items())
    feats = {}
    for name, (s, e) in features.items():
        mapped = [pos_map[i] for i in range(s, e + 1) if i in pos_map]
        feats[name] = {
            "paired": len(mapped),
            "length": e - s + 1,
            "identical": sum(1 for _, same in mapped if same),
        }
    return {
        "length": len(model),
        "paired_residues": len(pos_map),
        "identity_over_paired_pct": round(100 * ident / len(pos_map), 1),
        "first_paired_human_residue": first_human,
        "starts_with_met": model.startswith("M"),
        "human_gaps_ge5": gaps,
        "features": feats,
    }


results = {"human Q9P2K1 length": len(human.sequence)}
results.update({name: compare(s) for name, s in seqs.items()})
(here / "results-rereview.json").write_text(json.dumps(results, indent=2) + "\n")

lines = [
    "# CC2D2A re-review: horse gene models vs human and mouse",
    "",
    "Generated by `compare_sequences_rereview.py` (global BLOSUM62 alignment to human",
    f"Q9P2K1, {len(human.sequence)} aa; free end gaps). Feature intervals are human UniProt FT positions.",
    "",
    "| sequence | length | paired | identity % | first paired human residue | human gaps (>=5 aa) |",
    "|---|---|---|---|---|---|",
]
for name, r in results.items():
    if not isinstance(r, dict):
        continue
    lines.append(
        f"| {name} | {r['length']} | {r['paired_residues']} | {r['identity_over_paired_pct']} | "
        f"{r['first_paired_human_residue']} | {', '.join(r['human_gaps_ge5']) or 'none'} |"
    )
lines += ["", "## Feature coverage (paired/length, identical)", ""]
for name, r in results.items():
    if not isinstance(r, dict):
        continue
    cov = "; ".join(f"{k}: {v['paired']}/{v['length']} ({v['identical']} id)" for k, v in r["features"].items())
    lines.append(f"- {name}: {cov}")
(here / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
