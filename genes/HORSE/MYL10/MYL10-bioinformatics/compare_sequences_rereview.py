"""Re-review analysis for horse MYL10 (A0A9L0TJE1).

Compares the A0A9L0TJE1 conserved light-chain core against MYL10 orthologs
(PANTHER PTHR23049:SF36 members) and other human regulatory light chain paralogs,
builds a neighbour-joining tree from core-region pairwise distances, and compares
the four horse MYL10 gene-model entries.

Input: rlc_family_sequences_rereview.fa (UniProt REST FASTA, fetched 2026-10-20).
Run from the repository root:
    uv run python genes/HORSE/MYL10/MYL10-bioinformatics/compare_sequences_rereview.py
"""

import json
from pathlib import Path

from Bio import Align, SeqIO
from Bio.Phylo.TreeConstruction import DistanceMatrix, DistanceTreeConstructor
from Bio import Phylo
import io

HERE = Path(__file__).resolve().parent
FASTA = HERE / "rlc_family_sequences_rereview.fa"
TARGET = "A0A9L0TJE1"
CORE_START_MOTIF = "SNVF"  # start of the conserved RLC core (after the variable N-terminus)

records = {r.id.split("|")[1]: r for r in SeqIO.parse(FASTA, "fasta")}
labels = {acc: r.id.split("|")[2] for acc, r in records.items()}
seqs = {acc: str(r.seq) for acc, r in records.items()}


def core(seq: str) -> str:
    i = seq.find(CORE_START_MOTIF)
    return seq[i:] if i >= 0 else seq


aligner = Align.PairwiseAligner()
aligner.mode = "global"
aligner.substitution_matrix = Align.substitution_matrices.load("BLOSUM62")
aligner.open_gap_score = -10
aligner.extend_gap_score = -0.5
aligner.end_gap_score = 0


def identity(a: str, b: str) -> tuple[int, int, int]:
    aln = aligner.align(a, b)[0]
    x, y = str(aln[0]), str(aln[1])
    pairs = [(u, v) for u, v in zip(x, y) if u != "-" and v != "-"]
    gaps = sum(1 for u, v in zip(x, y) if (u == "-") != (v == "-"))
    return sum(u == v for u, v in pairs), len(pairs), gaps


horse_models = [a for a in seqs if labels[a].endswith("_HORSE")]
tree_set = [a for a in seqs if a not in horse_models or a == TARGET]

# identities of the target core to each other sequence core
rows = []
for acc in seqs:
    if acc == TARGET:
        continue
    ident, paired, gaps = identity(core(seqs[TARGET]), core(seqs[acc]))
    rows.append(
        {
            "accession": acc,
            "entry": labels[acc],
            "length": len(seqs[acc]),
            "core_identical": ident,
            "core_paired": paired,
            "core_identity": round(ident / paired, 3),
            "core_gap_columns": gaps,
        }
    )
rows.sort(key=lambda r: -r["core_identity"])

# distance matrix on cores for the NJ tree (one horse model only)
names = [labels[a] for a in tree_set]
matrix = []
for i, a in enumerate(tree_set):
    row = []
    for j in range(i + 1):
        if i == j:
            row.append(0.0)
        else:
            ident, paired, _ = identity(core(seqs[a]), core(seqs[tree_set[j]]))
            row.append(round(1 - ident / paired, 4))
    matrix.append(row)
dm = DistanceMatrix(names, matrix)
tree = DistanceTreeConstructor().nj(dm)
tree.root_at_midpoint()
buf = io.StringIO()
Phylo.write(tree, buf, "newick")
newick = buf.getvalue().strip()
ascii_buf = io.StringIO()
Phylo.draw_ascii(tree, file=ascii_buf)

# horse gene models: shared core, differing N-termini
model_rows = []
for acc in horse_models:
    s = seqs[acc]
    model_rows.append(
        {
            "accession": acc,
            "length": len(s),
            "core_start": s.find(CORE_START_MOTIF) + 1 if CORE_START_MOTIF in s else None,
            "n_terminal_extension": s[: s.find(CORE_START_MOTIF)] if CORE_START_MOTIF in s else s[:20],
            "ends_with_canonical_C_terminus": s.endswith("HGEEKD"),
        }
    )

# EF-hand 1 loop (canonical RLC Ca/Mg-binding loop DxDxDGxxDxxE)
loop = "DQNRDGFIDKED"
loop_hits = {labels[a]: (seqs[a].find(loop) + 1 if loop in seqs[a] else None) for a in seqs}

# lineage-specific insertion in human MYL10 relative to mouse/rat/horse
human_insert = None
hm = seqs["Q9BUA6"]
i = hm.find("QIQEFKE") + len("QIQEFKE")
j = hm.find("AFTIMDQNR")
if i > 0 and j > i:
    human_insert = {"start": i + 1, "end": j, "sequence": hm[i:j]}

result = {
    "target": TARGET,
    "target_length": len(seqs[TARGET]),
    "target_core_length": len(core(seqs[TARGET])),
    "core_identity_to_target": rows,
    "horse_gene_models": model_rows,
    "ef_hand1_loop_DQNRDGFIDKED_position": loop_hits,
    "human_MYL10_insertion_absent_from_rodent_and_horse": human_insert,
    "nj_tree_newick": newick,
    "aligner": "global BLOSUM62, gap open -10, extend -0.5, free end gaps",
}
(HERE / "results-rereview.json").write_text(json.dumps(result, indent=2) + "\n")

lines = [
    "# MYL10 (horse A0A9L0TJE1): re-review family placement and gene-model comparison",
    "",
    "Generated by `compare_sequences_rereview.py` from `rlc_family_sequences_rereview.fa`",
    "(UniProt REST, fetched 2026-10-20). Numbers below are computed, not hand-entered.",
    "",
    f"Target length {len(seqs[TARGET])} aa; conserved core (from `{CORE_START_MOTIF}`) "
    f"{len(core(seqs[TARGET]))} aa.",
    "",
    "## Core identity of A0A9L0TJE1 to MYL10 orthologs and RLC paralogs",
    "",
    "| Accession | Entry | Length | Core identical/paired | Core identity | Gap columns |",
    "|---|---|---|---|---|---|",
]
for r in rows:
    lines.append(
        f"| {r['accession']} | {r['entry']} | {r['length']} | {r['core_identical']}/{r['core_paired']} "
        f"| {r['core_identity']:.3f} | {r['core_gap_columns']} |"
    )
lines += [
    "",
    "## Neighbour-joining tree (core-region p-distances, midpoint rooted)",
    "",
    "```",
    ascii_buf.getvalue().rstrip(),
    "```",
    "",
    f"Newick: `{newick}`",
    "",
    "## Horse MYL10 gene-model entries",
    "",
    "| Accession | Length | Core start | N-terminal segment before core | Canonical C-terminus |",
    "|---|---|---|---|---|",
]
for m in model_rows:
    lines.append(
        f"| {m['accession']} | {m['length']} | {m['core_start']} | `{m['n_terminal_extension']}` "
        f"| {m['ends_with_canonical_C_terminus']} |"
    )
lines += [
    "",
    "## EF-hand 1 loop `DQNRDGFIDKED` position",
    "",
    "| Entry | Position |",
    "|---|---|",
]
for k, v in loop_hits.items():
    lines.append(f"| {k} | {v} |")
lines += ["", "## Human MYL10-specific insertion", ""]
if human_insert:
    lines.append(
        f"Human Q9BUA6 residues {human_insert['start']}-{human_insert['end']} "
        f"(`{human_insert['sequence']}`, {len(human_insert['sequence'])} aa) sit between `QIQEFKE` and "
        "`AFTIMDQNR`; mouse, rat and horse MYL10 join these two segments directly."
    )
lines += [
    "",
    "Pairwise-distance NJ on a short, highly conserved domain is a coarse check of",
    "subfamily placement, not a substitute for the PANTHER HMM classification.",
]
(HERE / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
