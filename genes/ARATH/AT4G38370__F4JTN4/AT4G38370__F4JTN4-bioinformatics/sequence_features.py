"""Entry identity and simple localisation-relevant sequence features for F4JTN4 (At4g38370).

Fetches F4JTN4 and Q0WW53 from UniProt REST, checks sequence identity, scans for
classical monopartite (pat4/pat7) and bipartite nuclear localisation signal
patterns, and reports N-terminal hydrophobicity (Kyte-Doolittle) as a crude check
for a secretory signal peptide. These are heuristics; results are written to
RESULTS.md and are reported whatever they show.
"""
import re
import requests

KD = {"A": 1.8, "R": -4.5, "N": -3.5, "D": -3.5, "C": 2.5, "Q": -3.5, "E": -3.5,
      "G": -0.4, "H": -3.2, "I": 4.5, "L": 3.8, "K": -3.9, "M": 1.9, "F": 2.8,
      "P": -1.6, "S": -0.8, "T": -0.7, "W": -0.9, "Y": -1.3, "V": 4.2}


def fetch(acc: str) -> str:
    r = requests.get(f"https://rest.uniprot.org/uniprotkb/{acc}.fasta", timeout=60)
    r.raise_for_status()
    return "".join(r.text.splitlines()[1:])


def main() -> None:
    f4 = fetch("F4JTN4")
    q0 = fetch("Q0WW53")
    lines = ["# F4JTN4 (At4g38370) sequence features", "",
             "Generated by `sequence_features.py` (run with `uv run --script`); sequences fetched live from UniProt REST.", "",
             "## Entry identity", "",
             f"- F4JTN4 length: {len(f4)}",
             f"- Q0WW53 length: {len(q0)}",
             f"- Identical sequences: {f4 == q0}", ""]
    pat4 = [(m.start() + 1, m.group(1)) for m in re.finditer(r"(?=([KR]{4}|[KR]{3}H|[KR]{2}H[KR]|[KR]H[KR]{2}|H[KR]{3}))", f4)]
    pat7 = [(m.start() + 1, m.group(1)) for m in re.finditer(r"(?=(P.{2}[KR]{3}|P.{2}[KR]{2}.[KR]|P.{2}[KR].[KR]{2}))", f4)]
    bip = [(m.start() + 1, m.group(1)) for m in re.finditer(r"(?=([KR]{2}.{10,12}[KR]{3}))", f4)]
    lines += ["## Classical NLS pattern scan (PSORT-style heuristics)", "",
              f"- pat4 matches: {pat4 if pat4 else 'none'}",
              f"- pat7 matches: {pat7 if pat7 else 'none'}",
              f"- bipartite KR-x(10-12)-KRR-type matches: {bip if bip else 'none'}", ""]
    nterm = f4[:30]
    win = 11
    scores = [sum(KD[a] for a in nterm[i:i + win]) / win for i in range(len(nterm) - win + 1)]
    best = max(scores)
    lines += ["## N-terminal hydrophobicity (residues 1-30, Kyte-Doolittle, window 11)", "",
              f"- N-terminal 30 residues: {nterm}",
              f"- maximum window mean: {best:.2f} (a signal-peptide h-region typically exceeds ~1.6)",
              f"- K+R count in residues 1-30: {sum(nterm.count(x) for x in 'KR')}; D+E count: {sum(nterm.count(x) for x in 'DE')}", "",
              "Interpretation: a classical NLS is reported only if a pattern matches; absence of a match does not exclude nuclear entry, which a ~25 kDa protein can achieve by diffusion. These heuristics are not localisation evidence in either direction beyond what they state.", ""]
    out = "\n".join(lines)
    print(out)
    with open(__file__.replace("sequence_features.py", "RESULTS.md"), "w") as fh:
        fh.write(out)


if __name__ == "__main__":
    main()
