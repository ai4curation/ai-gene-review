"""Re-review: map UniProt-curated catalytic residues of characterized
histidine-phosphatase branch-1 (PGAM-like) enzymes onto AT4G38370.

Inputs are fetched live from UniProt REST (Q0WW53, F4JTN4, Q8LCU4 and the
Swiss-Prot reference enzymes). Output: RESULTS-rereview.md + results-rereview.json.
"""
import json
from pathlib import Path

import requests
from Bio import Align
from Bio.Align import substitution_matrices

TARGETS = ["Q0WW53", "F4JTN4", "Q8LCU4"]
# Swiss-Prot references with curated active sites (fold-level comparators only)
REFS = {
    "P18669": "human PGAM1 (2,3-bisphosphoglycerate-dependent phosphoglycerate mutase)",
    "P62707": "E. coli GpmA (2,3-bisphosphoglycerate-dependent phosphoglycerate mutase)",
    "Q9NQ88": "human TIGAR (fructose-2,6-bisphosphatase)",
}
OUT = Path(__file__).parent


def fetch(acc: str) -> dict:
    r = requests.get(f"https://rest.uniprot.org/uniprotkb/{acc}.json", timeout=60)
    r.raise_for_status()
    return r.json()


def main() -> None:
    entries = {a: fetch(a) for a in TARGETS + list(REFS)}
    seqs = {a: e["sequence"]["value"] for a, e in entries.items()}
    target = seqs["Q0WW53"]
    out: dict = {"identity": {}, "references": {}}
    for a in ["F4JTN4", "Q8LCU4"]:
        s = seqs[a]
        diffs = [
            f"{target[i]}{i+1}{s[i]}" for i in range(min(len(s), len(target))) if s[i] != target[i]
        ]
        out["identity"][a] = {"length": len(s), "differences_vs_Q0WW53": diffs,
                              "same_length": len(s) == len(target)}
    aligner = Align.PairwiseAligner()
    aligner.substitution_matrix = substitution_matrices.load("BLOSUM62")
    aligner.open_gap_score = -10
    aligner.extend_gap_score = -0.5
    aligner.mode = "local"
    for ref, desc in REFS.items():
        rs = seqs[ref]
        aln = aligner.align(rs, target)[0]
        # map ref position -> target position
        mapping = {}
        ident = 0
        alen = 0
        for (rs0, re0), (ts0, te0) in zip(*aln.aligned):
            for k in range(int(re0 - rs0)):
                mapping[int(rs0) + k + 1] = int(ts0) + k + 1
                alen += 1
                if rs[rs0 + k] == target[ts0 + k]:
                    ident += 1
        feats = []
        for f in entries[ref].get("features", []):
            if f["type"] in ("Active site", "Binding site", "Site"):
                p = f["location"]["start"]["value"]
                q = f["location"]["end"]["value"]
                if p != q:
                    continue
                tp = mapping.get(p)
                feats.append({
                    "type": f["type"], "description": f.get("description", ""),
                    "ligand": f.get("ligand", {}).get("name", ""),
                    "ref_pos": p, "ref_res": rs[p - 1],
                    "target_pos": tp, "target_res": target[tp - 1] if tp else None,
                })
        out["references"][ref] = {
            "description": desc, "length": len(rs), "aligned_pairs": alen,
            "identical": ident, "pct_identity_aligned": round(100 * ident / alen, 1) if alen else 0,
            "features": feats,
        }
    # simple motif scan
    import re
    motifs = {}
    for name, pat in {"RHG (branch-1 nucleophile motif)": r"RHG", "E proton donor context (xRERxxG)": r"[LIVM]RER..G",
                      "C-terminal HG": r"S?HG[DN]"}.items():
        motifs[name] = [(m.start() + 1, m.group()) for m in re.finditer(pat, target)]
    out["motifs"] = motifs
    (OUT / "results-rereview.json").write_text(json.dumps(out, indent=2))
    lines = ["# AT4G38370 re-review: entry identity and catalytic-residue mapping", "",
             "Generated by `catalytic_residues_rereview.py` (run with `uv run --script`). "
             "Sequences and curated features fetched live from UniProt REST.", "",
             "## Entry identity (same locus At4g38370)", ""]
    for a, v in out["identity"].items():
        lines.append(f"- {a}: length {v['length']}; differences vs Q0WW53: {v['differences_vs_Q0WW53'] or 'none (identical)'}")
    lines += ["", "## Motif scan on Q0WW53", ""]
    for k, v in motifs.items():
        lines.append(f"- {k}: {v}")
    lines += ["", "## Mapping of curated sites from Swiss-Prot branch-1 enzymes (local BLOSUM62 alignment)", ""]
    for ref, v in out["references"].items():
        lines.append(f"### {ref} {v['description']}")
        lines.append(f"Aligned pairs {v['aligned_pairs']}, identical {v['identical']} ({v['pct_identity_aligned']}%).")
        lines.append("")
        lines.append("| Feature | Ligand | Ref residue | Q0WW53 residue |")
        lines.append("|---|---|---|---|")
        for f in v["features"]:
            t = f"{f['target_res']}{f['target_pos']}" if f["target_pos"] else "unaligned"
            lines.append(f"| {f['type']}: {f['description']} | {f['ligand']} | {f['ref_res']}{f['ref_pos']} | {t} |")
        lines.append("")
    lines.append("Fold-level comparators only: none of these references is in PANTHER PTHR47821, so the mapping "
                 "tests retention of the shared histidine-phosphatase catalytic apparatus, not substrate identity.")
    (OUT / "RESULTS-rereview.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
