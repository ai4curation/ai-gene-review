"""Pairwise comparison of PA4022 (Q9HX05) with ExaC.

Compares three sequences:
  * Q9HX05  PA4022, P. aeruginosa PAO1 (cached gene folder)
  * Q9ZAA1  ExaC, P. aeruginosa ATCC 17933, the characterized enzyme (cached gene folder)
  * Q9I2C4  exaC/PA1984, P. aeruginosa PAO1 (fetched live from the UniProt REST API)

Each pair is globally aligned (BLOSUM62, open -10, extend -0.5); percent identity
is reported over aligned columns. The ALDH catalytic residues of ExaC (Glu262 and
the Cys301 nucleophile, UniProt ACT_SITE features) are mapped onto PA4022.
Writes RESULTS.md beside this script.

Usage (from repo root):
    uv run python genes/PSEAE/PA4022/PA4022-bioinformatics/pairwise_exac.py
"""
from pathlib import Path

import requests
from Bio import Align
from Bio.Align import substitution_matrices

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def read_flatfile_seq(path: Path) -> str:
    """Return the sequence from a UniProt flat file."""
    lines = path.read_text().splitlines()
    i = next(n for n, line in enumerate(lines) if line.startswith("SQ   "))
    seq = []
    for line in lines[i + 1:]:
        if line.startswith("//"):
            break
        seq.append(line.replace(" ", ""))
    return "".join(seq)


def fetch_fasta_seq(acc: str) -> str:
    """Fetch a sequence from UniProt REST (external system)."""
    r = requests.get(f"https://rest.uniprot.org/uniprotkb/{acc}.fasta", timeout=60)
    r.raise_for_status()
    return "".join(r.text.splitlines()[1:])


def make_aligner() -> Align.PairwiseAligner:
    """Return a BLOSUM62 global aligner."""
    al = Align.PairwiseAligner()
    al.substitution_matrix = substitution_matrices.load("BLOSUM62")
    al.open_gap_score = -10
    al.extend_gap_score = -0.5
    return al


def identity_and_map(al: Align.PairwiseAligner, x: str, y: str) -> tuple[float, dict[int, tuple[int, str]]]:
    """Return percent identity over aligned columns and an x->y position map."""
    aln = al.align(x, y)[0]
    a, b = aln[0], aln[1]
    ix = iy = same = cols = 0
    mapping: dict[int, tuple[int, str]] = {}
    for p, q in zip(a, b):
        if p != "-":
            ix += 1
        if q != "-":
            iy += 1
        if p != "-" and q != "-":
            cols += 1
            same += p == q
            mapping[ix] = (iy, q)
    return 100 * same / cols, mapping


def main() -> None:
    """Run the comparison and write RESULTS.md."""
    seqs = {
        "Q9HX05 PA4022 (PAO1)": read_flatfile_seq(ROOT / "genes/PSEAE/PA4022/PA4022-uniprot.txt"),
        "Q9ZAA1 ExaC (ATCC 17933)": read_flatfile_seq(ROOT / "genes/PSEAE/exaC/exaC-uniprot.txt"),
        "Q9I2C4 exaC/PA1984 (PAO1)": fetch_fasta_seq("Q9I2C4"),
    }
    al = make_aligner()
    names = list(seqs)
    out = ["# PA4022 vs ExaC pairwise comparison", "",
           "Generated by `pairwise_exac.py` (BLOSUM62 global alignment, open -10, extend -0.5).", "",
           "| Pair | Lengths | Identity over aligned columns |", "|---|---|---|"]
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            pid, _ = identity_and_map(al, seqs[names[i]], seqs[names[j]])
            out.append(f"| {names[i]} vs {names[j]} | {len(seqs[names[i]])} / {len(seqs[names[j]])} | {pid:.1f}% |")
    exac, pa = seqs[names[1]], seqs[names[0]]
    _, mapping = identity_and_map(al, exac, pa)
    out += ["", "Catalytic residues of ExaC mapped onto PA4022:", ""]
    for pos in (262, 301):
        q, res = mapping[pos]
        out.append(f"- ExaC {exac[pos - 1]}{pos} aligns to PA4022 {res}{q}")
    text = "\n".join(out) + "\n"
    (HERE / "RESULTS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
