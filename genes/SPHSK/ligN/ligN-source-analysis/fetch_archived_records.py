#!/usr/bin/env python3
"""Recover retired SYK-6 records through the normal GOA/review seeding pipeline.

Run from repository root with uv run python <this-file>. UniSave versions are
pinned; the original flat-file blocks are passed unchanged to fetch_gene_data.
No functional decisions or annotation rows are generated by this wrapper.
"""

from datetime import datetime, timezone
import hashlib
from pathlib import Path
import re

import requests
import yaml
from ai_gene_review.etl import gene as etl

ROOT = Path(__file__).resolve().parents[4]
RECORDS = [
    ("ligN", "C0SUK1", 74, "UPI00019B2644"),
    ("ligP", "E1CJ68", 63, "UPI0001DD3D33"),
    ("ligQ", "G2IKM4", 56, "UPI0002276658"),
]


def main():
    for symbol, accession, version, uniparc in RECORDS:
        url = f"https://rest.uniprot.org/unisave/{accession}?format=txt&versions={version}"
        response = requests.get(url, timeout=90)
        response.raise_for_status()
        match = re.search(r"^ID   .*?^//\s*$", response.text, re.M | re.S)
        if not match:
            raise ValueError(f"No complete UniSave record: {accession}/{version}")
        flat = match.group().rstrip() + "\n"
        if not re.search(r"^AC   " + re.escape(accession) + r";", flat, re.M):
            raise ValueError(f"Accession mismatch: {accession}")
        if "NCBI_TaxID=627192" not in flat:
            raise ValueError("Unexpected SYK-6 archival taxon")
        current_url = f"https://rest.uniprot.org/uniprotkb/{accession}.json"
        current = requests.get(current_url, timeout=90)
        current.raise_for_status()
        current_record = current.json()
        if current_record.get("extraAttributes", {}).get("uniParcId") != uniparc:
            raise ValueError("UniParc identity changed; investigate before refreshing")
        metadata_url = f"https://rest.uniprot.org/unisave/{accession}?format=json"
        metadata = requests.get(metadata_url, timeout=90)
        metadata.raise_for_status()
        entry = next(
            x for x in metadata.json()["results"] if x["entryVersion"] == version
        )
        folder = ROOT / "genes" / "SPHSK" / symbol
        folder.mkdir(parents=True, exist_ok=True)
        snapshot = {
            "accession": accession,
            "retrieved_at": datetime.now(timezone.utc).isoformat(),
            "current_record_url": current_url,
            "current_record_status": current_record,
            "metadata_url": metadata_url,
            "source_url": url,
            "entry_version": version,
            "sequence_version": entry.get("sequenceVersion"),
            "first_release": entry["firstRelease"],
            "last_release": entry["lastRelease"],
            "record_sha256": hashlib.sha256(flat.encode()).hexdigest(),
            "record_text": flat,
        }
        evidence_path = folder / f"{symbol}-record-evidence.yaml"
        if not evidence_path.exists():
            evidence_path.write_text(
                yaml.safe_dump(snapshot, sort_keys=False, allow_unicode=True, width=100)
            )
        existing = folder / f"{symbol}-uniprot.txt"
        if existing.exists() and existing.read_text() and existing.read_text() != flat:
            raise ValueError(
                f"Preserve existing raw source; divergent content at {existing}"
            )
        original = etl.fetch_uniprot_data

        def archived_fetch(requested, *, expected=accession, record=flat):
            if requested != expected:
                raise ValueError(f"Unexpected requested accession: {requested}")
            return record

        try:
            etl.fetch_uniprot_data = archived_fetch
            result = etl.fetch_gene_data(
                ("SPHSK", symbol), uniprot_id=accession, base_path=ROOT, force=True
            )
        finally:
            etl.fetch_uniprot_data = original
        print(symbol, accession, version, result, flush=True)


if __name__ == "__main__":
    main()
