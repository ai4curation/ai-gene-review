#!/usr/bin/env python
"""Count accepted ARBA annotations that no other source already covers.

An accepted ARBA row (``gene_side_rows.tsv``, action ACCEPT) is *covered* when
the gene's GOA file has a non-NOT annotation from any other reference (manual
curation, PAINT, InterPro2GO, other pipelines) to the same term or to an
is_a/part_of descendant of it. The rest are what ARBA alone adds. Writes
``UNIQUE_ACCEPTS.md`` and ``unique_accepts.tsv``.

Usage::

    uv run python projects/ARBA_REVIEW/unique_accepts.py
"""

from __future__ import annotations

import collections
import csv
import datetime
import glob
from pathlib import Path

from gene_side_failures import ancestors_fn

HERE = Path(__file__).parent
ARBA = "GO_REF:0000117"


def other_terms(gene: str) -> set[str]:
    """Non-NOT GO terms on *gene* from any reference other than ARBA."""
    goa = glob.glob(f"genes/{gene}/*-goa.tsv")
    if not goa:
        return set()
    return {a["GO TERM"] for a in csv.DictReader(open(goa[0]), delimiter="\t")
            if not a["QUALIFIER"].startswith("NOT") and a["REFERENCE"] != ARBA}


def main() -> None:
    rows = [r for r in csv.DictReader(open(HERE / "gene_side_rows.tsv"), delimiter="\t")
            if r["action"] == "ACCEPT"]
    anc = ancestors_fn()
    others = {g: other_terms(g) for g in {r["gene"] for r in rows}}
    unique = [r for r in rows if not any(r["term"] in anc(t) for t in others[r["gene"]])]
    with open(HERE / "unique_accepts.tsv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["gene", "term", "label", "rules"], delimiter="\t",
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(unique)
    organisms = collections.Counter(r["gene"].split("/")[0] for r in unique)
    lines = [
        "---",
        'title: "Accepted ARBA annotations no other source covers"',
        "autolink_gene_symbols: false",
        "---",
        "",
        "# Accepted ARBA annotations no other source covers",
        "",
        "Generated by `unique_accepts.py`; do not edit by hand. Rows are in",
        "[unique_accepts.tsv](unique_accepts.tsv).",
        "",
        f"- run: {datetime.date.today().isoformat()}; ARBA rows and review actions come from the committed "
        "`gene_side_rows.tsv` snapshot, other-source terms from the current GOA files",
        f"- accepted ARBA annotations: **{len(rows)}**",
        f"- covered by the same or a more specific term from another source: "
        f"**{len(rows) - len(unique)}** ({(len(rows) - len(unique)) / len(rows):.0%})",
        f"- added only by ARBA: **{len(unique)}**",
        "",
        "| organism | rows |",
        "|---|---:|",
    ] + [f"| {o} | {n} |" for o, n in organisms.most_common()]
    (HERE / "UNIQUE_ACCEPTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[10:15]))


if __name__ == "__main__":
    main()
