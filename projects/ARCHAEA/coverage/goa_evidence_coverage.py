"""Count GOA rows by evidence code for the ARCHAEA project's gene folders.

Reads the `species` list from the frontmatter of projects/ARCHAEA.md, then every
`genes/<SPECIES>/<GENE>/<GENE>-goa.tsv` under those species, and reports per
species: genes, rows, rows per evidence code, the electronic (IEA) share, the
experimental share, and the electronic rows split by pipeline (GO_REF).

The counts describe the GOA snapshots fetched into this repo for reviewed genes,
not the whole proteome, so they measure how far the annotations under review
rest on electronic inference. Re-run after new reviews:

    uv run python projects/ARCHAEA/coverage/goa_evidence_coverage.py > projects/ARCHAEA/coverage/RESULTS.md
"""

from __future__ import annotations

import csv
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
PROJECT = ROOT / "projects" / "ARCHAEA.md"

EXPERIMENTAL = {"EXP", "IDA", "IPI", "IMP", "IGI", "IEP", "HTP", "HDA", "HMP", "HGI", "HEP"}
PHYLOGENETIC = {"IBA", "IBD", "IKR", "IRD"}
AUTHOR_CURATOR = {"TAS", "NAS", "IC", "ND"}
SIMILARITY = {"ISS", "ISO", "ISA", "ISM", "IGC", "RCA"}

# Electronic pipelines, keyed by GO_REF. Names checked against the titles in
# geneontology/go-site metadata/gorefs.yaml; unlisted GO_REFs are shown as is.
PIPELINES = {
    "GO_REF:0000002": "InterPro2GO",
    "GO_REF:0000003": "EC mapping",
    "GO_REF:0000041": "UniPathway mapping",
    "GO_REF:0000043": "UniProtKB keyword mapping",
    "GO_REF:0000044": "UniProtKB subcellular location mapping",
    "GO_REF:0000104": "UniRule (shared sequence features)",
    "GO_REF:0000108": "GO logical inference",
    "GO_REF:0000116": "Rhea mapping",
    "GO_REF:0000117": "ARBA",
    "GO_REF:0000118": "TreeGrafter",
    "GO_REF:0000120": "Combined multiple IEA methods",
}


@dataclass
class SpeciesTally:
    """GOA row counts for one species folder."""

    genes: set[str] = field(default_factory=set)
    codes: Counter[str] = field(default_factory=Counter)
    pipelines: Counter[str] = field(default_factory=Counter)

    @property
    def rows(self) -> int:
        """Total GOA rows."""
        return sum(self.codes.values())

    def share(self, codes: set[str]) -> float:
        """Fraction of rows whose evidence code is in ``codes``.

        >>> t = SpeciesTally(codes=Counter({"IEA": 3, "IDA": 1}))
        >>> t.share({"IEA"})
        0.75
        """
        return sum(n for c, n in self.codes.items() if c in codes) / self.rows if self.rows else 0.0


def project_species(path: Path = PROJECT) -> list[str]:
    """Species codes listed in the project page's frontmatter."""
    front = path.read_text().split("---")[1]
    return list(yaml.safe_load(front)["species"])


def tally(species: str, root: Path = ROOT) -> SpeciesTally:
    """Count evidence codes over every GOA file for one species."""
    out = SpeciesTally()
    for goa in sorted((root / "genes" / species).glob("*/*-goa.tsv")):
        out.genes.add(goa.parent.name)
        with goa.open() as fh:
            for row in csv.DictReader(fh, delimiter="\t"):
                code = row["GO EVIDENCE CODE"]
                out.codes[code] += 1
                if code == "IEA":
                    out.pipelines[PIPELINES.get(row["REFERENCE"], row["REFERENCE"])] += 1
    return out


def pct(x: float) -> str:
    """Format a fraction as a whole-number percentage.

    >>> pct(0.256)
    '26%'
    """
    return f"{round(100 * x)}%"


def report(species_list: list[str]) -> str:
    """Markdown report of the tallies."""
    tallies = {s: tally(s) for s in species_list}
    tallies = {s: t for s, t in tallies.items() if t.rows}
    total = SpeciesTally()
    for s, t in tallies.items():
        total.genes |= {f"{s}/{g}" for g in t.genes}
        total.codes.update(t.codes)
        total.pipelines.update(t.pipelines)

    lines = [
        "# ARCHAEA GOA evidence coverage",
        "",
        "Generated by `goa_evidence_coverage.py` from the GOA snapshots in `genes/`",
        "for the species in the project frontmatter. Counts cover the genes reviewed",
        "so far, not whole proteomes.",
        "",
        "| Species | Genes | Rows | IEA | IBA/phylogenetic | Similarity (ISS etc.) | Experimental | Curator/author |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s, t in [*tallies.items(), ("**All**", total)]:
        lines.append(
            f"| {s} | {len(t.genes)} | {t.rows} | {pct(t.share({'IEA'}))} | "
            f"{pct(t.share(PHYLOGENETIC))} | {pct(t.share(SIMILARITY))} | {pct(t.share(EXPERIMENTAL))} | "
            f"{pct(t.share(AUTHOR_CURATOR))} |"
        )
    lines += ["", "## Electronic rows by pipeline (all species)", "", "| Pipeline | Rows |", "|---|---|"]
    lines += [f"| {p} | {n} |" for p, n in total.pipelines.most_common()]
    lines += ["", "## Rows by evidence code (all species)", "", "| Code | Rows |", "|---|---|"]
    lines += [f"| {c} | {n} |" for c, n in total.codes.most_common()]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(report(project_species()), end="")
