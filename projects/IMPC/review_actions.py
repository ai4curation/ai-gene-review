"""How have reviewers in this repository treated mutant-phenotype (IMP) annotations?

Joins every ``existing_annotations`` row in ``genes/mouse/*/*-ai-review.yaml``
to the reviewer's action, by evidence code and then by evidence code within each
GO aspect, so knockout-derived annotations (IMP, IGI) can be compared with
direct-assay ones (IDA, IPI). Aspect matters because IMP rows are mostly
biological process, where KEEP_AS_NON_CORE is common for any evidence, while IDA
rows also cover function and location. The aspect of each term comes from
go-basic (``.cache/impc/go-basic.obo``); a term not in it (obsolete or newer) is
counted under ``unknown``.

Output: ``projects/IMPC/results/review_actions.tsv`` (all aspects),
``review_actions_by_aspect.tsv`` and ``REVIEW_ACTIONS.md``.

    uv run python projects/IMPC/review_actions.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).parent
RESULTS = HERE / "results"
ROOT = Path("genes/mouse")
CODES = ["IMP", "IGI", "IDA", "IPI", "IBA", "ISO", "IEA"]
ACTIONS = [
    "ACCEPT",
    "KEEP_AS_NON_CORE",
    "MODIFY",
    "MARK_AS_OVER_ANNOTATED",
    "TOO_GENERAL",
    "REMOVE",
    "UNDECIDED",
]


ASPECTS = {"biological_process": "BP", "molecular_function": "MF", "cellular_component": "CC"}


def go_aspects(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    cur = None
    for line in path.read_text().splitlines():
        if line.startswith("id: GO:"):
            cur = line[4:]
        elif cur and line.startswith("namespace: "):
            out[cur] = ASPECTS.get(line[11:], "unknown")
    return out


def action_table(df: pd.DataFrame, title: str) -> list[str]:
    tab = pd.crosstab(df.evidence, df.action).reindex(index=CODES, columns=ACTIONS, fill_value=0)
    lines = [
        f"## {title}",
        "",
        "| Evidence | n | " + " | ".join(ACTIONS) + " |",
        "|---|---:|" + "---:|" * len(ACTIONS),
    ]
    for code in CODES:
        r = tab.loc[code]
        n = int(r.sum())
        cells = [f"{100 * r[a] / n:.0f}%" if n else "-" for a in ACTIONS]
        lines.append(f"| {code} | {n:,} | " + " | ".join(cells) + " |")
    return lines + [""]


def main() -> None:
    aspects = go_aspects(Path(".cache/impc/go-basic.obo"))
    rows = []
    for path in sorted(ROOT.glob("*/*-ai-review.yaml")):
        doc = yaml.safe_load(path.read_text()) or {}
        for ann in doc.get("existing_annotations") or []:
            action = (ann.get("review") or {}).get("action")
            term = ann.get("term") or {}
            if not action or action in {"PENDING", "NEW"}:
                continue
            rows.append(
                {
                    "gene": path.parent.name,
                    "evidence": ann.get("evidence_type"),
                    "go": term.get("id"),
                    "action": action,
                }
            )
    df = pd.DataFrame(rows)
    df = df[df.evidence.isin(CODES)].copy()
    df["aspect"] = df.go.map(lambda g: aspects.get(g, "unknown"))
    tab = pd.crosstab(df.evidence, df.action).reindex(index=CODES, columns=ACTIONS, fill_value=0)
    RESULTS.mkdir(exist_ok=True)
    tab.to_csv(RESULTS / "review_actions.tsv", sep="\t")
    by_aspect = (
        df.groupby(["aspect", "evidence", "action"]).size().rename("rows").reset_index()
    )
    by_aspect.to_csv(RESULTS / "review_actions_by_aspect.tsv", sep="\t", index=False)
    mix = pd.crosstab(df.evidence, df.aspect).reindex(index=CODES, fill_value=0)

    genes = df.gene.nunique()
    lines = [
        "# Reviewer actions on mouse annotations, by evidence code (generated)",
        "",
        f"Generated by `review_actions.py` from {genes} mouse gene reviews; do not edit by hand.",
        "Rows are existing GOA annotations with a final action; percentages are of each row,"
        " so each row sums to 100% across the seven actions.",
        "",
    ]
    lines += action_table(df, "All aspects")
    cols = [c for c in ["BP", "MF", "CC", "unknown"] if c in mix.columns]
    lines += [
        "## Aspect mix by evidence code",
        "",
        "| Evidence | " + " | ".join(cols) + " |",
        "|---|" + "---:|" * len(cols),
    ]
    for code in CODES:
        n = int(mix.loc[code].sum())
        lines.append(
            f"| {code} | " + " | ".join(f"{100 * mix.loc[code, c] / n:.0f}%" if n else "-" for c in cols) + " |"
        )
    lines.append("")
    for asp, name in [("BP", "Biological process only"), ("MF", "Molecular function only"), ("CC", "Cellular component only")]:
        lines += action_table(df[df.aspect == asp], name)
    (RESULTS / "REVIEW_ACTIONS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
