#!/usr/bin/env python3
"""Compare the blinded re-check (batch_*.yaml) with the original, unblinded
assessments (key.yaml). Verdicts are grouped as wrong (NPI/PLI/REP), correct
(COR/LSP) or undecided (UNC). Writes summary.yaml: for claims drawn as REJECTED
and for the distractors, the wrong rate before and after blinding, the
agreement on the three-way grouping, and Cohen's kappa."""
import glob
import os
from collections import Counter

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
GROUP = {"NPI": "wrong", "PLI": "wrong", "REP": "wrong", "COR": "correct", "LSP": "correct", "UNC": "undecided"}
key = {k["blind_id"]: k for k in yaml.safe_load(open(os.path.join(HERE, "key.yaml")))["key"]}
blind = {}
for path in sorted(glob.glob(os.path.join(HERE, "batch_*.yaml"))):
    for c in yaml.safe_load(open(path))["claims"]:
        blind[c["blind_id"]] = c


def kappa(pairs):
    n = len(pairs)
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[g] * cb[g] for g in set(ca) | set(cb)) / n / n
    return round((po - pe) / (1 - pe), 3) if pe < 1 else None


out = {}
for label, sel in (("drawn_as_REJECTED", lambda k: k["drawn_as"] == "REJECTED"),
                   ("distractors", lambda k: k["drawn_as"] != "REJECTED"),
                   ("all", lambda k: True)):
    ids = [b for b, k in key.items() if sel(k)]
    pairs = [(GROUP[key[b]["original_assessment"]], GROUP[blind[b]["assessment"]]) for b in ids]
    orig, new = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    out[label] = {
        "n": len(ids),
        "original": dict(orig), "blinded": dict(new),
        "wrong_rate_original": round(orig["wrong"] / len(ids), 3),
        "wrong_rate_blinded": round(new["wrong"] / len(ids), 3),
        "agreement": round(sum(a == b for a, b in pairs) / len(ids), 3),
        "kappa": kappa(pairs),
        "transitions": {f"{a}->{b}": n for (a, b), n in sorted(Counter(pairs).items())},
    }
out["disagreements"] = [
    {"blind_id": b, "claim": f"{k['source']}:{k['claim_id']}", "drawn_as": k["drawn_as"],
     "original": k["original_assessment"], "blinded": blind[b]["assessment"],
     "gene": blind[b]["gene"], "term": blind[b]["term"]["label"]}
    for b, k in sorted(key.items())
    if GROUP[k["original_assessment"]] != GROUP[blind[b]["assessment"]]]
with open(os.path.join(HERE, "summary.yaml"), "w") as fh:
    fh.write("# Generated by compare.py; do not edit by hand.\n")
    yaml.safe_dump(out, fh, sort_keys=False)
print(yaml.safe_dump({k: v for k, v in out.items() if k != "disagreements"}, sort_keys=False))
for d in out["disagreements"]:
    print(d)
