#!/usr/bin/env python3
"""Map each cohort taxon to its species-rank ancestor in eggNOG's NCBI taxonomy
(eggnog.taxa.db), so that ``--excluded_taxa`` removes every strain of the
query's species. Writes ``cohort_species_taxa.yaml`` (accession -> species taxid).

Usage: species_taxa.py EGGNOG_DATA_DIR/eggnog.taxa.db [BASE_DIR]
BASE_DIR holds cohort.yaml (default: the project directory).
"""
import os
import sqlite3
import sys

import yaml

HERE = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db = sqlite3.connect(sys.argv[1])
cohort = yaml.safe_load(open(os.path.join(HERE, "cohort.yaml")))["proteins"]


def species_of(taxid: int):
    seen = set()
    t = taxid
    while t and t not in seen:
        seen.add(t)
        row = db.execute("SELECT parent, rank FROM species WHERE taxid=?", (t,)).fetchone()
        if row is None:
            # merged/retired id: try the merged table
            m = db.execute("SELECT taxid_new FROM merged WHERE taxid_old=?", (t,)).fetchone()
            if m is None:
                return None
            t = m[0]
            continue
        parent, rank = row
        if rank == "species":
            return t
        t = parent
    return None


out, missing = {}, []
for rec in cohort:
    sp = species_of(rec["taxon"])
    if sp is None:
        missing.append(rec["accession"])
        sp = rec["taxon"]
    out[rec["accession"]] = sp
with open(os.path.join(HERE, "cohort_species_taxa.yaml"), "w") as fh:
    fh.write("# Generated by scripts/species_taxa.py; do not edit by hand.\n")
    yaml.safe_dump({"species_taxid": out, "not_resolved": missing}, fh, sort_keys=True)
print(len(out), "mapped;", len(set(out.values())), "species;", len(missing), "unresolved", missing)
