#!/usr/bin/env python3
"""Deep-dive cohort: every eligible review (same rule as ../build_cohort.py) for
four non-model genomes: P. putida KT2440 (PSEPK), horse (HORSE), pennycress
(THLAR) and poplar (POPTR). Writes cohort.yaml and cohort.fasta here, in the
same format as the main cohort, with ``stratum`` = organism directory.
When two review folders share an accession (e.g. ``aroE`` and ``aroE__Q88IJ7``),
only the first in sorted order is kept, so each protein is scored once."""
import glob
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from build_cohort import ROOT, eligible, read_uniprot  # noqa: E402

ORGANISMS = ["PSEPK", "HORSE", "THLAR", "POPTR"]
out = []
seen = set()
for org in ORGANISMS:
    n = 0
    for review in sorted(glob.glob(os.path.join(ROOT, "genes", org, "*", "*-ai-review.yaml"))):
        gene = review.split(os.sep)[-2]
        uniprot = os.path.join(os.path.dirname(review), f"{gene}-uniprot.txt")
        if not os.path.exists(uniprot):
            continue
        doc = eligible(review)
        if doc is None:
            continue
        acc, taxon, seq = read_uniprot(uniprot)
        if not (acc and taxon and seq) or str(doc.get("id", "")).split(":")[-1] not in ("", acc):
            continue
        if acc in seen:
            print(f"  skip {gene}: accession {acc} already in cohort")
            continue
        seen.add(acc)
        out.append({"organism_dir": org, "gene": gene, "accession": acc, "taxon": taxon,
                    "review": os.path.relpath(review, ROOT), "length": len(seq),
                    "stratum": org, "_seq": seq})
        n += 1
    print(org, n)
with open(os.path.join(HERE, "cohort.fasta"), "w") as fa:
    for r in out:
        fa.write(f">{r['accession']}\n" + "\n".join(r["_seq"][i:i + 60] for i in range(0, len(r["_seq"]), 60)) + "\n")
with open(os.path.join(HERE, "cohort.yaml"), "w") as fh:
    fh.write("# Generated by build_deep_cohort.py; do not edit by hand.\n")
    yaml.safe_dump({"organisms": ORGANISMS,
                    "proteins": [{k: v for k, v in r.items() if not k.startswith("_")} for r in out]},
                   fh, sort_keys=False)
print(len(out), "proteins", len(seen), "unique")
