#!/usr/bin/env python3
"""Tally the deep-dive adjudication (<ORG>.yaml) into summary.yaml: assessments
per genome and per automatic category, and error types per genome."""
import glob
import os
from collections import Counter, defaultdict

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
WRONG = {"NPI", "PLI", "REP"}
out = {"genomes": {}}
for path in sorted(glob.glob(os.path.join(HERE, "*.yaml"))):
    if os.path.basename(path) == "summary.yaml":
        continue
    org = os.path.basename(path)[:-5]
    claims = yaml.safe_load(open(path))["claims"]
    by_cat = defaultdict(Counter)
    for c in claims:
        by_cat[c["category"]][c.get("assessment") or "MISSING"] += 1
    a = Counter(c.get("assessment") or "MISSING" for c in claims)
    out["genomes"][org] = {
        "claims": len(claims),
        "assessment": dict(sorted(a.items())),
        "wrong": sum(a[k] for k in WRONG),
        "assessment_by_category": {k: dict(sorted(v.items())) for k, v in sorted(by_cat.items())},
        "error_types": dict(Counter(c["error_type"] for c in claims if c.get("error_type")).most_common()),
    }
with open(os.path.join(HERE, "summary.yaml"), "w") as fh:
    fh.write("# Generated by summarize.py; do not edit by hand.\n")
    yaml.safe_dump(out, fh, sort_keys=False)
print(yaml.safe_dump(out, sort_keys=False))
