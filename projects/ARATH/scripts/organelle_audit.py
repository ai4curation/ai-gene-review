#!/usr/bin/env python
"""Audit chloroplast/plastid and mitochondrion localization rows in ARATH reviews.

Lists every ``existing_annotations`` row in ``genes/ARATH/*/*-ai-review.yaml``
whose term is plastid (GO:0009536) or mitochondrion (GO:0005739), or one of
their is_a/part_of descendant compartments (chloroplast, thylakoid, stroma,
envelope, mitochondrial matrix, inner/outer membrane, ...). Protein-containing
complexes (descendants of GO:0032991) are excluded: they are complex membership
claims, not organelle localization claims.

GO ids are resolved from the local OAK GO SQLite build (default
``~/.data/oaklib/go.db``; pass ``--go-db sqlite:obo:go`` to download).

Usage:
    UV_NO_SYNC=1 uv run python projects/ARATH/scripts/organelle_audit.py
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

import yaml
from oaklib import get_adapter

ROOTS = {"GO:0009536": "plastid", "GO:0005739": "mitochondrion"}
COMPLEX_ROOT = "GO:0032991"
PREDICATES = ["rdfs:subClassOf", "BFO:0000050"]
REPO = Path(__file__).resolve().parents[3]


def excerpt(text: str | None, n: int = 220) -> str:
    if not text:
        return ""
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 3] + "..."


def build_term_sets(go_db: str) -> dict[str, str]:
    """Map each in-scope GO id to its organelle root label."""
    adapter = get_adapter(go_db)
    complexes = set(adapter.descendants([COMPLEX_ROOT], predicates=PREDICATES))
    terms: dict[str, str] = {}
    for root, label in ROOTS.items():
        for t in adapter.descendants([root], predicates=PREDICATES, reflexive=True):
            if t.startswith("GO:") and t not in complexes:
                terms[t] = label
    return terms


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--go-db", default=f"sqlite:{Path.home()}/.data/oaklib/go.db")
    ap.add_argument("--genes-dir", default=str(REPO / "genes" / "ARATH"))
    ap.add_argument("--out", default=str(REPO / "projects" / "ARATH" / "organelle-audit.yaml"))
    args = ap.parse_args()

    terms = build_term_sets(args.go_db)
    rows = []
    for path in sorted(Path(args.genes_dir).glob("*/*-ai-review.yaml")):
        doc = yaml.safe_load(path.read_text())
        gene = doc.get("gene_symbol") or path.parent.name
        for i, ann in enumerate(doc.get("existing_annotations") or []):
            term = ann.get("term") or {}
            tid = term.get("id")
            if tid not in terms:
                continue
            review = ann.get("review") or {}
            rows.append(
                {
                    "gene": gene,
                    "folder": path.parent.name,
                    "uniprot": doc.get("id"),
                    "row_index": i,
                    "organelle": terms[tid],
                    "term_id": tid,
                    "term_label": term.get("label"),
                    "evidence_type": ann.get("evidence_type"),
                    "reference": ann.get("original_reference_id"),
                    "negated": bool(ann.get("negated", False)),
                    "action": review.get("action"),
                    "reason": excerpt(review.get("reason")),
                }
            )

    by_action = Counter(r["action"] for r in rows)
    by_ev_action = Counter(f"{r['evidence_type']}:{r['action']}" for r in rows)
    by_term_action = Counter(f"{r['term_label']}:{r['action']}" for r in rows)
    out = {
        "description": (
            "ARATH existing_annotations rows on plastid/mitochondrion localization "
            "terms (generated by projects/ARATH/scripts/organelle_audit.py; do not edit)"
        ),
        "summary": {
            "n_rows": len(rows),
            "n_genes": len({r["folder"] for r in rows}),
            "by_action": dict(sorted(by_action.items(), key=lambda kv: str(kv[0]))),
            "by_evidence_action": dict(sorted(by_ev_action.items())),
            "by_term_action": dict(sorted(by_term_action.items())),
        },
        "rows": rows,
    }
    Path(args.out).write_text(yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120))
    print(f"wrote {len(rows)} rows to {args.out}")


if __name__ == "__main__":
    main()
