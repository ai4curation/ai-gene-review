"""Per-gene Bgee expression report for a gene review's bioinformatics folder.

For one gene (and optional paralogs from the same PANTHER family) this writes
``genes/<org>/<GENE>/<GENE>-bioinformatics/`` with:

    RESULTS.md         human-readable report (generated; do not edit)
    bgee_calls.tsv     Bgee simple calls (present/absent, stages merged) for gene + paralogs
    bgee_stage_calls.tsv  stage-resolved present calls (REST API) for gene + paralogs

The report has four parts, all computed, none typed by hand:
  1. top tissues and breadth (share of sampled entities with a present call);
  2. every GO term in the gene's GOA file that names an anatomy (go-plus),
     classified with the BGEEDB_EXPRESSION classifier, for the gene and for
     each paralog (a detected paralog is the positive control for absence);
  3. optional context checks for terms with no GO anatomy (e.g. the
     gluconeogenic tissues from the pathway-satisfiability engine);
  4. stage-resolved present calls in named anatomies of interest.

Usage (from repo root):
    uv run python projects/BGEEDB_EXPRESSION/scripts/gene_report.py mouse G6pc2 \
        --paralog G6pc1 --paralog G6pc3 \
        --context "gluconeogenesis:UBERON:0002107,UBERON:0001225,UBERON:0002108" \
        --focus UBERON:0000006 --focus UBERON:0002107 --focus UBERON:0002113
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import bgee_common as bc  # noqa: E402
import cerebellum_timing as ct  # noqa: E402  (stage axis)
from paralogs import calls_for, score_context, score_term  # noqa: E402

TAXON = {"mouse": 10090, "human": 9606}


def gene_dir(org: str, gene: str) -> Path:
    return bc.REPO / "genes" / org / gene


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("organism")
    ap.add_argument("gene")
    ap.add_argument("--paralog", action="append", default=[], help="paralog symbol with a review folder or UniProt file")
    ap.add_argument("--context", action="append", default=[], help="LABEL:UBERON,UBERON,... for a term without GO anatomy")
    ap.add_argument("--focus", action="append", default=[], help="anatomy id whose stage-resolved calls to list")
    args = ap.parse_args()

    org, gene = args.organism, args.gene
    taxon = TAXON[org]
    go = bc.load_go_anatomy()
    anat = bc.load_anatomy()
    axis = ct.stage_axis()

    def ens_for(sym: str) -> str:
        """Bgee gene id from the gene's cached UniProt record (or its paralog's)."""
        for path in (gene_dir(org, sym) / f"{sym}-uniprot.txt",):
            gid = bc.bgee_gene_id(path)
            if gid:
                return gid
        # paralog without a review folder: look it up in the project's UniProt map
        with (bc.DATA / "uniprot_bgee_map.tsv").open() as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                if r["gene"] == sym and r["taxon"] == str(taxon):
                    return r["bgee"]
        raise SystemExit(f"no Bgee gene id for {sym}")

    symbols = [gene] + args.paralog
    ids = {ens_for(s): s for s in symbols}
    by_sym = {s: g for g, s in ids.items()}
    calls = calls_for(org, ids)

    out_dir = gene_dir(org, gene) / f"{gene}-bioinformatics"
    out_dir.mkdir(parents=True, exist_ok=True)
    bc.write_calls_tsv(calls, ids, out_dir / "bgee_calls.tsv")

    # GO terms from the gene's GOA file (the annotations under review)
    terms: dict[str, str] = {}
    with (gene_dir(org, gene) / f"{gene}-goa.tsv").open() as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            terms.setdefault(row["GO TERM"], row["GO NAME"])

    lines = [
        f"# {gene} ({org}): Bgee expression evidence",
        "",
        f"Generated by `projects/BGEEDB_EXPRESSION/scripts/gene_report.py`; do not edit. Source: {bc.BGEE_RELEASE} "
        f"({org} simple call files for present/absent calls with stages merged; REST API for stage-resolved present calls). "
        "Method and tier definitions: `projects/BGEEDB_EXPRESSION/methods.md`.",
        "",
        "Command:",
        "",
        "```bash",
        "uv run python projects/BGEEDB_EXPRESSION/scripts/gene_report.py " + " ".join(sys.argv[1:]),
        "```",
        "",
        "## 1. Where the gene and its paralogs are expressed",
        "",
        "| gene | Bgee id | present / sampled entities | breadth | top present tissues (score) |",
        "|---|---|---|---|---|",
    ]
    for s in symbols:
        cs = [c for c in calls[by_sym[s]] if c.quality in ("gold", "silver")]
        pres = sorted((c for c in cs if c.state == "present"), key=lambda c: -c.score)
        breadth = len(pres) / len(cs) if cs else 0.0
        top = "; ".join(f"{c.name} ({c.score:.0f})" for c in pres[:8])
        lines.append(f"| {s} | {by_sym[s]} | {len(pres)} / {len(cs)} | {breadth:.2f} | {top} |")

    lines += ["", "## 2. GO terms with a GO anatomy, scored for the gene and each paralog", "",
              "Tier per gene: ENRICHED (present in the term's anatomy and in the gene's own top 10%), CONSISTENT, "
              "ABSENT (calls exist there, all absent), ABSENT_DEVELOPMENTAL (absent, but the term is developmental and "
              "calls merge stages), NO_DATA. A paralog that is detected where the gene is absent shows the anatomy was "
              "sampled.", "",
              "| GO term | anatomy | " + " | ".join(symbols) + " |", "|---|---|" + "---|" * len(symbols)]
    n_anat = 0
    for gid, label in sorted(terms.items()):
        tg, _, _ = go.targets(gid)
        if not tg:
            continue
        n_anat += 1
        cells = []
        for s in symbols:
            r = score_term(gid, calls[by_sym[s]], go, anat, False)
            extra = f" ({r['best']})" if r["best"] else (f" (absent in {', '.join(r['absent_in'][:2])})" if r["absent_in"] else "")
            cells.append(r["tier"] + extra)
        anatomy = ", ".join(sorted({f"{anat.name(a)}" for _, a in tg}))
        lines.append(f"| {gid} {label} | {anatomy} | " + " | ".join(cells) + " |")

    if not n_anat:
        lines.append("| none of the gene's GO terms names an anatomy | | " + " | ".join("" for _ in symbols) + " |")

    if args.context:
        lines += ["", "## 3. Context checks for terms without GO anatomy", "",
                  "| context | gene | present in context | best in context | top-10 in context (chance) | breadth |",
                  "|---|---|---|---|---|---|"]
        for spec in args.context:
            label, ids_s = spec.split(":", 1)
            targets = [t if t.startswith("UBERON:") else "UBERON:" + t for t in ids_s.replace("UBERON:", "").split(",")]
            for t in targets:
                if t not in anat.names:
                    raise SystemExit(f"unknown anatomy {t}")
            names = ", ".join(anat.name(t) for t in targets)
            for s in symbols:
                r = score_context(targets, calls[by_sym[s]], anat)
                lines.append(f"| {label} ({names}) | {s} | {r['present_in_context']} present, {r['absent_in_context']} absent | "
                             f"{r['best_in_context'] or '—'} | {r['top10_in_context']} ({r['expected_top10_in_context_by_chance']}) | "
                             f"{r['breadth_present_fraction']} |")
            lines += ["", f"Calls inside the {label} context, by gene (gold/silver; state, score):", ""]
            for s in symbols:
                related = sorted((c for c in calls[by_sym[s]] if c.quality in ("gold", "silver")
                                  and any(anat.within(c.entity, t) for t in targets)), key=lambda c: (c.state, -c.score))
                desc = "; ".join(f"{c.name} {c.state} ({c.score:.0f})" for c in related) or "no calls"
                lines.append(f"- **{s}**: {desc}")

    stage_rows = []
    for s in symbols:
        for c in bc.stage_calls(by_sym[s], taxon):
            aid = c["condition"]["anatEntity"]["id"]
            st = c["condition"].get("devStage", {})
            sid = st.get("id", "")
            span = axis.get(sid)
            stage_rows.append({"gene": s, "entity": aid, "entity_name": c["condition"]["anatEntity"]["name"],
                               "stage": sid, "stage_name": st.get("name", ""),
                               "stage_start_dpc": round(span[0], 1) if span else "",
                               "score": c["expressionScore"]["expressionScore"],
                               "data_types": "|".join(c.get("dataTypesWithData", []))})
    with (out_dir / "bgee_stage_calls.tsv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, list(stage_rows[0]) if stage_rows else ["gene"], delimiter="\t", lineterminator="\n")
        w.writeheader()
        w.writerows(sorted(stage_rows, key=lambda r: (r["gene"], str(r["stage_start_dpc"]), r["entity"])))

    if args.focus:
        lines += ["", "## 4. Stage-resolved present calls in anatomies of interest", "",
                  "Present calls only (the API reports no absent calls); a missing stage means no call, not absence. "
                  "Stages broader than one developmental window (life cycle, organogenesis stage) are omitted.", ""]
        for f in args.focus:
            lines += [f"### {f} {anat.name(f)} and its parts", "", "| gene | entity | stage | start (dpc) | score | data types |",
                      "|---|---|---|---|---|---|"]
            hits = [r for r in stage_rows if (anat.within(r["entity"], f)) and r["stage"] in axis
                    and (axis[r["stage"]][1] - axis[r["stage"]][0]) <= 31]
            if not hits:
                lines.append("| — | no stage-resolved present call | | | | |")
            for r in sorted(hits, key=lambda r: (r["gene"], r["stage_start_dpc"], r["entity"])):
                lines.append(f"| {r['gene']} | {r['entity_name']} | {r['stage_name']} | {r['stage_start_dpc']} | "
                             f"{float(r['score']):.1f} | {r['data_types']} |")
            lines.append("")

    (out_dir / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {out_dir / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
