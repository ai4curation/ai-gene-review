"""Compartments and EC codes of the YEAST-FAO-PWY gene products in yeast GEMs.

For each gene enabling an activity in GO-CAM YeastPathways_YEAST-FAO-PWY, list
how many reactions it has in iMM904 and yeast-GEM, in which compartments, and
under which EC numbers. Also lists, per model, every reaction carrying
EC 5.3.3.8 (delta3-delta2-enoyl-CoA isomerase) or EC 5.3.3.21 (dienoyl-CoA
isomerase) with its GPR, and every reaction whose GPR names DCI1 (YOR180C),
to see which gene each model gives the isomerase steps.
Writes gem_compartments.md beside this script. Nothing is hardcoded beyond the
gene list, model URLs and the two EC numbers.

Usage: uv run python gem_compartments.py [CACHE_DIR]
"""

import hashlib
import json
import sys
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path

import yaml

IMM904_URL = "https://bigg.ucsd.edu/static/models/iMM904.json"
YEASTGEM_TAG = "v9.1.1"
YEASTGEM_URL = (
    "https://raw.githubusercontent.com/SysBioChalmers/yeast-GEM/"
    f"{YEASTGEM_TAG}/model/yeast-GEM.yml"
)
GENES = {
    "YGL205W": "POX1", "YOR317W": "FAA1", "YER015W": "FAA2", "YIL009W": "FAA3",
    "YMR246W": "FAA4", "YBR041W": "FAT1", "YOR180C": "DCI1", "YLR284C": "ECI1",
    "YKR009C": "FOX2", "YIL160C": "POT1",
}
ISOMERASE_ECS = {"5.3.3.8", "5.3.3.21"}


def fetch(url: str, dest: Path) -> str:
    if not dest.exists():
        urllib.request.urlretrieve(url, dest)
    return hashlib.sha256(dest.read_bytes()).hexdigest()


def omap_loader():
    class Loader(yaml.SafeLoader):
        pass

    def omap(loader, node):
        return {k: v for item in loader.construct_sequence(node, deep=True) for k, v in item.items()}

    Loader.add_constructor("tag:yaml.org,2002:omap", omap)
    return Loader


def as_list(x):
    if x is None:
        return []
    return x if isinstance(x, list) else [x]


def summarise(title, reactions, out):
    """reactions: iterable of (id, name, gpr, ecs, compartments)."""
    comps = defaultdict(Counter)
    ecs = defaultdict(Counter)
    iso = []
    dci = []
    for rid, name, gpr, ec_list, cs in reactions:
        for loc, sym in GENES.items():
            if loc in gpr:
                comps[sym][",".join(sorted(cs))] += 1
                for e in ec_list:
                    ecs[sym][e] += 1
        if ISOMERASE_ECS & set(ec_list):
            iso.append(f"- {rid} ({name.strip()}) EC {','.join(ec_list)} in [{','.join(sorted(cs))}]; GPR {gpr or 'none'}")
        if "YOR180C" in gpr:
            dci.append(f"- {rid} ({name.strip()}) EC {','.join(ec_list) or 'none'} in [{','.join(sorted(cs))}]; GPR {gpr}")
    out += [f"## {title}", "", "| Gene | Reactions | Compartments | EC numbers |", "|---|---|---|---|"]
    for sym in GENES.values():
        n = sum(comps[sym].values())
        c = "; ".join(f"{k} ({v})" for k, v in sorted(comps[sym].items())) or "-"
        e = ", ".join(f"{k} ({v})" for k, v in sorted(ecs[sym].items())) or "-"
        out.append(f"| {sym} | {n} | {c} | {e} |")
    out += ["", "Reactions with EC 5.3.3.8 or 5.3.3.21:", ""] + (iso or ["- none"]) + [""]
    out += ["Reactions whose GPR names DCI1 (YOR180C):", ""] + (dci or ["- none"]) + [""]


def main() -> None:
    cache = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / ".cache" / "aigr-gem")
    cache.mkdir(parents=True, exist_ok=True)
    out = ["# YEAST-FAO-PWY gene products in yeast GEMs", "",
           "Generated by gem_compartments.py; do not edit by hand.", ""]

    sha = fetch(IMM904_URL, cache / "iMM904.json")
    m = json.loads((cache / "iMM904.json").read_text())
    mcomp = {x["id"]: x["compartment"] for x in m["metabolites"]}
    rx = [(r["id"], r["name"], r.get("gene_reaction_rule") or "",
           as_list((r.get("annotation") or {}).get("ec-code")),
           {mcomp[k] for k in r["metabolites"]}) for r in m["reactions"]]
    summarise(f"iMM904 (sha256 {sha[:16]}; c cytosol, x peroxisome, r ER, m mitochondrion, e extracellular)", rx, out)

    sha = fetch(YEASTGEM_URL, cache / f"yeast-GEM-{YEASTGEM_TAG}.yml")
    y = yaml.load((cache / f"yeast-GEM-{YEASTGEM_TAG}.yml").read_text(), Loader=omap_loader())
    ycomp = {x["id"]: x["compartment"] for x in y["metabolites"]}
    rx = [(r["id"], r.get("name") or "", r.get("gene_reaction_rule") or "",
           as_list((r.get("annotation") or {}).get("ec-code")),
           {ycomp[k] for k in r["metabolites"]}) for r in y["reactions"]]
    summarise(f"yeast-GEM {y['metaData']['version']} (sha256 {sha[:16]}; c cytosol, p peroxisome, "
              "erm ER membrane, lp lipid particle, ce cell envelope, e extracellular)", rx, out)

    Path(__file__).with_name("gem_compartments.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
