"""Compare GO-CAM YeastPathways_PWY-5177 with two yeast genome-scale metabolic models.

Downloads iMM904 (BiGG) and yeast-GEM (pinned tag) into a cache directory
outside the repository, then writes gem_reactions.md listing, for each model:
  * every reaction whose GPR names ERG10 (YPL028W), PHS1 (YJL097W),
    FOX2 (YKR009C) or POT1 (YIL160C), restricted to the short-chain (C4)
    steps and the acetoacetyl-CoA thiolase steps the GO-CAM depicts, plus a
    count of each gene's other reactions with their compartments;
  * every reaction that involves glutaryl-CoA or glutaconyl-CoA.
Nothing is hardcoded: the output is whatever the downloaded models contain.

Usage: uv run python gem_check.py [CACHE_DIR]
"""

import hashlib
import json
import sys
import urllib.request
from collections import Counter
from pathlib import Path

import yaml

IMM904_URL = "https://bigg.ucsd.edu/static/models/iMM904.json"
YEASTGEM_TAG = "v9.1.1"
YEASTGEM_URL = (
    "https://raw.githubusercontent.com/SysBioChalmers/yeast-GEM/"
    f"{YEASTGEM_TAG}/model/yeast-GEM.yml"
)
GENES = {"YPL028W": "ERG10", "YJL097W": "PHS1", "YKR009C": "FOX2", "YIL160C": "POT1"}
# C4 / acetoacetyl-CoA metabolites of the GO-CAM (BiGG ids and yeast-GEM names)
C4_BIGG = {"aacoa", "b2coa", "3hbcoa", "3hbcoa_R", "3hbcoa_S"}
C4_NAMES = {
    "acetoacetyl-coa", "trans-but-2-enoyl-coa", "crotonoyl-coa",
    "(r)-3-hydroxybutanoyl-coa", "(s)-3-hydroxybutanoyl-coa", "3-hydroxybutanoyl-coa",
}
GLUT = ("glutaryl-coa", "glutaconyl", "glutcoa", "glutccoa")


def is_glut(name: str) -> bool:
    """Glutaryl-/glutaconyl-CoA, excluding 3-hydroxy-3-methylglutaryl-CoA (HMG-CoA)."""
    n = name.lower().replace("methylglutaryl", "")
    return any(x in n for x in GLUT)


def fetch(url: str, dest: Path) -> str:
    if not dest.exists():
        urllib.request.urlretrieve(url, dest)
    return hashlib.sha256(dest.read_bytes()).hexdigest()


def omap_loader():
    class Loader(yaml.SafeLoader):
        pass

    def omap(loader, node):
        return {k: v for item in loader.construct_sequence(node, deep=True) for k, v in item.items()}

    Loader.add_constructor("tag:yaml.org,2002:omap", omap)
    return Loader


def genes_in(gpr: str) -> list[str]:
    return [sym for loc, sym in GENES.items() if loc in (gpr or "")]


def direction(lb: float, ub: float) -> str:
    if lb < 0 < ub:
        return "reversible"
    if lb >= 0:
        return "forward only"
    return "reverse only"


def side(st: dict, sign: int, label) -> str:
    return " + ".join(f"{abs(v):g} {label(k)}" for k, v in st.items() if v * sign > 0)


def main() -> None:
    cache = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / ".cache" / "aigr-gem")
    cache.mkdir(parents=True, exist_ok=True)
    out = ["# GEM check for GO-CAM YeastPathways_PWY-5177", "",
           "Generated by gem_check.py; do not edit by hand.", ""]

    # iMM904
    sha = fetch(IMM904_URL, cache / "iMM904.json")
    m = json.loads((cache / "iMM904.json").read_text())
    out += [f"## iMM904 ({IMM904_URL}, sha256 {sha[:16]})", ""]
    other = Counter()
    present = set()
    for r in m["reactions"]:
        mets = r["metabolites"]
        base = {k.rsplit("_", 1)[0] for k in mets}
        g = genes_in(r.get("gene_reaction_rule", ""))
        present.update(g)
        glut = any(is_glut(k) for k in mets)
        if glut or (g and base & C4_BIGG):
            eq = f"{side(mets, -1, str)} -> {side(mets, 1, str)}"
            out.append(f"- {r['id']} ({r['name'].strip()}): {eq}; "
                       f"{direction(r['lower_bound'], r['upper_bound'])}; GPR {r.get('gene_reaction_rule') or 'none'}")
        elif g:
            comps = sorted({k.rsplit('_', 1)[1] for k in mets})
            for s in g:
                other[(s, ",".join(comps))] += 1
    out += ["", "Other reactions per gene (compartments):", ""]
    out += [f"- {s}: {n} reactions in [{c}]" for (s, c), n in sorted(other.items())]
    out += ["", "Genes absent from iMM904 GPRs: " + (", ".join(sorted(set(GENES.values()) - present)) or "none"), ""]

    # yeast-GEM
    sha = fetch(YEASTGEM_URL, cache / f"yeast-GEM-{YEASTGEM_TAG}.yml")
    y = yaml.load((cache / f"yeast-GEM-{YEASTGEM_TAG}.yml").read_text(), Loader=omap_loader())
    names = {x["id"]: (x["name"], x["compartment"]) for x in y["metabolites"]}
    out += [f"## yeast-GEM {y['metaData']['version']} ({YEASTGEM_URL}, sha256 {sha[:16]})", ""]
    other = Counter()

    def lab(k):
        n, c = names[k]
        return f"{n}[{c}]"

    for r in y["reactions"]:
        mets = r["metabolites"]
        mnames = {names[k][0].lower() for k in mets}
        gpr = r.get("gene_reaction_rule") or ""
        g = genes_in(gpr)
        glut = any(is_glut(n) for n in mnames)
        if glut or (g and mnames & C4_NAMES):
            eq = f"{side(mets, -1, lab)} -> {side(mets, 1, lab)}"
            out.append(f"- {r['id']} ({r.get('name')}): {eq}; "
                       f"{direction(r.get('lower_bound', -1000), r.get('upper_bound', 1000))}; GPR {gpr or 'none'}")
        elif g:
            comps = sorted({names[k][1] for k in mets})
            for s in g:
                other[(s, ",".join(comps))] += 1
    out += ["", "Other reactions per gene (compartments):", ""]
    out += [f"- {s}: {n} reactions in [{c}]" for (s, c), n in sorted(other.items())]
    n_glut = sum(1 for line in out if line.startswith("- ") and is_glut(line))
    out += ["", f"Reactions above involving glutaryl-CoA or glutaconyl-CoA (both models): {n_glut}", ""]

    Path(__file__).with_name("gem_reactions.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
