"""Audit stereochemistry and compartments of FOX2, PHS1 and ERG10 reactions in yeast GEMs.

Follow-up to gem_check.py. For every reaction whose GPR names FOX2 (YKR009C),
PHS1 (YJL097W) or ERG10 (YPL028W) in iMM904 and yeast-GEM, it reports the
compartment(s), EC codes, and the stereodescriptor of each 3-hydroxyacyl-CoA
participant ((R), (S) or unspecified, read from the metabolite name), then
tallies them per gene and model. Both FOX2 (MFE-2) and PHS1 act on
(3R)-3-hydroxyacyl-CoA, so (S) participants on their reactions are worth
checking. Writes gem_gene_audit.md beside this script.

Usage: uv run python gem_gene_audit.py [CACHE_DIR]   (same cache as gem_check.py)
"""

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

from gem_check import IMM904_URL, YEASTGEM_TAG, YEASTGEM_URL, fetch, omap_loader

GENES = {"YKR009C": "FOX2", "YJL097W": "PHS1", "YPL028W": "ERG10"}
HYDROXY = re.compile(r"3[- ]hydroxy", re.I)


def stereo(name: str) -> str:
    n = name.strip()
    if re.search(r"\(S\)|^S\s", n):
        return "S"
    if re.search(r"\(R\)|^R\s", n):
        return "R"
    return "unspecified"


def audit(model_name, reactions, out):
    tally = defaultdict(Counter)
    comps = defaultdict(Counter)
    rows = []
    for rid, rname, gpr, ecs, parts in reactions:
        for loc, sym in GENES.items():
            if loc not in gpr:
                continue
            cs = sorted({c for _, c in parts})
            comps[sym][",".join(cs)] += 1
            hyd = [(n, stereo(n)) for n, _ in parts if HYDROXY.search(n) and "CoA" in n]
            for _, st in hyd:
                tally[sym][st] += 1
            if hyd:
                desc = "; ".join(f"{n.strip()} [{st}]" for n, st in hyd)
                rows.append(f"- {sym} {rid} ({rname.strip()}) EC {','.join(ecs) or 'none'} in [{','.join(cs)}]: {desc}")
    out += [f"## {model_name}", "", "Compartments of each gene's reactions:", ""]
    for sym in GENES.values():
        if comps[sym]:
            out.append(f"- {sym}: " + ", ".join(f"{n} in [{c}]" for c, n in sorted(comps[sym].items())))
        else:
            out.append(f"- {sym}: no reactions")
    out += ["", "3-hydroxyacyl-CoA stereodescriptors on each gene's reactions:", ""]
    for sym in GENES.values():
        t = tally[sym]
        out.append(f"- {sym}: R={t['R']} S={t['S']} unspecified={t['unspecified']}")
    out += ["", "Reactions with a 3-hydroxyacyl-CoA participant:", ""] + rows + [""]


def main() -> None:
    cache = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / ".cache" / "aigr-gem")
    cache.mkdir(parents=True, exist_ok=True)
    out = ["# FOX2 / PHS1 / ERG10 audit in yeast GEMs", "",
           "Generated by gem_gene_audit.py; do not edit by hand.", ""]

    fetch(IMM904_URL, cache / "iMM904.json")
    m = json.loads((cache / "iMM904.json").read_text())
    mets = {x["id"]: (x["name"], x["compartment"]) for x in m["metabolites"]}
    rx = [(r["id"], r["name"], r.get("gene_reaction_rule") or "",
           (r.get("annotation") or {}).get("ec-code", []),
           [mets[k] for k in r["metabolites"]]) for r in m["reactions"]]
    audit("iMM904 (compartment x = peroxisome, m = mitochondrion, c = cytosol, r = ER)", rx, out)

    fetch(YEASTGEM_URL, cache / f"yeast-GEM-{YEASTGEM_TAG}.yml")
    y = yaml.load((cache / f"yeast-GEM-{YEASTGEM_TAG}.yml").read_text(), Loader=omap_loader())
    mets = {x["id"]: (x["name"], x["compartment"]) for x in y["metabolites"]}
    rx = [(r["id"], r.get("name") or "", r.get("gene_reaction_rule") or "",
           (r.get("annotation") or {}).get("ec-code", []),
           [mets[k] for k in r["metabolites"]]) for r in y["reactions"]]
    audit(f"yeast-GEM {y['metaData']['version']} (p = peroxisome, m = mitochondrion, c = cytosol, erm = ER membrane)", rx, out)

    Path(__file__).with_name("gem_gene_audit.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
