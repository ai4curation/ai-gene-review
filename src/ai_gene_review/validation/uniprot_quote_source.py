"""Checks on *what kind* of UniProt statement a supporting_text quotes.

``local_source_text`` checks that a quote from a ``-uniprot.txt`` file is
verbatim. This module asks what the quoted statement is, because a UniProt
record mixes evidence with labels and with unvetted predictions:

* Experimental and curated statements (kinetics, binding and active sites,
  free text tied to a publication) are good support.
* Family and domain classification is good support for membership, and an
  agent may use membership to argue for a function: NCBIfam, InterPro/Pfam/
  PROSITE signature matches (``ECO:0000259``), the curated UniRule systems
  (HAMAP, PIRSR, PIRNR, RuleBase), family-membership notes ("Belongs to the X
  family") and family cross-references. A family note whose only evidence is
  an ARBA rule is still an unvetted prediction. Structure-derived automatic evidence
  (``ECO:0007...``, e.g. sites from a PDB entry) is also evidence.
* Sequence-analysis features are valid computational evidence: transmembrane
  helices (Phobius), signal peptides (SignalP), disordered regions
  (MobiDB-lite) and coiled coils (Coils), tagged ``ECO:0000256|SAM:...``.
* Unvetted predictions are not evidence: ARBA's association rules ("guilt by
  association" from co-occurring signatures), annotation imported unchecked
  from submitters (``ECO:0000313``, often itself from a genome-annotation
  pipeline), names generated by machine-learning models such as ProtNLM
  (``ECO:0008006``) and electronic GO lines (``IEA:``). Citing one repeats a
  prediction; citing ARBA text for an ARBA annotation is circular.
* Labels restate an annotation rather than support it: protein names and EC
  numbers, keywords, and the record's own GO cross-references.

Three checks follow, all reported as warnings; the first two apply whatever the
quote supports:

``uniprot_quote_unvetted_prediction``
    Every evidence item on the quoted statement is an unvetted prediction
    (``UNVETTED_MARKERS``). A statement that a classification method, a curated
    rule or an experiment also supports is not flagged.
``uniprot_quote_restating_field``
    The quote comes from a label field (``RESTATING_FIELDS``) or a GO
    cross-reference.
``uniprot_quote_existence_as_support``
    The quote is the protein existence (``PE``) line, cited for an ACCEPT row or
    a core function. Existence says nothing about function; it can argue that an
    annotation rests on prediction, but not support accepting one. An accepted
    ND annotation needs evidence that the literature was searched instead.

A quote that occurs in several places is flagged only when every occurrence
would be flagged, so a phrase that is also in a supported comment is not
reported. Before matching, a quote loses any flat-file line codes and feature
keys copied with it; feature ranges (``102..292``) are positions, not an
ellipsis; and brackets the verbatim check treats as editorial are gaps, while
literal notation such as ``[2Fe-2S]`` stays. Quotes that cannot be located are
left to the verbatim check.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from ai_gene_review.validation.local_source_text import (
    PROJECT_ROOT,
    _validator,
    iter_local_quotes,
    resolve_local_source,
)
from ai_gene_review.validation.validation_report import (
    ValidationReport,
    ValidationSeverity,
)

UNVETTED_CHECK = "uniprot_quote_unvetted_prediction"
FIELD_CHECK = "uniprot_quote_restating_field"
EXISTENCE_CHECK = "uniprot_quote_existence_as_support"

#: Line codes that are labels for the entry rather than evidence about it:
#: identifiers, names, gene names, taxonomy, keywords and the sequence.
#: Protein existence (``PE``) is not a label: it is a fair argument that an
#: annotation rests on prediction, though never support for accepting one
#: (``EXISTENCE_CHECK``).
#: Cross-references are labels only for GO (``RESTATING_DR``); family and
#: domain cross-references are classification evidence.
RESTATING_FIELDS = frozenset(
    {"ID", "AC", "DT", "DE", "GN", "OS", "OG", "OC", "OX", "OH", "KW", "SQ"}
)
RESTATING_DR = frozenset({"GO"})

FIELD_LABELS = {
    "DE": "protein name or EC number", "KW": "keyword", "DR": "database cross-reference",
    "GN": "gene name", "OS": "organism", "OC": "taxonomy", "OX": "taxonomy",
    "ID": "entry identifier", "AC": "accession", "DT": "entry date", "PE": "protein existence",
    "SQ": "sequence", "OG": "organelle", "OH": "host",
}

#: (label, markers) for evidence that is an unvetted prediction. An evidence
#: item is unvetted when it contains one of the markers.
UNVETTED_MARKERS = (
    ("ARBA", ("ARBA",)),
    ("imported", ("ECO:0000313",)),
    ("machine-generated name", ("ECO:0008006",)),
    ("electronic GO", ("IEA:",)),
)

_BRACE = re.compile(r"(?:Evidence=)?\{(ECO:[^{}]*)\}")
#: Evidence tokens left over when a quote cuts through a brace.
_STRAY_EVIDENCE = re.compile(r"(?:Evidence=)?\{?ECO:\d{7}(?:\|[^\s,;}]*)?[,;}]?|[{}]")
#: A flat-file line code (``DR   ``, ``CC       ``) copied into a quote, with
#: a feature key after ``FT``; the parsed statements drop both (the key is the
#: statement's topic), so they must go before a quote can be located.
_LINE_CODE = re.compile(r"(?:^|(?<=\s))(?:FT {3}\w+ +|[A-Z]{2} {3,})")
#: Bracketed text. What the verbatim check drops as editorial (``[protein]``)
#: is a gap here, since dropping it would join words that are not adjacent in
#: the record; literal notation (``[2Fe-2S]``) is kept as quoted text.
_BRACKETED = re.compile(r"\[[^\]\n]*\]")
#: A feature range (``102..292``), which must not be read as an ellipsis.
_RANGE = re.compile(r"(?<=[\d<>?])\.\.(?=[<>?]?[\d?])")
_FT_EVIDENCE = re.compile(r'/evidence="([^"]*)"')
_REFERENCE_CODES = frozenset({"RN", "RP", "RC", "RX", "RG", "RA", "RT", "RL"})


@dataclass(frozen=True)
class Statement:
    """One evidence-bearing unit of a UniProt record.

    ``field`` is the line code (``CC``, ``DE``, ``FT`` ...; ``REF`` for a
    citation block), ``topic`` the comment topic, feature key or
    cross-referenced database, and ``evidence`` the evidence strings attached
    to the statement.
    """

    field: str
    topic: str
    text: str
    evidence: Tuple[str, ...]

    @property
    def is_unvetted(self) -> bool:
        """True when the statement has evidence and every item is an unvetted prediction.

        >>> Statement("CC", "FUNCTION", "x", ("ECO:0000256|ARBA:ARBA00003800",)).is_unvetted
        True
        >>> Statement("DE", "", "x", ("ECO:0000313|EMBL:AAN1.1",)).is_unvetted
        True
        >>> Statement("DE", "", "x", ("ECO:0008006|Google:ProtNLM",)).is_unvetted
        True
        >>> Statement("DR", "GO", "x", ("IEA:UniProtKB-ARBA",)).is_unvetted
        True

        Classification methods, curated rules, structures and experiments are
        evidence, alone or alongside ARBA:

        >>> Statement("DE", "", "x", ("ECO:0000256|NCBIfam:TIGR01792",)).is_unvetted
        False
        >>> Statement("CC", "COFACTOR", "x", ("ECO:0000256|PIRSR:PIRSR1-51",)).is_unvetted
        False
        >>> Statement("KW", "", "x", ("ECO:0000256|ARBA:ARBA1", "ECO:0000256|RuleBase:RU1")).is_unvetted
        False
        >>> Statement("FT", "BINDING", "x", ("ECO:0007744|PDB:1ABC",)).is_unvetted
        False
        >>> Statement("FT", "TRANSMEM", "Helical", ("ECO:0000256|SAM:Phobius",)).is_unvetted
        False
        >>> Statement("CC", "FUNCTION", "x", ("ECO:0000256|ARBA:ARBA1", "ECO:0000269|PubMed:1")).is_unvetted
        False
        >>> Statement("CC", "FUNCTION", "x", ()).is_unvetted
        False
        """
        return bool(self.evidence) and all(_unvetted_label(e) for e in self.evidence)

    @property
    def unvetted_sources(self) -> Tuple[str, ...]:
        """Labels of the unvetted sources behind the statement.

        >>> Statement("DR", "GO", "x", ("IEA:UniProtKB-ARBA",)).unvetted_sources
        ('ARBA', 'electronic GO')
        """
        return tuple(label for label, markers in UNVETTED_MARKERS
                     if any(m in e for e in self.evidence for m in markers))

    @property
    def is_restating(self) -> bool:
        """True for label fields and the record's own GO cross-references.

        >>> Statement("DE", "", "RecName: Full=X", ()).is_restating
        True
        >>> Statement("DR", "GO", "GO; GO:1; F:x; IEA:InterPro.", ()).is_restating
        True

        Family membership and other cross-references are evidence:

        >>> Statement("CC", "SIMILARITY", "Belongs to the X family", ()).is_restating
        False
        >>> Statement("DR", "NCBIfam", "NCBIfam; TIGR01792; urease_alph; 1.", ()).is_restating
        False
        >>> Statement("CC", "BIOPHYSICOCHEMICAL PROPERTIES", "KM=2 uM", ()).is_restating
        False
        """
        return self.field in RESTATING_FIELDS or (self.field == "DR" and self.topic in RESTATING_DR)


def _unvetted_label(evidence: str) -> Optional[str]:
    """The unvetted-source label for one evidence item, or None if it is evidence.

    >>> _unvetted_label("ECO:0000256|ARBA:ARBA1"), _unvetted_label("ECO:0000256|HAMAP-Rule:MF_1")
    ('ARBA', None)
    """
    for label, markers in UNVETTED_MARKERS:
        if any(m in evidence for m in markers):
            return label
    return None


def _split_evidence(text: str) -> Tuple[str, ...]:
    """Split an evidence list; ids never contain spaces, so line-wrap spaces are removed.

    >>> _split_evidence("ECO:0000256|PIRSR:PIRSR611612- 51, ECO:0000269|PubMed:1")
    ('ECO:0000256|PIRSR:PIRSR611612-51', 'ECO:0000269|PubMed:1')
    """
    return tuple(e.replace(" ", "") for e in text.split(",") if e.strip())


def _chunk(field: str, topic: str, text: str) -> List[Statement]:
    """Split a block into statements, each ending at its evidence brace.

    >>> [(s.text, s.evidence) for s in _chunk("KW", "", "NAD {ECO:1}; Oxidoreductase {ECO:2, ECO:3}.")]
    [('NAD', ('ECO:1',)), ('; Oxidoreductase', ('ECO:2', 'ECO:3'))]
    """
    out: List[Statement] = []
    prev = 0
    for m in _BRACE.finditer(text):
        piece = text[prev:m.start()].strip()
        if piece:
            out.append(Statement(field, topic, piece, _split_evidence(m.group(1))))
        prev = m.end()
    rest = text[prev:].strip()
    if re.search(r"\w", rest):
        out.append(Statement(field, topic, rest, ()))
    return out


def parse_uniprot_statements(raw: str) -> List[Statement]:
    """Parse a UniProt flat file into statements with their evidence.

    >>> flat = (
    ...     "DE   RecName: Full=Kinase {ECO:0000256|ARBA:ARBA1};\\n"
    ...     "CC   -!- FUNCTION: Binds DNA. {ECO:0000269|PubMed:1}.\\n"
    ...     "DR   GO; GO:0003677; F:DNA binding; IEA:UniProtKB-ARBA.\\n"
    ...     "FT   BINDING         10\\n"
    ...     'FT                   /evidence="ECO:0000269|PubMed:2"\\n'
    ... )
    >>> [(s.field, s.topic, s.evidence) for s in parse_uniprot_statements(flat)]
    [('DE', '', ('ECO:0000256|ARBA:ARBA1',)), ('CC', 'FUNCTION', ('ECO:0000269|PubMed:1',)), ('DR', 'GO', ('IEA:UniProtKB-ARBA',)), ('FT', 'BINDING', ('ECO:0000269|PubMed:2',))]
    """
    blocks: List[Tuple[str, str, List[str]]] = []

    def start(field: str, topic: str, body: str) -> None:
        blocks.append((field, topic, [body]))

    for line in raw.splitlines():
        if line.startswith("//"):
            continue
        code, body = line[:2], line[5:].strip()
        if code == "  ":
            code = "SQ"
        if code == "CC":
            if body.startswith("-!-"):
                topic = body[3:].split(":", 1)[0].strip()
                start("CC", topic, body)
            elif body.startswith("---"):
                start("CC", "COPYRIGHT", body)
            elif blocks and blocks[-1][0] == "CC":
                blocks[-1][2].append(body)
            else:
                start("CC", "", body)
        elif code == "FT":
            if line[5:6] != " ":
                start("FT", line[5:21].strip(), line[21:].strip())
            elif blocks and blocks[-1][0] == "FT":
                blocks[-1][2].append(body)
        elif code == "DR":
            start("DR", body.split(";", 1)[0].strip(), body)
        elif code in _REFERENCE_CODES:
            if code == "RN" or not blocks or blocks[-1][0] != "REF":
                start("REF", "", body)
            else:
                blocks[-1][2].append(body)
        elif blocks and blocks[-1][0] == code:
            blocks[-1][2].append(body)
        else:
            start(code, "", body)

    statements: List[Statement] = []
    for field, topic, lines in blocks:
        text = " ".join(lines)
        if field == "FT":
            evidence = tuple(e for m in _FT_EVIDENCE.finditer(text) for e in _split_evidence(m.group(1)))
            statements.append(Statement(field, topic, text, evidence))
        elif field == "DR" and topic == "GO":
            source = text.rstrip(".").rsplit(";", 1)[-1].strip()
            statements.append(Statement(field, topic, text, (source,)))
        elif field in ("DR", "REF", "SQ"):
            statements.append(Statement(field, topic, text, ()))
        else:
            statements.extend(_chunk(field, topic, text))
    return statements


@lru_cache(maxsize=256)
def _indexed(path: Path, mtime_ns: int, size: int) -> Tuple[Tuple[Statement, ...], str, Tuple[int, ...]]:
    """Statements of *path*, their normalised concatenation, and each one's start offset."""
    statements = tuple(parse_uniprot_statements(path.read_text(encoding="utf-8")))
    normalize = _validator().normalize_text
    starts: List[int] = []
    pieces: List[str] = []
    offset = 0
    for s in statements:
        piece = normalize(s.text)
        starts.append(offset)
        pieces.append(piece)
        offset += len(piece) + 1
    return statements, " ".join(pieces), tuple(starts)


def _occurrences(part: str, statements, text: str, starts) -> List[List[Statement]]:
    """Every whole-word place *part* occurs, as the list of statements each occurrence spans.

    Normalised text is space-separated words, so padding both sides with a
    space keeps "nad" from matching inside "canadensis".
    """
    padded, needle = f" {text} ", f" {part} "
    ends = list(starts[1:]) + [len(text) + 1]
    found = []
    i = padded.find(needle)
    while i >= 0:
        # padded[i] is the space before the match, so the match starts at text[i]
        end = i + len(part)
        found.append([s for s, a, b in zip(statements, starts, ends) if a < end and b - 1 > i])
        i = padded.find(needle, i + 1)
    return found


def _quote_parts(quote: str) -> List[str]:
    """Normalised ``...``-separated parts of a quote, without evidence tags.

    >>> _quote_parts("Oxidoreductase {ECO:0000256|ARBA:ARBA00023002, ... NAD {ECO:0000256|ARBA:ARBA1};")
    ['oxidoreductase', 'nad']
    >>> _quote_parts("DR   GO; GO:0003677; F:DNA binding; IEA:InterPro.")
    ['go go 0003677 f dna binding iea interpro']
    >>> _quote_parts("CC       Reaction=L-seryl-[protein] + ATP")
    ['reaction l seryl', 'atp']
    >>> _quote_parts("Name=[2Fe-2S] cluster")
    ['name 2fe 2s cluster']
    >>> _quote_parts("FT   DNA_BIND        102..292")
    ['102 292']
    >>> _quote_parts("FT   CHAIN           ?..649")
    ['649']
    """
    validator = _validator()

    def gap(m: re.Match) -> str:
        inner = m.group(0)[1:-1]
        return m.group(0) if any(p.search(inner) for p in validator._literal_bracket_regexes) else " ... "

    stripped = _BRACKETED.sub(gap, _RANGE.sub(" ", _LINE_CODE.sub(" ", quote)))
    stripped = _STRAY_EVIDENCE.sub(" ", _BRACE.sub(" ", stripped))
    return [p for p in (validator.normalize_text(x) for x in validator._split_query(stripped)) if p]


def _index(path: Path):
    stat = path.stat()
    return _indexed(path, stat.st_mtime_ns, stat.st_size)


def locate_quote(quote: str, path: Path) -> List[Statement]:
    """Statements spanned by the first occurrence of each part of *quote*; [] if not located."""
    statements, text, starts = _index(path)
    located: List[Statement] = []
    for part in _quote_parts(quote):
        occ = _occurrences(part, statements, text, starts)
        if not occ:
            return []
        located.extend(s for s in occ[0] if s not in located)
    return located


def classify_quote(quote: str, path: Path) -> Optional[Tuple[bool, bool, List[Statement]]]:
    """``(unvetted, restating, statements)`` for a quote, or None if not located.

    A flag holds only if it holds for every occurrence of every part.
    """
    statements, text, starts = _index(path)
    parts = _quote_parts(quote)
    if not parts:
        return None
    unvetted = restating = True
    first: List[Statement] = []
    for part in parts:
        occ = _occurrences(part, statements, text, starts)
        if not occ:
            return None
        first.extend(s for s in occ[0] if s not in first)
        unvetted &= all(all(s.is_unvetted for s in o) for o in occ)
        restating &= all(all(s.is_restating for s in o) for o in occ)
    return unvetted, restating, first


@dataclass(frozen=True)
class QuoteFinding:
    """A flagged UniProt quote."""

    path: str
    reference_id: str
    check_type: str
    statements: Tuple[Statement, ...]


_ELEMENT = re.compile(r"^(existing_annotations|core_functions)\[(\d+)\]")


def _accepts(data: Any, path: str) -> bool:
    """Whether the quote at *path* supports accepting a function: an ACCEPT row or a core function.

    >>> data = {"existing_annotations": [{"review": {"action": "ACCEPT"}},
    ...                                  {"review": {"action": "MARK_AS_OVER_ANNOTATED"}}]}
    >>> _accepts(data, "existing_annotations[0].review.supported_by[0].supporting_text")
    True
    >>> _accepts(data, "existing_annotations[1].review.supported_by[0].supporting_text")
    False
    >>> _accepts(data, "core_functions[0].supported_by[0].supporting_text")
    True
    >>> _accepts(data, "references[0].findings[0].supporting_text")
    False
    """
    m = _ELEMENT.match(path)
    if not m:
        return False
    if m.group(1) == "core_functions":
        return True
    try:
        element = data["existing_annotations"][int(m.group(2))]
    except (KeyError, IndexError, TypeError):
        return False
    return ((element or {}).get("review") or {}).get("action") == "ACCEPT"


def _is_nd(data: Any, path: str) -> bool:
    m = _ELEMENT.match(path)
    if not m or m.group(1) != "existing_annotations":
        return False
    try:
        return data["existing_annotations"][int(m.group(2))].get("evidence_type") == "ND"
    except (KeyError, IndexError, TypeError, AttributeError):
        return False


def quote_source_findings(data: Any, project_root: Path = PROJECT_ROOT) -> List[QuoteFinding]:
    """Flagged UniProt quotes in a review document."""
    findings: List[QuoteFinding] = []
    for path, reference_id, quote in iter_local_quotes(data):
        source = resolve_local_source(reference_id, project_root)
        if source is None or not source.name.endswith("-uniprot.txt"):
            continue
        result = classify_quote(quote, source)
        if result is None:
            continue
        unvetted, restating, statements = result
        if unvetted:
            findings.append(QuoteFinding(path, reference_id, UNVETTED_CHECK, tuple(statements)))
        if restating:
            findings.append(QuoteFinding(path, reference_id, FIELD_CHECK, tuple(statements)))
        if all(s.field == "PE" for s in statements) and _accepts(data, path):
            findings.append(QuoteFinding(path, reference_id, EXISTENCE_CHECK, tuple(statements)))
    return findings


def _describe(statements: Tuple[Statement, ...]) -> str:
    labels: Dict[str, None] = {}
    for s in statements:
        if s.field == "CC":
            labels[f"comment ({s.topic})"] = None
        elif s.field == "DR":
            labels[f"{FIELD_LABELS['DR']} ({s.topic})"] = None
        elif s.field == "FT":
            labels[f"feature ({s.topic})"] = None
        else:
            labels[FIELD_LABELS.get(s.field, s.field)] = None
    return ", ".join(labels)


def validate_uniprot_quote_sources(
    data: Any, report: ValidationReport, project_root: Path = PROJECT_ROOT
) -> None:
    """Warn on UniProt quotes that are unvetted predictions or labels, or that cite protein existence for an ACCEPT."""
    for f in quote_source_findings(data, project_root):
        where = _describe(f.statements)
        if f.check_type == EXISTENCE_CHECK:
            message = (
                "Supporting text quotes UniProt protein existence, which says whether the protein "
                "exists, not what it does; it cannot support accepting a function"
            )
            if _is_nd(data, f.path):
                suggestion = (
                    "Accepting an ND (no data) annotation needs evidence that the literature was "
                    "searched and found nothing, not the protein's existence level"
                )
            else:
                suggestion = (
                    "Cite evidence for the function itself; protein existence can support "
                    "MARK_AS_OVER_ANNOTATED or UNDECIDED, not ACCEPT"
                )
        elif f.check_type == UNVETTED_CHECK:
            labels = sorted({label for s in f.statements for label in s.unvetted_sources})
            evidence = sorted({e for s in f.statements for e in s.evidence})
            message = (
                f"Supporting text quotes a UniProt {where} supported only by an unvetted "
                f"prediction ({', '.join(labels)}: {', '.join(evidence)}); it is not evidence"
            )
            suggestion = (
                "Cite an experimental or curated statement, family or domain classification, "
                "the publication behind it, or your own analysis"
            )
        else:
            message = (
                f"Supporting text quotes a UniProt {where}, a label that restates an "
                "annotation rather than giving evidence for it"
            )
            suggestion = (
                "Quote evidence instead: kinetics, sites, family or domain membership, or "
                "curated free text tied to a publication"
            )
        report.add_issue(
            ValidationSeverity.WARNING,
            message,
            path=f.path,
            suggestion=suggestion,
            validation_category="BestPractices",
            check_type=f.check_type,
        )
