"""Compute paper statistics from paper/data/*.tsv.

Writes paper/generated/stats.tex (\\newcommand macros) and
paper/generated/tab_*.tex (table bodies) and figures to paper/figures/.
Every number quoted in the manuscript must come from here.
"""
import os
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
D, G, F = (os.path.join(ROOT, x) for x in ("data", "generated", "figures"))
os.makedirs(G, exist_ok=True); os.makedirs(F, exist_ok=True)

ACTIONS = ["ACCEPT", "KEEP_AS_NON_CORE", "MODIFY", "TOO_GENERAL",
           "MARK_AS_OVER_ANNOTATED", "REMOVE", "UNDECIDED"]
SHORT = {"ACCEPT": "Accept", "KEEP_AS_NON_CORE": "Non-core", "MODIFY": "Modify",
         "TOO_GENERAL": "Too general", "MARK_AS_OVER_ANNOTATED": "Over-ann.",
         "REMOVE": "Remove", "UNDECIDED": "Undecided"}
EXP = {"EXP", "IDA", "IPI", "IMP", "IGI", "IEP"}
HTP = {"HTP", "HDA", "HMP", "HGI", "HEP"}
PHYLO = {"IBA", "IBD", "IRD", "IKR"}
SEQ = {"ISS", "ISO", "ISA", "ISM", "IGC", "RCA"}
AUTH = {"TAS", "NAS", "IC"}

def egroup(e):
    for name, s in (("Experimental", EXP), ("High-throughput", HTP), ("Phylogenetic (IBA)", PHYLO),
                    ("Sequence/orthology", SEQ), ("Author/curator statement", AUTH)):
        if e in s:
            return name
    return {"IEA": "Electronic (IEA)", "ND": "No data (ND)"}.get(e, "Other")

GOREF = {  # GO_REF ids -> pipeline names (http://geneontology.org/gorefs)
    "GO_REF:0000002": "InterPro2GO", "GO_REF:0000003": "EC2GO", "GO_REF:0000041": "UniPathway2GO",
    "GO_REF:0000043": "UniProt keyword2GO", "GO_REF:0000044": "UniProt subcellular location2GO",
    "GO_REF:0000104": "UniRule", "GO_REF:0000107": "Ensembl Compara orthology",
    "GO_REF:0000108": "GO logical inference", "GO_REF:0000115": "RNAcentral",
    "GO_REF:0000116": "Rhea2GO", "GO_REF:0000117": "ARBA", "GO_REF:0000118": "TreeGrafter",
    "GO_REF:0000120": "Combined automated (UniProt)",
}

macros = {}
def mac(name, val):
    if isinstance(val, float):
        val = f"{val:.1f}"
    elif isinstance(val, int):
        val = f"{val:,}"
    macros[name] = val

a = pd.read_csv(os.path.join(D, "annotations.tsv"), sep="\t", low_memory=False)
r = pd.read_csv(os.path.join(D, "reviews.tsv"), sep="\t", low_memory=False)
m = pd.read_csv(os.path.join(D, "goa_meta.tsv"), sep="\t", low_memory=False, dtype=str)

new = a[a.action == "NEW"]
a = a[a.action.isin(ACTIONS)].copy()
a = a.merge(m, on=["id", "term_id", "evidence_type", "reference"], how="left")
a["egroup"] = a.evidence_type.map(egroup)
a["pb"] = a.term_id == "GO:0005515"
a["rejected"] = a.action.isin(["REMOVE", "MARK_AS_OVER_ANNOTATED"])
a["changed"] = a.action.isin(["REMOVE", "MARK_AS_OVER_ANNOTATED", "MODIFY", "TOO_GENERAL"])

mac("nReviews", len(r)); mac("nOrgFolders", r.organism.nunique())
mac("nAnn", len(a)); mac("nNew", len(new)); mac("nPB", int(a.pb.sum()))
mac("pctPB", 100 * a.pb.mean())
mac("nRefs", int(r.n_references.sum())); mac("nCoreFns", int(r.n_core_functions.sum()))
mac("nProposedTerms", int(r.n_proposed_new_terms.sum()))
mac("nKnowledgeGaps", int(r.n_knowledge_gaps.sum()))
mac("aspectMatched", 100 * a.aspect.notna().mean())
for act in ACTIONS:
    mac("pct" + act.title().replace("_", ""), 100 * (a.action == act).mean())
b = a[~a.pb]
mac("nAnnNoPB", len(b))
for act in ACTIONS:
    mac("pct" + act.title().replace("_", "") + "NoPB", 100 * (b.action == act).mean())
mac("pctRejectedNoPB", 100 * b.rejected.mean()); mac("pctChangedNoPB", 100 * b.changed.mean())
mac("pctRejectedAll", 100 * a.rejected.mean()); mac("pctChangedAll", 100 * a.changed.mean())

def pct_table(df, by, order=None, min_n=0):
    t = pd.crosstab(df[by], df.action)
    for c in ACTIONS:
        if c not in t: t[c] = 0
    n = t.sum(1)
    p = t[ACTIONS].div(n, axis=0) * 100
    p.insert(0, "n", n)
    p = p[p.n >= min_n]
    if order: p = p.reindex([o for o in order if o in p.index])
    else: p = p.sort_values("n", ascending=False)
    return p

def write_tab(p, fname, label_col):
    lines = []
    for idx, row in p.iterrows():
        cells = [str(idx).replace("_", r"\_").replace("&", r"\&"), f"{int(row.n):,}"]
        cells += [f"{row[c]:.1f}" for c in ACTIONS]
        lines.append(" & ".join(cells) + r" \\")
    with open(os.path.join(G, fname), "w") as fh:
        fh.write("% generated by scripts/compute_stats.py -- do not edit\n")
        fh.write("\\begin{tabular}{lrrrrrrrr}\\toprule\n")
        fh.write(" & ".join([label_col, "$n$"] + [SHORT[c] for c in ACTIONS]) + r" \\ \midrule" + "\n")
        fh.write("\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")

EG = ["Experimental", "High-throughput", "Author/curator statement", "Phylogenetic (IBA)",
      "Sequence/orthology", "Electronic (IEA)", "No data (ND)"]
write_tab(pct_table(b, "egroup", EG), "tab_action_by_egroup.tex", "Evidence class")
write_tab(pct_table(b, "evidence_type", min_n=400), "tab_action_by_code.tex", "Code")
write_tab(pct_table(b.dropna(subset=["aspect"]), "aspect", ["MF", "BP", "CC"]), "tab_action_by_aspect.tex", "Aspect")
iea = b[b.evidence_type == "IEA"].copy()
iea["pipeline"] = iea.reference.map(GOREF).fillna("other")
write_tab(pct_table(iea, "pipeline", min_n=200), "tab_action_by_iea_pipeline.tex", "IEA pipeline")
write_tab(pct_table(a[a.pb], "evidence_type", min_n=100), "tab_protein_binding.tex", "Code")
write_tab(pct_table(b.dropna(subset=["assigned_by"]), "assigned_by", min_n=1500), "tab_action_by_assigned_by.tex", "Assigned by")
for grp in ["ComplexPortal", "CACAO", "PseudoCAP", "SynGO", "SynGO-UCL"]:
    sub = b[b.assigned_by == grp]
    if len(sub):
        k = "".join(ch for ch in grp if ch.isalpha())
        mac("n" + k, len(sub)); mac("rej" + k, 100 * sub.rejected.mean())
        mac("acc" + k, 100 * (sub.action == "ACCEPT").mean())
orgs = b.organism.value_counts().head(12).index.tolist()
write_tab(pct_table(b[b.organism.isin(orgs)], "organism"), "tab_action_by_organism.tex", "Organism")

for g, sub in b.groupby("egroup"):
    key = "".join(ch for ch in g.title() if ch.isalpha())
    mac("rej" + key, 100 * sub.rejected.mean()); mac("acc" + key, 100 * (sub.action == "ACCEPT").mean())
    mac("n" + key, len(sub))
for code in ["IDA", "IMP", "IPI", "IGI", "IEP", "HDA", "IBA", "ISS", "ISO", "TAS", "NAS", "IEA", "RCA", "EXP"]:
    sub = b[b.evidence_type == code]
    if len(sub):
        mac("rej" + code, 100 * sub.rejected.mean()); mac("acc" + code, 100 * (sub.action == "ACCEPT").mean())
        mac("mod" + code, 100 * (sub.action == "MODIFY").mean()); mac("n" + code, len(sub))
pbs = a[a.pb]
mac("pbRemove", 100 * (pbs.action == "REMOVE").mean()); mac("pbModify", 100 * (pbs.action == "MODIFY").mean())

# figure: stacked bars by evidence class
try:
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    p = pct_table(b, "egroup", EG)
    colors = ["#2b8a3e", "#8ce99a", "#4dabf7", "#ced4da", "#ffa94d", "#e03131", "#868e96"]
    fig, ax = plt.subplots(figsize=(7, 3.2))
    left = [0] * len(p)
    for c, col in zip(ACTIONS, colors):
        ax.barh([f"{i} (n={int(n):,})" for i, n in zip(p.index, p.n)], p[c], left=left, color=col, label=SHORT[c])
        left = [x + y for x, y in zip(left, p[c])]
    ax.invert_yaxis(); ax.set_xlabel("% of reviewed annotations"); ax.set_xlim(0, 100)
    ax.legend(ncol=4, fontsize=7, loc="upper center", bbox_to_anchor=(0.5, -0.22), frameon=False)
    fig.tight_layout(); fig.savefig(os.path.join(F, "action_by_evidence.pdf")); plt.close(fig)
except ImportError:
    pass

with open(os.path.join(G, "stats.tex"), "w") as fh:
    fh.write("% generated by scripts/compute_stats.py -- do not edit\n")
    for k, v in sorted(macros.items()):
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(f"{len(macros)} macros written")
