"""Manifest of the sequence alignments behind gene reviews, for the data release.

Scans genes/*/*/*-bioinformatics/ for alignment files, identified by content, not name:
aligned FASTA (>= 2 records, equal lengths, containing gaps), Clustal (CLUSTAL header) or
Stockholm (# STOCKHOLM header). Records path, SHA-256, format, sequence count and column count,
and links each gene to its MSA-based residue claims (data/residue_claims.tsv).

Outputs: paper/release/alignment_manifest.tsv, paper/generated/stats_alignments.{tex,json}
"""
import csv, glob, hashlib, json, os
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PAPER = os.path.join(ROOT, "paper")
EXT = {".aln", ".afa", ".fa", ".fasta", ".faa", ".fas", ".sto", ".stk", ".msa", ".clustal", ".mfa", ".txt"}
MAX_BYTES = 50_000_000

def parse_fasta(text):
    recs, cur = {}, None
    for line in text.splitlines():
        if line.startswith(">"):
            cur = line[1:].strip() or f"seq{len(recs)}"; recs[cur] = []
        elif cur is not None:
            recs[cur].append(line.strip())
    return {k: "".join(v) for k, v in recs.items()}

def classify(path):
    """Return (format, n_seqs, n_cols) for an alignment file, or None."""
    if os.path.getsize(path) > MAX_BYTES:
        return None
    text = open(path, errors="replace").read()
    head = text.lstrip()[:200]
    if head.startswith("# STOCKHOLM"):
        names = {l.split()[0] for l in text.splitlines() if l and not l.startswith(("#", "//")) and len(l.split()) == 2}
        cols = sum(len(l.split()[1]) for l in text.splitlines() if l and l.split()[0] == next(iter(names), None)) if names else 0
        return ("stockholm", len(names), cols)
    if head.upper().startswith("CLUSTAL") or head.startswith("MUSCLE"):
        rows = [l.split() for l in text.splitlines()[1:] if l and not l.startswith(" ") and len(l.split()) >= 2]
        names = {r[0] for r in rows}
        first = next(iter(names), None)
        cols = sum(len(r[1]) for r in rows if r[0] == first)
        return ("clustal", len(names), cols)
    if head.startswith(">"):
        recs = parse_fasta(text)
        lens = {len(s) for s in recs.values()}
        if len(recs) >= 2 and len(lens) == 1 and any("-" in s for s in recs.values()):
            return ("aligned-fasta", len(recs), lens.pop())
    return None

def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "genes", "*", "*", "*-bioinformatics", "**", "*"), recursive=True)):
        if not os.path.isfile(path) or os.path.splitext(path)[1].lower() not in EXT or "/.venv/" in path:
            continue
        c = classify(path)
        if not c:
            continue
        rel = os.path.relpath(path, ROOT)
        org, gdir = rel.split(os.sep)[1:3]
        rows.append({"organism": org, "gene_dir": gdir, "path": rel, "format": c[0], "n_seqs": c[1], "n_cols": c[2],
                     "sha256": hashlib.sha256(open(path, "rb").read()).hexdigest()})
    os.makedirs(os.path.join(PAPER, "release"), exist_ok=True)
    with open(os.path.join(PAPER, "release", "alignment_manifest.tsv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()), delimiter="\t"); w.writeheader(); w.writerows(rows)
    man = pd.DataFrame(rows)
    rc = pd.read_csv(os.path.join(PAPER, "data", "residue_claims.tsv"), sep="\t")
    msa = rc[(rc.method == "MSA") & (~rc.not_applicable)]
    # residue_claims.tsv carries gene symbols; gene folders are usually the symbol
    have = set(zip(man.organism, man.gene_dir))
    msa_genes = set(zip(msa.organism, msa.gene))
    covered = {g for g in msa_genes if g in have}
    pairwise = msa.comment.fillna("").str.contains(r"pairwise|needle|water|BLOSUM|Smith.Waterman|Needleman", case=False)
    macros = {"nAlnMsaPairwise": f"{int(pairwise.sum()):,}", "nAlnFiles": f"{len(man):,}", "nAlnGenes": f"{len(have):,}",
              "nAlnMsaClaimGenes": f"{len(msa_genes):,}", "nAlnMsaClaimGenesCovered": f"{len(covered):,}",
              "nAlnMsaClaims": f"{len(msa):,}",
              "nAlnMsaClaimsCovered": f"{int(msa.apply(lambda r: (r.organism, r.gene) in have, axis=1).sum()):,}"}
    with open(os.path.join(PAPER, "generated", "stats_alignments.tex"), "w") as fh:
        fh.write("% generated by scripts/alignment_manifest.py -- do not edit\n")
        for k, v in sorted(macros.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    json.dump({**macros, "msa_claim_genes_without_alignment": sorted("/".join(g) for g in msa_genes - covered)},
              open(os.path.join(PAPER, "generated", "stats_alignments.json"), "w"), indent=1)
    print(json.dumps(macros, indent=1)); print(man.format.value_counts().to_dict())
    print("MSA-claim genes without an alignment file:", sorted("/".join(g) for g in msa_genes - covered))

if __name__ == "__main__":
    main()
