"""Fetch GOA-wide annotation counts from QuickGO, for Table 1 shares and the extrapolation.

QuickGO's search endpoint ignores a GO evidence code filter, so counts are taken per ECO code
(exact match) and summed to GO evidence codes using the ECO->GO-code pairs observed in the
repository's own GOA files (every ECO code there maps to exactly one GO code). ECO codes not
seen locally are reported as an unmapped residual. Electronic pipelines are counted by GO_REF.

QuickGO is live, so totals drift slightly between queries; the fetch date is recorded.
Writes paper/release/goa_counts.yaml. Re-run with --refresh to refetch; otherwise the cached
file is kept.
"""
import argparse, csv, datetime, glob, json, os, sys, time, urllib.request
from concurrent.futures import ThreadPoolExecutor
import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "paper", "release", "goa_counts.yaml")
API = "https://www.ebi.ac.uk/QuickGO/services/annotation"
PIPELINES = ["GO_REF:0000002", "GO_REF:0000003", "GO_REF:0000041", "GO_REF:0000043", "GO_REF:0000044",
             "GO_REF:0000104", "GO_REF:0000107", "GO_REF:0000108", "GO_REF:0000116", "GO_REF:0000117",
             "GO_REF:0000118", "GO_REF:0000120", "GO_REF:0000033"]
ROOTS = "goId=GO:0008150,GO:0003674,GO:0005575&goUsage=descendants&goUsageRelationships=is_a,part_of,occurs_in"

def get(url, tries=4):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=600) as r:
                return json.load(r)
        except Exception as e:  # network: retry with backoff
            if i == tries - 1:
                raise
            time.sleep(2 ** (i + 1))
            print(f"retry {url}: {e}", file=sys.stderr)

def hits(query):
    return int(get(f"{API}/search?{query}&limit=1")["numberOfHits"])

def eco_map():
    m = {}
    for f in glob.glob(os.path.join(ROOT, "genes", "*", "*", "*-goa.tsv")):
        with open(f, newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                e, g = r.get("ECO ID"), r.get("GO EVIDENCE CODE")
                if e and g:
                    m.setdefault(e, set()).add(g)
    clash = {e: g for e, g in m.items() if len(g) > 1}
    if clash:
        raise SystemExit(f"ECO codes mapping to several GO codes: {clash}")
    return {e: g.pop() for e, g in m.items()}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--refresh", action="store_true"); a = ap.parse_args()
    if os.path.exists(OUT) and not a.refresh:
        print(f"{OUT} exists; use --refresh to refetch"); return
    stats = get(f"{API}/stats?{ROOTS}")
    ann = next(g for g in stats["results"] if g["groupName"] == "annotation")
    total = int(ann["totalHits"])
    aspect = {v["key"]: int(v["hits"]) for t in ann["types"] if t["type"] == "aspect" for v in t["values"]}
    emap = eco_map()
    with ThreadPoolExecutor(max_workers=6) as ex:
        eco_hits = dict(zip(emap, ex.map(lambda e: hits(f"evidenceCode={e}&evidenceCodeUsage=exact"), emap)))
        ref_hits = dict(zip(PIPELINES, ex.map(lambda r: hits(f"reference={r}"), PIPELINES)))
    by_code = {}
    for e, n in eco_hits.items():
        by_code[emap[e]] = by_code.get(emap[e], 0) + n
    data = {
        "source": "QuickGO annotation search/stats API (live UniProt-GOA)",
        "fetched": datetime.date.today().isoformat(),
        "total_annotations": total,
        "by_aspect": aspect,
        "by_go_evidence_code": dict(sorted(by_code.items(), key=lambda kv: -kv[1])),
        "unmapped_residual": total - sum(by_code.values()),
        "by_go_ref": ref_hits,
        "eco_codes_queried": len(emap),
        "note": "Counts summed from exact ECO matches using ECO->GO pairs seen in local GOA files; "
                "the residual covers ECO codes absent locally and drift between live queries.",
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("# generated by paper/scripts/fetch_goa_counts.py -- do not edit\n")
        yaml.safe_dump(data, fh, sort_keys=False)
    print(yaml.safe_dump({k: data[k] for k in ("total_annotations", "unmapped_residual", "by_go_ref")}, sort_keys=False))

if __name__ == "__main__":
    main()
