"""The standalone pathway-satisfiability demo stays import-free and in sync.

``projects/PATHWAY_SATISFIABILITY/demo_standalone.py`` is generated by
``build_standalone_demo.py`` so that it runs under ``uvx marimo run`` and in a
WebAssembly export, where ``ai_gene_review`` is not installed. These tests keep
that contract in CI, and keep the committed file from drifting from the engine
it inlines.
"""

from __future__ import annotations

import ast
import importlib.util
import sys
from pathlib import Path

DEMO_DIR = Path(__file__).resolve().parents[1] / "projects" / "PATHWAY_SATISFIABILITY"
DEMO = DEMO_DIR / "demo_standalone.py"


def _top_level_modules(source: str) -> set[str]:
    modules: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Import):
            modules.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            modules.add(node.module.split(".")[0])
    return modules


def test_demo_imports_only_the_standard_library_and_marimo():
    source = DEMO.read_text()
    assert "ai_gene_review" not in source
    assert _top_level_modules(source) - set(sys.stdlib_module_names) == {"marimo"}


def test_committed_demo_matches_a_fresh_build():
    """Regenerate with ``uv run python projects/PATHWAY_SATISFIABILITY/build_standalone_demo.py``."""
    spec = importlib.util.spec_from_file_location("build_standalone_demo", DEMO_DIR / "build_standalone_demo.py")
    assert spec and spec.loader
    build = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(build)
    assert build.NOTEBOOK == DEMO.read_text()
